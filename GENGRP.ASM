; TITLE   GENGRP  GENERALIZED GRAPHICS    /WHG

@GENGRP@_CLIPPL=0
@GENGRP@_WINDOW=0
@GENGRP@_VIEW=0
@GENGRP@_TILE=0
@GENGRP@_HAL=0
@GENGRP@_PC8A=0
@GENGRP@_MODEL3=0
@GENGRP@_TSHIBA=0
@GENGRP@_ALPCPM=0
@GENGRP@_HALL4=0
	@GENGRP@_CLIPPL=@GENGRP@_PC8A OR @TRSER2 OR @GENGRP@_MODEL3
	@GENGRP@_WINDOW=@GENGRP@_PC8A
	@GENGRP@_VIEW=@GENGRP@_PC8A OR @TRSER2 OR @GENGRP@_MODEL3
