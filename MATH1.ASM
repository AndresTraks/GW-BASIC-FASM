@STROUT:  ;fetch from code segment
	MOV	AL,byte [cs:BX+0]  ;get char
	INC	BX  ;point at next one
	OR	AL,AL  ;end of string?
	JNZ	@MATH1@_STOULP  ;no print char until done
	RET
@@SDZERO:  ;DOUBLE PRECISION ZERO
	MOV	DI,@@SDFACL
	MOV	CX,4
	MOV	AX,0
	CLD
 REP	STOSW
	RET

@ZERO:
@MATH1@_@SZERO:  ;ZERO THE FAC
