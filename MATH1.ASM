	RET

@SIGN:
@@SSIGNS:  ;DETERMINE SIGN OF FAC
;ZF=1 IF ($FAC)=0, SF=1 IF ($FAC) .LT.0, NEITHER OF
;THESE FLAGS SET IF ($FAC).GT.0
	CALL	@@SGETYP  ;IF NOT INTEGER CAN LOOK AT FAC:FAC-1
	JNE	@MATH1@_SIS01
	JMP	@TMERR  ;Strings illegal 9-Mar-82/ngt
@MATH1@_SIS01:
	JNS	@MATH1@_SIS05  ;NOT INTEGER PROCEED
	MOV	AX,word [@@SFACLO]  ;FETCH INTEGER
	OR	AX,AX  ;DETERMINE SIGN
	JZ	@MATH1@_SIS10
	MOV	AL,((1) and 0FFh)
	JNS	@MATH1@_SIS10
	NEG	AL
	RET
@MATH1@_SIS05:
	MOV	AL,byte [@@SFAC]  ;FIRST CHECK FOR ZERO
	OR	AL,AL
	JZ	@MATH1@_SIS10  ;IF ZERO JUST RETURN
	MOV	AL,byte [@@SFAC-1]  ;FETCH SIGN BYTE
@MATH1@_SIGNAL: OR	AL,AL  ;SIGNSET NOW
	JZ	@MATH1@_SIS07  ;MUST MAKE AL=1 AND ZF=0
	MOV	AL,((1) and 0FFh)
	JNS	@MATH1@_SIS10
	NEG	AL
	RET
@MATH1@_SIS07:	OR	AL,((1) and 0FFh)  ;KNOW POSITIVE NON-ZERO
@MATH1@_SIS10:	RET

; Set cond. codes according to type value.
;   S, C = Integer
;   Z, C = String
;      C = Single Precision
;   None = Double Precision

@@SGETYP:
	MOV	AL,byte [@@SVALTP]  ;FETCH TYPE VARIABLE
	CMP	AL,((8) and 0FFh)  ;CF=1 EXCEPT FOR DOUBLE PREC.
	DEC	AL  ;WILL SUBTRACT 3 WITH DECBREMENTS
	DEC	AL
	DEC	AL
	RET  ;ZF=1 IF STRING,SF=1 IF INTEGER
;PO=1 IF SINGLE PREC

@MATH1@_@SVADDH:  ;ADD .5 ACCORDING TO TYPE
	CALL	@@SGETYP  ;SET CODES ACCORDING TO TYPE
	JB	@MATH1@_@SFADDH
@MATH1@_@SDADDH:  ;DOUBLE PRECISION ADD .5
	PUSH	BX
	MOV	BX,@MATH1@_@SDHALF
	CALL	@MATH1@_@SMOVAC  ;MOVE TO ARG
	CALL	@MATH1@_@SFADDD  ;ADD TO FAC
	POP	BX
	RET
@MATH1@_@SFADDH:  ;SINGLE PRECISION ADD .5
	XOR	DX,DX  ;WILL SET (BXDX)=.5
	MOV	BX,32768
	CALL	@@SFADDS  ;ADD .5 TO FAC
	RET
@MATH1@_@SDIV10:  ;DIVIDE FAC BY 10
	CALL	@@SGETYP
	MOV	BX,@MATH1@_@SDPM01  ;ADDRESS .1
	JB	@MATH1@_ML10
	JMP	@MATH1@_ML05  ;MULTIPLY

@MATH1@_@SMUL10:  ;MULTIPLY THE FAC BY 10
	CALL	@@SGETYP  ;SEE IF SINGLE OR DOUBLE PREC
	MOV	BX,@MATH1@_@SDP01  ;ADDRESS OF DOUBLE PREC 10.
	JB	@MATH1@_ML10  ;JUMP IF SINGLE
@MATH1@_ML05:	CALL	@MATH1@_@SMOVAC  ;MOVE 10. TO ARG
	CALL	@MATH1@_@SFMULD  ;MULTIPLY
	RET
@MATH1@_ML10:  ;MULTIPLY SINGLE PREC. FAC BY NO. POINTED TO BY BX
@MATH1@_@SMLSP:
	PUSH	word [@@SFACM1]  ;PUSH FAC ON THE STACK
	PUSH	word [@@SFACLO]
	MOV	byte [@@SVALTP],((8) and 0FFh)  ;SET UP D.P.
	CALL	@MATH1@_@SMOVFC  ;MOVE DOUBLE PREC. 10 TO FAC
	CALL	@@SCSD  ;CONVERT TO SINGLE PRECISION
	POP	DX  ;GET LOW MANTISSA BITS
	POP	BX  ;EXP SIGN AND HIGH MATISSA BITS
	CALL	@@SFMULS  ;MULTIPLY
	RET

@MATH1@_@SRDL:	MOV	CX,4  ;WILL SHIFT 4 WORDS LEFT
@MATH1@_RDL120: RCL	word [BX+0],1  ;SHIFT  LEFT 1 BIT SHIFTING IN CF
	INC	BX
	INC	BX
	LOOP	@MATH1@_RDL120
	RET
@MATH1@_@SSHDR:	MOV	CX,4  ;DO DOUBLE PRECISION RIGHT SHIFT
@MATH1@_@SSHRM:  ;SHIFT NO. POINTED TO BY (BX) , (CX) WDS RT.
	RCR	word [BX+0],1  ;SHIFT 1 WD. RT. THRU CF
	DEC	BX
	DEC	BX  ;TO NEXT WD.
	LOOP	@MATH1@_@SSHRM  ;DO THIS (CX) TIMES
	RET
@MATH1@_SHST:	OR	byte [BX+2],((32) and 0FFh)  ;"OR" IN ST BIT
	LOOP	@MATH1@_@SSHRA
	RET
@MATH1@_@SSHRA:  ;SHIFT $ARG RIGHT (CX) BITS
	MOV	BX,@@SARG-2
	CMP	CL,((8) and 0FFh)  ;CAN I DO A BYTE MOVE
	JB	@MATH1@_SHRA30  ;IF NOT PROCEED AS NORMAL
;*************************************************************
;FOR SPEED PURPOSES WE WILL DO A BYTE MOVE TO THE RIGHT
;*************************************************************
	PUSH	CX  ;SAVE BITS TO SHIFT
	MOV	CX,7  ;7 BYTE MOVE
	MOV	BX,@@SARGLO-1
	MOV	AH,byte [BX+0]  ;FETCH OVERFLOW BYTE
@MATH1@_SHRA11: MOV	AL,byte [BX+1]
	MOV	byte [BX+0],AL
	INC	BX
	LOOP	@MATH1@_SHRA11
	XOR	AL,AL
	MOV	byte [BX+0],AL
	POP	CX  ;RECALL BIT COUNT
	SUB	CL,((8) and 0FFh)
	AND	AH,((32) and 0FFh)  ;WILL NEED TO RE-ESTABLISH ST
	JZ	@MATH1@_@SSHRA  ;NO-ST JUST PROCEED
	OR	byte [@@SARGLO-1],AH
	JMP	@MATH1@_@SSHRA
@MATH1@_SHRA30:
	OR	CL,CL
	JZ	@MATH1@_SHRA40  ;JUMP IF DONE
	PUSH	CX  ;SAVE NO. BITS TO SHIFT
	CLC  ;DON'T WANT THE CARRY SHIFTED IN
	CALL	@MATH1@_@SSHDR
	POP	CX
	TEST	byte [BX+2],((16) and 0FFh)  ;SEE IF SHIFTED THRU "ST"
	JNZ	@MATH1@_SHST  ;MUST "OR" ST BIT IN IF NON-ZERO
	LOOP	@MATH1@_@SSHRA
@MATH1@_SHRA40: RET

@MATH1@_@SXCGAF: MOV	SI,@@SDFACL  ;WILL EXCHANGE FAC AND ARG (D.P.)
	MOV	DI,@@SARGLO
	CLD  ;SO MOVW WILL INCREMENT INDICES
	MOV	CX,4  ;WILL MOVE 4 WORDS (8 BYTES)
@MATH1@_XCG10:	MOV	AX,word [DI+0]  ;FETCH DESTINATION WORD
	MOVSW  ;MOVE FAC TO ARG & INCREMENT INDICES
	MOV	word [SI-2],AX  ;ARG TO FAC
	LOOP	@MATH1@_XCG10  ;CONTINUE
	RET

;*********************************************************************
;       SPECIAL MOVE ROUTINES FOR HANDLING CONSTANTS FROM THE CODE
;       SEGMENT
;*********************************************************************
@MATH1@_@SMOVBS:  ;THIS ROUTINE IS USED TO MOVE A SINGLE PRECISION NO. FROM THE
;CODE SEGMENT TO $DBUFF. THE NO. IS POINTED TO BY (BX)
	MOV	DI,@@SDBUFF+4
	MOV	CX,2
	JMP	@MATH1@_MBF10
@MATH1@_@SMOVBF:  ;THIS ROUTINE IS USED TO MOVE A DOUBLE PRECISION NO. FROM THE
;CODE SEGMENT TO $DBUFF. THE NO. IS POINTED TO BY (BX)
	MOV	DI,@@SDBUFF
@MATH1@_MBF05:	MOV	CX,4
@MATH1@_MBF10:	CLD
	MOV	SI,BX  ;SO WE CAN USE A LODW
@MATH1@_MBF20:
	lodsw  ;FETCH FROM CS
	STOSW  ;STORE IN DBUFF
	LOOP	@MATH1@_MBF20  ;CONTINUE WITH MOVE
	MOV	BX,DI  ;UPDATE (BX)
	SUB	BX,2  ;GET POINTER CORRECT
	RET

@MATH1@_@SMOVAC:  ;ROUTINE TO MOVE A DOUBLE PRECISION NO. POINTED TO BY (BX)
;FROM THE CODE SEGMENT TO ARG
	MOV	DI,@@SARGLO
	JMP	@MATH1@_MBF05

@MATH1@_@SMOVFC:  ;ROUTINE USED TO MOVE A DOUBLE PRECISION NO. FROM THE CODE
;SEGMENT TO THE FAC. NO. IS POINTED TO BY (BX)
	MOV	DI,@@SDFACL
	JMP	@MATH1@_MBF05

@MATH1@_MOVAM:  ;MOVE NO. POINTED TO BY BX TO ARG
	MOV	DI,@@SARGLO  ;LOW ADDRESS OF ARG
	MOV	CX,4  ;MOVE DOUBLE PREC NO. POINTED TO
;BY (BX) TO DOUBLE PREC NO. POINTED TO
;BY (DI)
@MATH1@_MOVEM:  ;MOVE NO. POINTED TO BY (BX) TO NO. POINTED TO BY (DI)
;FOR (CX) WORDS
	XCHG	BX,SI  ;SO MOVW CAN BE USED
	CLD  ;SO MOVW WILL INC
;DO MOVE (CX) TIMES
 REP	MOVSW  ;MOVE "FROM" TO "TO"
	XCHG	BX,SI  ;GET REGISTERS STRAIGHT
	RET

@MATH1@_@SMOVAF:  ;MOVE THE $FAC TO $ARG
	PUSH	CX  ;SAVE CX,BX,DI
	PUSH	BX
	PUSH	DI
	MOV	BX,@@SDFACL  ;"FROM" ADDRESS
	MOV	DI,@@SARGLO  ;"TO" ADDRESS
@MATH1@_MAF05:	MOV	CX,4  ;4 16-BIT QUANTITIES TO MOVE
	CALL	@MATH1@_MOVEM  ;DO THE MOVE
	POP	DI
	POP	BX
	POP	CX  ;REGISTERS RESTORED
	RET

@@SMOVFA:  ;MOVE THE $ARG TO THE FAC
	PUSH	CX
	PUSH	BX
	PUSH	DI  ;SAVE REGISTERS
	MOV	BX,@@SARGLO  ;"FROM" ADDRESS
	MOV	DI,@@SDFACL  ;"TO" ADDRESS
	JMP	@MATH1@_MAF05  ;GO MOVE
;**************************************************************
;SINGLE PRECISION MOVE ROUTINES
;***************************************************************
@@SMOVFR:  ;MOVE (BXDX) TO FAC
	MOV	word [@@SFACLO],DX
	MOV	word [@@SFAC-1],BX
	RET

@@SMOVRF:  ;MOVE THE FAC INTO REGISTERS (BXDX)
	MOV	DX,word [@@SFACLO]
	MOV	BX,word [@@SFAC-1]
	RET

; ZCMPCK is called by the comparison routines to handle the
; cases where the exponent of either or both of the numbers
; is zero.  These must be treated as special cases because
; a number whose exponent is zero is zero regardless of the
; garbage that might be in the mantissa.

; On entry -    BH=exponent of comperand
;               Bit 7 of BL=sign of comperand

; On exit -     Carry clear - caller must continue comparison.

;               Carry set - comparison is finished.
;               A=1, Z=0, S=0 for FAC .GT. comperand
;               A=0, Z=1 for FAC .EQ. comperand
;               A=377 octal, Z=0, S=1 for FAC .LT. comperand

@MATH1@_ZCMPCK: OR	BH,BH  ;Is the comperand zero?
	JNZ	@MATH1@_NZCOMP  ;No.
	CALL	@MATH1@_SIS05  ;Yes, result is the sign of the FAC.
	STC  ;Set carry to say comparison is done
	RET  ;and return.

@MATH1@_NZCOMP: MOV	AL,byte [@@SFAC]  ;Is the FAC zero?
	OR	AL,AL  ;(Also clear carry.)
	JNZ	@MATH1@_ZCMPRT  ;No, return with carry clear to tell
;the caller he must continue.
	MOV	AL,BL  ;Yes, the result is the opposite
	NOT	AL  ;of the sign of the comperand.
	CALL	@MATH1@_SIGNAL
	STC  ;Set carry to say comparison is
@MATH1@_ZCMPRT: RET  ;finished and return.

; ZCMPBX performs the special zero check for the case where
; BX points to the comperand.

@MATH1@_ZCMPBX: PUSH	BX  ;Preserve the comperand pointer.
	MOV	BX,word [BX+0]  ;BH:=exponent, BL bit 7:=sign for
;ZCMPCK.
	CALL	@MATH1@_ZCMPCK  ;Check for the zero cases.
	POP	BX  ;Retrieve the comperand pointer
	RET  ;and return.

@MATH1@_@SVCOMP:  ;DETERMINE IF SINGLE OR DOUBLE PRECISION AND COMPARE ACCORDINGLY
	CALL	@@SGETYP  ;SET CODES ACCORDING TO TYPE
	JB	@MATH1@_@SCOMPM  ;DO S.P. COMPARE
	JMP	@MATH1@_@SDCMPM  ;GO DO D.P. COMPARE

@@SFCOMP:  ;SINGLE PRECISION COMPARE OF ($FAC) AND (BXDX)
;(AL)=1 AND ZF=0,SF=0,CF=0 IF ($FAC).GT.(BXDX)
;(AL)=0 AND ZF=1 IF ($FAC)=(BXDX)
;(AL)=377 AND ZF=0,SF=1,CF=1 IF ($FAC).LT.(BXDX)

	CALL	@MATH1@_ZCMPCK  ;Check for zero exponent cases.
	JB	@MATH1@_ZEREXP  ;All done if carry set.
	PUSH	BX
	PUSH	DI
	MOV	AL,BL  ;SIGN OF (BXDX) TO (AL)
	XOR	AL,byte [@@SFAC-1]  ;SET CODES FOR SIGNS
	JS	@MATH1@_CPM05
	OR	BL,BL
	JS	@MATH1@_UFC10  ;NEGATIVE NOS.
	MOV	AX,word [@@SFAC-1]  ;SIGNS SAME MUST COMPARE
	SUB	AX,BX  ;SUBTRACT HIGH WORD
	JB	@MATH1@_CPM10  ;($FAC) SMALLER
	JNZ	@MATH1@_CPM06  ;($FAC) LARGER
	MOV	AX,word [@@SFACLO]  ;MUST COMPARE LOW WORD
	SUB	AX,DX
	JMP	@MATH1@_TSTFLG  ;return comparison result based on flags
@MATH1@_UFC10:	MOV	AX,BX  ;SINCE NEGATIVE LARGER MAGNITUDE IS
	SUB	AX,word [@@SFAC-1]  ;SMALLER NO.
	JB	@MATH1@_CPM10
	JNZ	@MATH1@_CPM06  ;(BXDX) SMALLER
	MOV	AX,DX  ;MUST COMPARE LOW WORD
	SUB	AX,word [@@SFACLO]
@MATH1@_TSTFLG: JB	@MATH1@_CPM10  ;branch if FAC is smaller than comperand
	JNZ	@MATH1@_CPM06  ;branch if FAC is larger than comperand
	XOR	AL,AL  ;FAC is equal to comperand
	JMP	@MATH1@_CPM80

;One of the exponents was zero (meaning the number=0).
; Set Carry flag if [AL]=377 (if FAC is less than comperand)

@MATH1@_ZEREXP: INC	AL  ;Map AL from (377, 0, 1) to (0, 1, 2)
	SUB	AL,((1) and 0FFh)  ;Map it back, setting Flags appropriately
	RET

@MATH1@_@SCOMPM:  ;COMPARE FAC TO NUMBER POINTED TO BY (BX)
;       (BX) MUST BE POINTING TO SIGN BYTE OF NO.
;SET (AL)=1,ZF=0,SF=0,CF=0 IF (FAC).GT.[BX]
;    (AL)=0,ZF=1 IF (FAC)=[BX]
;    (AL)=377,ZF=0,SF=1,CF=1 IF (FAC).LT.[BX]

	CALL	@MATH1@_ZCMPBX  ;Check for zero exponent cases.
	JB	@MATH1@_ZEREXP  ;All done if carry set.
	PUSH	BX  ;SAVE INITIAL ADDRESS
	PUSH	DI  ;SAVE DI
	MOV	DI,@@SFAC-1
	MOV	AX,word [BX+0]  ;FETCH SIGN BYTE INTO AL
	XOR	AL,byte [@@SFAC-1]  ;SF=1 IF SIGNS DIFFERENT
	JNS	@MATH1@_CPM20
;*****************************************************************
;SIGNS ARE DIFFERENT , THE ONE WITH POS. SIGN IS BIGGER
;******************************************************************
@MATH1@_CPM05:	MOV	AH,byte [@@SFAC-1]  ;FETCH FAC SIGN
	OR	AH,AH
	JS	@MATH1@_CPM10  ;FAC IS SMALLER MUST SET (AL)=377
@MATH1@_CPM06:	MOV	AL,((1) and 0FFh)
	OR	AL,AL  ;MIGHT HAVE GOTTEN A ZF=1 ON LAST "OR"
	JMP	@MATH1@_CPM80
@MATH1@_CPM10:	MOV	AL,((255) and 0FFh)  ;KNOW SF=1
	STC  ;WANT CF=1 IF FAC SMALLER
	JMP	@MATH1@_CPM80
@MATH1@_CPM20:
;******************************************************************
;SIGNS ARE THE SAME MUST DO ACTUAL COMPARE
;******************************************************************
	PUSH	CX  ;WILL USE (CX) FOR LOOP CONTROL
	MOV	CX,2
@MATH1@_CPM22:	XCHG	BX,SI  ;SO CMPW CAN BE USED
	MOV	AL,byte [@@SFAC-1]  ;IF NEGATIVE NO. NEED TO REVERSE CMP
	OR	AL,AL
	JNS	@MATH1@_CPM25
	XCHG	SI,DI  ;WILL CAUSE CORRECT COMPARE FOR NEG.
@MATH1@_CPM25:
	STD  ;SO CMPW WILL DECREMENT
@MATH1@_CPM30:	CMPSW  ;FORM CODES FOR (.SI)-(.DI)
	JNZ	@MATH1@_CPM50
	LOOP	@MATH1@_CPM30  ;CONTINUE THRU VALUES
	MOV	AL,((0) and 0FFh)  ;ZF=1 ALREADY SET
	JMP	@MATH1@_CPM70
@MATH1@_CPM50:	JNB	@MATH1@_CPM60  ;MEMORY VALUE LARGER
	MOV	AL,((1) and 0FFh)  ;FAC LARGER SF=0,ZF=0
	OR	AL,AL
	JMP	@MATH1@_CPM70
@MATH1@_CPM60:  ;MEMORY IS LARGER MUST SET SF=1 AND (AL)=377
	MOV	AL,((255) and 0FFh)
	OR	AL,AL
	STC  ;WANT CF=1 IF MEMORY VALUE LARGER
@MATH1@_CPM70:	POP	CX  ;RESTORE CX REGISTER
@MATH1@_CPM80:
	POP	DI
	POP	BX
	RET

@@SDCMPA:  ;DOUBLE PRECISION COMPARE OF ($FAC) AND ($ARG)
	MOV	BX,@@SARG-1

@MATH1@_@SDCMPM:  ;DOUBLE PRECISION COMPARE OF ($FAC) AND ((BX))
;(AL)=1 AND ZF=0,SF=0,CF=0 IF ($FAC).GT.((BX))
;(AL)=0 AND ZF=1 IF ($FAC)=((BX))
;(AL)=377 AND ZF=0,SF=1,CF=1 IF ($FAC).LT.((BX))

	CALL	@MATH1@_ZCMPBX  ;Check for zero exponent cases.
	JB	@MATH1@_ZEREXP  ;All done if carry set.
	PUSH	BX
	PUSH	DI  ;SAVE REGISTERS
	MOV	DI,@@SFAC-1  ;D.P. HIGH FAC WORD
	MOV	AL,byte [DI+0]  ;WILL FIRST SEE IF SIGNS DIFFERENT
	XOR	AL,byte [BX+0]
	JNS	@MATH1@_DC10  ;PROCEED IF NOT DIFFERENT
	JMP	@MATH1@_CPM05  ;SIGNS DIFFERENT SET CODES ACCORDINGLY
@MATH1@_DC10:	PUSH	CX
	MOV	CX,4  ;FOUR WORDS TO COMPARE
	JMP	@MATH1@_CPM22  ;GO COMPARE

@MATH1@_@SCONI2:  ;CHECK FAC FOR -32768 SINGLE PRECISION AND IF
;EQUAL CONVERT TO INTEGER
	MOV	BX,@MATH1@_@SS32KM  ;ADDRESS OF S.P. -32768
	CALL	@MATH1@_@SMOVBS  ;MOVE IT OUT TO DBUFF FOR COMPARISON
	CALL	@MATH1@_@SCOMPM  ;ONLY INTERESTED IN ZF
	JNZ	@MATH1@_CON10  ;IF NOT EQUAL JUST RETURN
	MOV	byte [@@SVALTP],((2) and 0FFh)  ;TO INDICATE INTEGER
	MOV	word [@@SFACLO],128*256  ;-32768
@MATH1@_CON10:	RET

@MATH1@_@SRSUBM:  ;SUBTRACT NO POINTED TO BY (BP) FROM (BLDX)
;NUMBER POINTED TO BY (BP) IS PRESUMED TO BE IN
;THE CODE SEGMENT
	SUB	DX,word [cs:BP+0]  ;FIRST 16 BITS
	SBB	BL,byte [cs:BP+2]
	RET  ;COND. FLAGS ALL SET

;*********************************************************
;THE "V" UTILITIES FOLLOW. THESE UTILITIES HAVE ONE THING IN
;COMMON: THEY MUST FIRST ASCERTAIN WHAT TYPE OF VARIABLE
;THEY ARE TO WORK ON BEFORE PERFORMING THEIR TASK.
;************************************************************
@ABSFN:
@MATH1@_@SVABS:  ;ABSOLUTE VALUE ROUTINE
	CALL	@@SGETYP  ;SEE WHAT TYPE VARIABLE
	JS	@MATH1@_@SIABS  ;IF INTEGER PROCEED
	MOV	AL,byte [@@SFAC-1]
	OR	AL,AL  ;SEE IF CURRENTLY NEGATIVE
	JS	@@SNEG  ;AND IF SO NEGATE
	RET
@MATH1@_@SIABS:	MOV	AX,word [@@SFACLO]  ;FETCH INTEGER
	OR	AX,AX  ;AND SEE IF ALREADY POS.
	JS	@MATH1@_VN15
	RET  ;RETURN IF POSITIVE

@VNEG:
@MATH1@_@SVNEG:  ;NEGATE THE VALUE IN THE FAC
	CALL	@@SGETYP  ;SET COND. CODES ACCORDING TO TYPE
	JS	@MATH1@_@SINEG  ;IT'S INTEGER MUST COMPLEMENT
;************************************************************
;IT'S SINGLE OR DOUBLE PRECISION MUST FLIP THE SIGN BIT
;************************************************************
@NEG:
@@SNEG:
	XOR	byte [@@SFAC-1],((128) and 0FFh)  ;FLIP SIGN OF FAC
	RET
@INEG:
@MATH1@_@SINEG:	MOV	AX,word [@@SFACLO]  ;WILL CHECK FOR -32768
@MATH1@_VN15:	CMP	AX,32768  ;SEE IF -32768
	JNZ	@MATH1@_VN20  ;IF NOT JUST NEGATE
	PUSH	BX  ;PRESERVE BX
	CALL	@@SCSI  ;CONVERT TO SINGLE PRECISION
	POP	BX  ;RECALL BX
	JMP	@@SNEG  ;GO NEGATE
@MATH1@_VN20:	NEG	word [@@SFACLO]  ;NEGATE
	RET

@MATH1@_@SSETDB:  ;MOVE FAC TO DBUFF FOR MULT. AND ZERO FAC
	MOV	BX,@@SDBUFF+1
	CALL	@MATH1@_@SVMVMF  ;MOVE FAC TO DBUFF
	MOV	DI,@@SDFACL-8  ;WILL NOW ZERO 16 BYTES OF FAC
	MOV	CX,8
	MOV	AX,0
	CLD
 REP	STOSW  ;STORES (AX) INTO LOCATIONS
	MOV	byte [@@SDBUFF],AL  ;ZERO OVERFLOW BYTE
	MOV	byte [@@SARGLO-1],AL  ;ZERO OVERFLOW BYTE OF ARG
	RET

@MATH1@_@SVMVAM:  ;MOVE THE VALUE POINTED TO BY (BX) TO (BXDX) IF SINGLE
;PRECISION, TO $ARG IF DOUBLE PRECISION
	CALL	@@SGETYP  ;SET CODES ACCORDING TO TYPE
	JB	@MATH1@_VM10  ;JUMP IF SINGLE PRECISION
	JMP	@MATH1@_MOVAM  ;MOVE THE VALUE TO THE ARG
@MATH1@_VM10:	MOV	DX,word [BX+0]  ;FETCH LOW MANTISSA BITS
	MOV	BX,word [BX+2]  ;FETCH HIGH MANTISSA AND EXPONENT
	RET

@MATH1@_@SVMOVM:  ;MOVE THE VARIABLE POINTED TO BY (BX) TO THE ONE POINTED
;TO BY (DI)
	MOV	CX,4  ;ASSUME DOUBLE PRECISION
	CALL	@@SGETYP
	JB	@MATH1@_VMM10  ;IT'S SINGLE PREC JUMP
	JMP	@MATH1@_MOVEM  ;GO DO MOVE
@MATH1@_VMM10:	MOV	CX,2
	JMP	@MATH1@_MOVEM  ;GO DO MOVE

@MATH1@_@SVMVMF:  ;MOVE THE FAC TO THE NO. POINTED TO BY (BX)
	MOV	CX,4  ;ASSUME DOUBLE PREC.
	XCHG	DI,BX  ;(DI)=DESTINATION,(BX)=ORIGIN
	MOV	BX,@@SDFACL
	CALL	@@SGETYP  ;SET COND. CODES ACCORDING TO $VALTP
	JB	@MATH1@_VMVM1  ;JUMP IF S.P.
	JMP	@MATH1@_MOVEM  ;GO DO MOVE
@MATH1@_VMVM1:	XCHG	BX,DI
@@SMOVMF: MOV	CX,2
	MOV	DI,@@SFACLO
	XCHG	DI,BX
	JMP	@MATH1@_MOVEM  ;GO DO MOVE

@MATH1@_@SVMVFM:  ;MOVE TO FAC THE NO POINTED TO BY (BX)
	MOV	CX,4  ;ASSUME DOUBLE PREC
	MOV	DI,@@SDFACL
	CALL	@@SGETYP
	JB	@@SMOVFM
	JMP	@MATH1@_MOVEM
@@SMOVFM: MOV	CX,2
	MOV	DI,@@SFACLO
	JMP	@MATH1@_MOVEM  ;GO DO MOVE

@MATH1@_@SVCMPM:  ;COMPARE FAC TO NO. POINTED TO BY (BX)
	CALL	@@SGETYP
	JB	@MATH1@_VCMP10
	JMP	@MATH1@_@SDCMPM  ;DO DOUBLE PREC COMPARE
@MATH1@_VCMP10: JMP	@MATH1@_@SCOMPM  ;SINGLE PREC COMPARE

@@SVPSHF:  ;PUSH THE FAC ON THE STACK ACCORDING TO TYPE
	CALL	@@SGETYP  ;SET COND CODES ACCORDING TO $VALTP
	MOV	CX,4  ;FOR DOUBLE PRECISION
	JNB	@MATH1@_VPS10  ;IF DOUBLE PREC PROCEED
@MATH1@_@SPUSHF:  ;PUSH SINGLE PRECISION FAC ON THE STACK
	MOV	CX,2
@MATH1@_VPS10:	POP	BP  ;GET RETURN ADDRESS OFF STACK
	MOV	DI,@@SFAC-1
@MATH1@_VPS20:	PUSH	word [DI+0]
	DEC	DI
	DEC	DI
	LOOP	@MATH1@_VPS20
	PUSH	BP  ;GET RETURN ADDRESS RIGHT
	RET  ;AND RETURN
@@SPOPA:  ;POP STACK INTO ARG
	MOV	DI,@@SARGLO
	MOV	CX,4
	JMP	@MATH1@_VPO17
@MATH1@_@SVPOPF:  ;POP EITHER 4 OR 8 BYTES OFF THE STACK
	CALL	@@SGETYP  ;SET CODES ACCORDING TO $VALTP
	MOV	DI,@@SDFACL
	MOV	CX,4
	JNB	@MATH1@_VPO17  ;JUMP IF DOUBLE PRECISION
	MOV	DI,@@SFACLO
	MOV	CX,2
@MATH1@_VPO17:	POP	AX  ;GET RETURN ADDRESS OFF STACK
@MATH1@_VPO20:	POP	word [DI+0]
	INC	DI
	INC	DI
	LOOP	@MATH1@_VPO20
	PUSH	AX  ;PUSH RETURN ADDRESS ON STACK
	RET
@VINT:
@@SVINT:  ;DO INT ACCORDING TO TYPE (SINGLE OR DOUBLE PRECISION)
	CALL	@@SGETYP  ;SET CODES ACCORDING TO TYPE
	JNS	@MATH1@_VIN05
	RET  ;RETURN IF INTEGER ALREADY
@MATH1@_VIN05:
	JB	@MATH1@_VIN10  ;JUMP IF SINGLE PRECISION
	JMP	@MATH1@_@SDINT  ;GO DO DOUBLE PRECISION
@MATH1@_VIN10:	JMP	@MATH1@_@SINT

; SUBTTL	 $FIN	 NUMERIC INPUT ROUTINE
;****************************************************************

;       $FIN    GIVEN A TEXT POINTER, $FIN WILL BUILD AN INPUT
;               NUMBER IN THE FAC. AS NECESSARY (OR IF FORCED)
;               $FIN WILL GO TO NEXT HIERARCHY OF NUMBERS
;               I.E. TRANSITIONS FROM INTEGER-SINGLE PRECISION-
;               DOUBLE PRECISION CAN EITHER BE FORCED OR DICTATED
;               BY THE INPUT NUMBERS.
;       CALLING         SEQUENCE:       CALL    $FIN
;               WITH (BX) POINTING TO TEXT CONTAINING THE NUMBER
;               TO BE CONVERTED FROM ASCII.

;******************************************************************

@FIN:
@MATH1@_@SFIN:	XOR	AL,AL  ;LET INPUT NUMBER DETERMINE TYPE
	JMP	@MATH1@_FN20
@FINDBL:
@MATH1@_@SFINDB:  ;FORCE DOUBLE PRECISION ENTRY POINT
	MOV	AL,((1) and 0FFh)  ;FLAG TO INDICATE D.P.
	MOV	byte [@@SVALTP],((8) and 0FFh)  ;SET TO DOUBLE PRECISION
@MATH1@_FN20:
	MOV	byte [@@SFLGOV],((1) and 0FFh)  ;SET ONCE-ONLY OVERFLOW MODE
	MOV	SI,@@SFLGOC  ;ADDRESS OF INPUT OVERFLOW CODE
	PUSH	SI  ;PUSH ON STACK SO RETURN IS HERE
	XOR	DI,DI  ;DIGITS PAST DECIMAL POINT
	MOV	CX,DI  ;DECIMAL POINT FLAG
	MOV	SI,DI  ;(SI) WILL FLAG POS/NEG EXPONENT
	NOT	CX  ;SET ALL BITS
	PUSH	AX
	CALL	@MATH1@_@SZERO  ;(FAC)=0
	POP	AX
	OR	AL,AL  ;MUST SEE IF $VALTP SHOULD START AT
	JNZ	@MATH1@_FN30  ;INTEGER OR NOT.
	MOV	byte [@@SVALTP],((2) and 0FFh)  ;SET TO INTEGER
@MATH1@_FN30:	MOV	AL,byte [BX+0]  ;FETCH 1ST CHARACTER FROM TEXT
	CMP	AL,(("&") and 0FFh)  ;SIGNIFIES SPECIAL INPUT NO.
	JNZ	@MATH1@_FN40  ;IF NOT, PROCEED
	JMP	@@SOHCNS  ;OTHERWISE GO PROCESS OCT. OR HEX
@MATH1@_FN40:	CMP	AL,(("-") and 0FFh)  ;NEGATIVE NUMBER?
	PUSHF  ;WILL SAVE ZF FOR POSSIBLE NEGATION
	JZ	@MATH1@_FN50  ;ONCE NUMBER IS FORMED POSITIVE
	CMP	AL,(("+") and 0FFh)  ;NEED TO ADVANCE TEXT POINTER FOR
	JZ	@MATH1@_FN50  ;LEADING SIGN
	DEC	BX
@MATH1@_FN50:	CALL	@MATH1@_@SCHRGT  ;GET NEXT CHARACTER OF NUMBER
	JNB	@MATH1@_FN60  ;IF NOT DIGIT GO EXAMINE FURTHER
@MATH1@_FN55:	CALL	@MATH1@_@SFIDIG  ;MUL FAC BY TEN AND ADD IN THE DIGIT
	JMP	@MATH1@_FN50
@MATH1@_FN60:
	MOV	BP,@MATH1@_@SFINCH+7
	XOR	DX,DX  ;MUST SET EXPONENT TO ZERO
	MOV	SI,DX  ;FOR SUBSEQUENT CALL TO FINE
@MATH1@_FN70:
	CMP	AL,byte [cs:BP+0]  ;CODE SEGMENT
	JZ	@MATH1@_FN80  ;FOUND SPEC CH (.,D,D+40,!,#,%,E,E+40)
	CMP	BP,@MATH1@_@SFINCH  ;IF EQUAL NONE OF THE SPECIAL CHARS.
	JZ	@MATH1@_FN96  ;GO FNISH UP NUMBER NON-RECOG. CHAR.
	DEC	BP  ;PROCEED TO NEXT CHARACTER
	JMP	@MATH1@_FN70  ;IF NOT FNISHED LOOK AT NEXT CHAR.
@MATH1@_FN80:	SUB	BP,@MATH1@_@SFINCH
	SHL	BP,1  ; BRANCH TABLE ENTRIES 2 BYTES EA
@MATH1@_FN90:
;CODE SEGMENT OVERRIDE PREFIX
	JMP	 word [cs:@MATH1@_FN95+BP]
label @MATH1@_FN95 word
	DW	@MATH1@_FN100
	DW	@MATH1@_FN200
	DW	@MATH1@_FN200
	DW	@MATH1@_FN400
	DW	@MATH1@_FN500
	DW	@MATH1@_FN600
	DW	@MATH1@_FN92
	DW	@MATH1@_FN92
@MATH1@_FN92:  ;IT WAS A "D"
	XOR	AL,AL  ;SET CONDITION CODES CORRECTLY
@MATH1@_FN94:	CALL	@MATH1@_@SFINEX  ;CALCULATE EXPONENT
@MATH1@_FN96:	CALL	@MATH1@_@SFINE  ;MODIFY NUMBER TO REFLECT EXPONENT
	JMP	@MATH1@_FINF  ;CLEAN UP, NEGATE AS NECESSARY
@MATH1@_FN100:  ;IT WAS A "."
	INC	CX  ;TO DENOTE DECIMAL POINT DETECTED
	JNZ	@MATH1@_FN96  ;GO FINISH UP NO.-2ED DECIMAL PT. SEEN!
	CALL	@@SGETYP  ;IF SNG OR DOUBLE JUST RETURN
	JNS	@MATH1@_FN50
	PUSH	CX
	PUSH	BX
	PUSH	DI
	CALL	@@SCSI  ;CONVERT TO SINGLE PRECISION
	POP	DI
	POP	BX
	POP	CX
	JMP	@MATH1@_FN50  ;GO PROCESS NEXT CHAR.
@MATH1@_FN200:  ;IT WAS AN "E" OR  "E"+40 (LOWER CASE E)
	CALL	@MATH1@_@SCHKEL  ;MAKE SURE WE DON'T HAVE AN "ELSE"
	JZ	@MATH1@_FN96  ;IT WAS AN "ELSE" OR "EQV"
	JMP	@MATH1@_FN94  ;GO DETERMINE EXPONENT
@MATH1@_FN400:  ;IT WAS A "%" (INTEGER)
	INC	BX  ;Eat the percent sign.
	JMP	@MATH1@_FN96  ;Call $FINE since could be working
;on a floating point.

@MATH1@_FN500:  ;IT WAS A "#" (DOUBLE PRECISION)
	CALL	@MATH1@_@SFIND
	JMP	@MATH1@_FINF  ;GO FINISH UP
@MATH1@_FN600:  ;IT WAS A "!"    (SINGLE PRECISION)
	XOR	AL,AL  ;FLAG AS SINGLE
	CALL	@MATH1@_@SFINS  ;FORCE TO SINGLE PRECISION
@MATH1@_FINF:	POPF  ;RECALL SIGN FLAG
	JNZ	@MATH1@_FN990  ;RETURN IF NOT NEGATIVE NO.
	CALL	@MATH1@_@SVNEG  ;NEGATE NUMBER
	CALL	@@SGETYP  ;SET CONDITION CODES ACCORDING TO TYPE
	JPE	@MATH1@_FN990  ;IF NOT SINGLE PRECISION RETURN
	PUSH	BX  ;SAVE TEXT POINTER
	CALL	@MATH1@_@SCONI2  ;CHECK FOR -32768 AND CONVERT TO INT.
	POP	BX  ;RECALL TEXT POINTER
;IF FOUND
@MATH1@_FN990:	RET

; SUBTTL	 $FPWR/$SQR	 INVOLUTION/SQUARE RT. OF SINGLE PRECISION NOS.
;***********************************************************

;       $FPWR   CALCULATES X^Y BY X^Y=EXP(Y*LOG(X))

;       CALLING SEQUENCE:       CALL    $FPWR
;               WITH Y IN THE $FAC, X IN (BXDX)
;       $SQR    ENTRY POINT TO PROVIDE SQUARE ROOT FUNCTION
;       CALLING SEQUENCE:       CALL    $SQR
;               WITH ARGUMENT IN $FAC

;************************************************************

;SQUARE ROOT FUNCTION (FAC)=SQR(FAC)
@SQR:
@MATH1@_@SSQR:
	MOV	DX,word [@@SFAC-2]
	OR	DH,DH  ;Test sign bit
	JS	@MATH1@_NEGNUM
	MOV	AL,byte [@@SFAC]  ;Get exponent
	OR	AL,AL
	JZ	@MATH1@_DONE  ;SQR(0)=0
	MOV	BH,byte [@@SFAC-3]
	MOV	BL,((0) and 0FFh)
	OR	DH,((128) and 0FFh)  ;Set implied bit
	SHR	AL,1  ;Divide exponent by two
	JNB	@MATH1@_EVENEX
	SHR	DX,1  ;HALF MANTISSA IF EXP ODD
	RCR	BX,1
	STC  ;RESTORE CARRY FOR ROUND UP
@MATH1@_EVENEX:
	ADC	AL,((64) and 0FFh)  ;ADD BACK 1/2 OF BIAS
	MOV	byte [@@SFAC],AL  ;SAVE FINAL EXPONENT
	MOV	CX,25  ;24 BITS PLUS 1 FOR ROUNDING
	XOR	BP,BP  ;CLEAR SOME REGISTERS
	MOV	SI,BP
	MOV	DI,BP
	MOV	AX,BP
@MATH1@_RTLP:
	SHL	BX,1  ;64 BIT LEFT SHIFT OF INPUT
	RCL	DX,1
	RCL	DI,1
	RCL	BP,1
	SHL	BX,1  ;SHIFT IT TWICE
	RCL	DX,1
	RCL	DI,1
	RCL	BP,1
	STC  ;ROTATE IN TEST BIT
	RCL	SI,1  ;32-BIT SHIFT OF PARTIAL RESULT
	RCL	AX,1
	SUB	DI,SI  ;TRY TEST BIT
	SBB	BP,AX
	JNB	@MATH1@_ROOTBT  ;JUMP OUT IF IT FIT
	ADD	DI,SI  ;RESTORE IF IT DIDN'T
	ADC	BP,AX
	DEC	SI
	LOOP	@MATH1@_RTLP
	JMP	@MATH1@_FPWRND
@MATH1@_ROOTBT:
	INC	SI  ;HERE IF TEST BIT FIT
	LOOP	@MATH1@_RTLP  ;SET REAL RESULT BIT AND CONTINUE
@MATH1@_FPWRND:
	SHR	AX,1  ;HALF TO A 25-BIT RESULT
	RCR	SI,1
	SHR	AX,1  ;TO A 24-BIT RESULT
	RCR	SI,1
	ADC	SI,0  ;ROUND IF A 1 SHIFTED OUT
	ADC	AX,0  ;AND PROPAGATE CARRY
	MOV	word [@@SFAC-3],SI  ;STORE RESULT
	AND	AL,((127) and 0FFh)  ;CLEAR SIGN BIT
	MOV	byte [@@SFAC-1],AL  ;AND STORE
@MATH1@_DONE:	RET

@MATH1@_NEGNUM: JMP	@@SFCERR

@@SFPWR:  ;INVOLUTION ($FAC):=(BXDX)^($FAC)
;OR         (FAC)=X^Y
	MOV	DI,@@SCLROV
	PUSH	DI
	MOV	DI,@@SFLGOV
	MOV	byte [DI+0],((1) and 0FFh)  ;ONCE-ONLY OVERFLOW MODE
	CALL	@@SSIGNS  ;SEE IF Y IS ZERO
	JNZ	@MATH1@_FP10
	JMP	@MATH1@_@SEXP  ;ANS IS 1 IF Y=0
@MATH1@_FP10:	JNS	@MATH1@_FP20  ;IF NEGATIVE POTENTIAL OVERFLOW
	OR	BH,BH  ;IF X IS ZERO
	JNZ	@MATH1@_FP25
	JMP	@@SDIV0S  ;DIVIDE-BY-ZERO CODE
@MATH1@_FP20:	OR	BH,BH  ;SEE IF ZERO TO POWER
	JNZ	@MATH1@_FP25
	JMP	@MATH1@_@SZERO  ;ANS IS ZERO
@MATH1@_FP25:  ;WE KNOW AT THIS POINT THAT X IS NON-ZERO. IF X IS NEGATIVE
;THEN Y MUST BE AN INTEGRAL POWER OR WE HAVE A FUNCTION
;CALL ERROR
	OR	BL,BL  ;IS X NEGATIVE?
	JNS	@MATH1@_FP30  ;IF NOT PROCEED
	CMP	byte [@@SFAC],((153) and 0FFh)  ;SEE IF Y TOO LARGE TO DETERMINE SIGN
;OF INVOLUTION RESULT
	JB	@MATH1@_FP27  ;JUMP IF OK TO COMPUTE
	JMP	@@SFCERR
@MATH1@_FP27:
	PUSH	DX  ;SAVE X ON THE STACK
	PUSH	BX
	PUSH	word [@@SFACLO]  ;PUSH Y ON THE STACK
	PUSH	word [@@SFACM1]
	CALL	@MATH1@_@SINT  ;MAKE Y AN INTEGER
	POP	BX  ;Y TO THE REGISTERS
	POP	DX
	CALL	@@SFCOMP  ;SEE IF Y IS AN INTEGER
	CALL	@@SMOVFR  ;MOVE ORIGINAL Y BACK TO FAC
	POP	BX  ;RECALL X
	POP	DX
	JZ	@MATH1@_FP30  ;PROCEED IF Y IS AN INTEGER
	JMP	@@SFCERR  ;OTHERWISE WE HAVE FCN CALL ERROR
@MATH1@_FP30:	MOV	AL,byte [@@SFAC-1]  ;NEED TO KNOW IF Y IS NEGATIVE
	OR	AL,AL
	JNS	@MATH1@_FP30A  ;Y POSITIVE
	AND	AL,((127) and 0FFh)  ;Y is negative - will invert when
	MOV	byte [@@SFAC-1],AL  ;finished.  Clear the sign bit of Y.
	PUSH	BX  ;Save the sign of X.
	PUSH	word [@@SFACM1]  ;Save Y.
	PUSH	word [@@SFACLO]
	CALL	@MATH1@_FP30A  ;FAC:=X^positive Y.
	TEST	byte [@@SFAC],((255) and 0FFh)  ;Did it underflow?
	JNZ	@MATH1@_INVERT  ;No, go invert it.
	POP	word [@@SFACLO]  ;Yes, pop Y into the FAC.
	POP	word [@@SFACM1]
	CALL	@MATH1@_@SQINT  ;Get least significant byte of Y
;into DL.
	POP	BX  ;Get sign of X into BL bit 7.
	ROR	DL,1  ;Set sign bit of FAC if X is negative
	AND	BL,DL  ;and Y is odd.
	MOV	byte [@@SFAC+1],BL
	MOV	BH,((255) and 0FFh)  ;Make BH nonzero for DOINF routine
;(which is called by $OVFLS) so it uses
;$FAC+1 to determine the sign of the
;inifinity to use.
	JMP	@MATH1@_@SOVFLS  ;Give Overflow error with and return
;appropriate (negative or positive)
;inifinity based on the sign just
;put into the FAC.

@MATH1@_INVERT: ADD	SP,6  ;Pop off the garbage.
	MOV	DX,0  ;BXDX:=1.0.
	MOV	BX,33024
	JMP	@@SFDIVS  ;Invert the result and return.

@MATH1@_FP30A:
	PUSH	BX  ;SAVE X ON THE STACK
	PUSH	DX
	OR	BL,((127) and 0FFh)  ;SET CODES TO REFLECT SIGNS OF X
	PUSHF  ;SAVE X POS/NEG INFORMATION
	PUSH	word [@@SFACM1]  ;PUSH Y ON THE STACK
	PUSH	word [@@SFACLO]
	CALL	@MATH1@_@SINT  ;MUST DETERMINE IF Y IS AN INTEGER
	POP	DX  ;RECALL ORIGINAL Y
	POP	BX
	CALL	@@SFCOMP  ;ZF=1 IF Y IS AN INTEGER
	JNZ	@MATH1@_FP34  ;IF NOT INTEGER PROCEED AS NORMAL
	PUSH	DX  ;SAVE Y
	PUSH	BX
	MOV	DX,0  ;WILL MAKE (BXDX) 32768.
	MOV	BX,36864
	CALL	@@SFCOMP  ;SEE IF TOO LARGE
	POP	BX  ;RECALL Y
	POP	DX
	JNS	@MATH1@_FP34  ;AND IF SO COMPUTE WITH LOG & EXP
	POPF  ;GET X POS/NEG INFO OFF STACK
	POP	DX  ;GET X TO REGISTERS
	POP	BX
	JMP	@MATH1@_XTON  ;AND COMPUTE X^N

@MATH1@_FP34:	POPF  ;GET X POS/NEG INFORMATION
	JNS	@MATH1@_FP40  ;NO PROBS IF X IS POSITIVE
	PUSH	BX  ;SAVE Y ON THE STACK
	PUSH	DX
	CALL	@MATH1@_@SQINT  ;NEED EVEN-ODD INFORMATION
	MOV	AL,DL  ;GET LOW BYTE OF INTEGER
	CALL	@@SNORMS  ;($FAC)=INT(Y)
	POP	DX  ;RECALL Y
	POP	BX
	RCR	AL,1  ;CF=1 IF ODD
@MATH1@_FP40:	POP	word [@@SFACLO]  ;GET X TO FAC
	POP	word [@@SFACLO+2]
	LAHF  ;SAVE EVEN/ODD INFO
	AND	byte [@@SFACM1],((127) and 0FFh)  ;CLEAR ANY SIGN BIT
	SAHF  ;GET EVEN/ODD INFO
	JNB	@MATH1@_FP60
	MOV	DI,@@SNEG
	PUSH	DI  ;WILL NEGATE AT THE END IF CF=1
@MATH1@_FP60:	PUSH	BX  ;SAVE Y AGAIN
	PUSH	DX
	CALL	@MATH1@_@SLOG  ;LOG(X)
	POP	DX  ;RECALL Y
	POP	BX
	CALL	@@SFMULS  ;($FAC)=Y*LOG(X)
	JMP	@MATH1@_@SEXP  ;COMPLETE CALCULATION
;**************************************************************
;       ($FAC)=($FAC)^(BXDX)
;WHERE (BXDX) IS AN INTEGER SUCH THAT 0.LT.(BXDX).LE.32767

;OR AS IN KNUTH X**N IS AS FOLLOWS
;THE ALGORITHM IS TAKEN FROM KNUTH VOL2 P400
;A1.Y=1, Z=X
;A2.HALVE N AND DETERMINE IF N WAS EVEN OR ODD. IF N WAS EVEN
;   THEN JUMP TO A4.
;A3.Y=Y*Z
;A4.IF N = 0 FINISHED WITH Y THE ANSWER
;A5.Z=Z*Z AND RETURN TO A2
;***************************************************************
@MATH1@_XTON:  ;($FAC):=(BXDX)^($FAC)
	PUSH	BX  ;SAVE X ON STACK
	PUSH	DX
	CALL	@MATH1@_@SQINT  ;CONVERT TO INTEGER
	MOV	word [@@SARG],DX  ;N TO $ARG
	MOV	word [@@SFACLO],0  ;WILL MOVE 1.0 TO FAC
	MOV	word [@@SFACM1],33024
@MATH1@_XTON10: SHR	word [@@SARG],1  ;SHIFT RIGHT 1 BIT
	JNB	@MATH1@_XTON20  ;IF NO MULTIPLY THEN Z=Z**2
	POP	DX  ;FETCH Z
	POP	BX
	PUSH	BX  ;AND PUT IT BACK ON STACK
	PUSH	DX
	CALL	@@SFMULS  ;Y=Y*Z
@MATH1@_XTON20: TEST	word [@@SARG],65535  ;SEE IF N HAS GONE TO ZERO
	JZ	@MATH1@_XTON30  ;GET OUT IF FINISHED
	POP	DX  ;FETCH Z TO REGISTERS
	POP	BX
	CALL	@MATH1@_@SPUSHF  ;Y TO STACK
	CALL	@@SMOVFR  ;Z TO FAC
	CALL	@@SFMULS  ;Z=Z*Z
	POP	DX  ;FETCH Y
	POP	BX
	CALL	@MATH1@_@SPUSHF  ;NEW Z TO STACK
	CALL	@@SMOVFR  ;Y TO FAC
	JMP	@MATH1@_XTON10  ;TRY AGAIN
@MATH1@_XTON30: POP	DX  ;GET STACK CLEAR OF Z
	POP	BX
	RET

; SUBTTL	 F4  MAP BETWEEN 8080-8086 CONVERTED F3 TO 8086 MATHPK

@MATH1@_@SCHRGT: JMP	@CHRGTR
@DSUB:
	XOR	byte [@@SFAC-1],((128) and 0FFh)  ;WILL FLIP SIGNS OF EACH ARGUMENT
	XOR	byte [@@SARG-1],((128) and 0FFh)
	JMP	@@SFSUBD
@FADD:
	XCHG	BX,CX
	JMP	@@SFADDS
@FSUB:
	XCHG	BX,CX
	JMP	@@SFSUBS
@FDIV:	XCHG	BX,CX
	JMP	@@SFDIVS
@CONSIH:
	MOV	word [@@SFACLO],BX
	JMP	@@SCSI
@MATH1@_FLOAT:
	PUSH	DX
	CBW
	MOV	DX,AX
	CALL	@@SFLT
	POP	DX
	RET
@FMULT:
	XCHG	BX,CX
	JMP	@@SFMULS
@MATH1@_FPWR:
	XCHG	BX,CX
	JMP	@@SFPWR

;*************************************************************
;INTEGER ARITHMETIC FOLLOWS
;*************************************************************
@ISUB:  ;(BX)=(DX)-(BX)
	CMP	BX,32768  ;CHECK FOR -32768
	JNZ	@MATH1@_IS10  ;PROCEED IF NOT
	CALL	@@SFLT  ;FLOAT DX
	XOR	DX,DX  ;WILL SET (BXDX)=-32768.0
	MOV	BX,36992
	CALL	@@SFSUBS  ;DO SUBTRACT
	CALL	@@SNEG  ;NEGATE
	JMP	@@SFI
@MATH1@_IS10:
	NEG	BX  ;NEGATE AND FALL INTO ADD

@IADD:  ;(BX)=(DX)+(BX)
	PUSH	BX  ;SAVE 1ST ARG
	ADD	BX,DX
	JO	@MATH1@_IAD10  ;IF OVERFLOW JUMP
	POP	AX  ;CLEAR STACK
	JMP	@MAKINT
@MATH1@_IAD10:
	CALL	@@SFLT  ;FLOAT 2ED ARG
	POP	DX  ;RECALL FIRST ARG
	PUSH	word [@@SFACLO]
	PUSH	word [@@SFAC-1]  ;FAC PUSHED ON THE STACK
	CALL	@@SFLT  ;FLOAT 2ED ARG
	POP	BX
	POP	DX  ;GET 2ED ARG TO (BXDX)
	JMP	@@SFADDS  ;GO ADD FLOATING

@IMULT:  ;(BX)=(BX)*(DX)
	MOV	AX,BX
	PUSH	DX  ;SAVE 2ED ARG
	IMUL	DX  ;PERFORM MULTIPLICATION
	POP	DX  ;RECALL 2ED ARG
	JB	@MATH1@_IM10  ;MUST FLOAT ARGS IF CF=1
	MOV	BX,AX
	JMP	@MAKINT
@MATH1@_IM10:
	PUSH	BX  ;SAVE FIRST ARG
	CALL	@@SFLT  ;FLOAT 2ED ARG
	POP	DX  ;RECALL 1ST ARG
	PUSH	word [@@SFACLO]
	PUSH	word [@@SFAC-1]
	CALL	@@SFLT  ;FLOAT 1ST ARG
	POP	BX
	POP	DX  ;GET 2ED ARG TO (BXDX)
	JMP	@@SFMULS  ;GO MULTIPLY FLOATING

@IDIV:  ;(BX)=(DX)/(BX)
	OR	BX,BX  ;MAKE SURE ITS NON-ZERO
	JNZ	@MATH1@_IDIV10
	MOV	byte [@@SFAC+1],DH  ;FOR CORRECT SIGN
	INC	BH  ; Hack for DOINF to work
	MOV	byte [@@SVALTP],((4) and 0FFh)
	JMP	@@SDIV0S
@MATH1@_IDIV10:
	CMP	DX,32768  ;CHECK FOR -32768
	JNZ	@MATH1@_IDIV15  ;PROCEED IF NOT
	CMP	BX,65535  ;Check for special case of -32768\-1
	JNE	@MATH1@_IDIV11
	CALL	@@SFLT  ;FLOAT DX
	CALL	@@SNEG
	RET
@MATH1@_IDIV11:
	CMP	BX,1  ;Other special case
	JNE	@MATH1@_IDIV15
	MOV	BX,DX  ;Put -32768\1 = -32768 in BX so we can ...
	JMP	@MAKINT  ;Return it as an Int. (IDIV doesn't work)
@MATH1@_IDIV15:
	MOV	word [@@SFACLO],BX  ;WILL PERFORM (DX:AX)/(FAC)
	MOV	AX,0
	MOV	word [@@SFACM1],AX
	XCHG	AX,DX  ;GET NO RT. ADJUSTED IN AX
	OR	AX,AX
	JNS	@MATH1@_IDV20
	MOV	DX,65535  ;SIGN EXTEND INTO DX
@MATH1@_IDV20:	OR	BX,BX  ;SEE IF DENOMINATOR NEEDS SIGN EXT
	JNS	@MATH1@_IDV30
	MOV	word [@@SFACM1],65535
@MATH1@_IDV30:	IDIV	word [@@SFACLO]  ;16 BIT DIVIDE
	MOV	BX,AX
	JMP	@MAKINT

@MOVFR:	XCHG	BX,CX
	CALL	@@SMOVFR  ;MOVE TO FAC
	XCHG	BX,CX  ;GET REGISTERS RIGHT
	RET
@MOVFM:	PUSH	BX
	CALL	@@SMOVFM
	POP	BX
	ADD	BX,4
	RET
@MOVRF:	MOV	DX,word [@@SFACLO]
	MOV	CX,word [@@SFAC-1]
	RET
@MOVMF:	PUSHF
	PUSH	BX
	CALL	@@SMOVMF
	POP	BX
	ADD	BX,4
	POPF
	RET
@FOUTO:	CALL	@FRQINT
	MOV	word [@@SFACLO],BX
	JMP	@@SFOUTO
@FOUTH:	CALL	@FRQINT
	MOV	word [@@SFACLO],BX
	JMP	@@SFOUTH
@FADDS:  ;ADD NO. POINTED TO BY (BX) TO (FAC)
	MOV	DX,word [BX+0]
	MOV	BX,word [BX+2]
	JMP	@@SFADDS
@PUSHF:	POP	SI  ;GET OUR RETURN ADDRESS OFF STACK
	PUSH	word [@@SFACLO]
	PUSH	word [@@SFAC-1]
	JMP	SI
@FCOMP:
	XCHG	BX,CX
	CALL	@@SFCOMP
	XCHG	BX,CX
	RET
@FRCSTR:
@CHKSTR: CALL	@@SGETYP  ;WANT TO ASSURE STRING
	JZ	@MATH1@_CH10
	JMP	@TMERR
@MATH1@_CH10:	RET
@INEG2:	XCHG	BX,DX
	CALL	@VALSNG
	XOR	AL,AL
@MATH1@_INEGAD: MOV	CH,((152) and 0FFh)
@MATH1@_FLOATR:
