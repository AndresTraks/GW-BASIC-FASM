; Tangent Code

@TAN:
@MATH1@_@STAN:	PUSH	word [@@SFACM1]  ;SAVE ARG
	PUSH	word [@@SFACLO]
	CALL	@MATH1@_@SSIN  ;CALCULATE SINE
	POP	DX  ;RECALL ARGUMENT
	POP	BX
	PUSH	word [@@SFACLO]  ;SAVE SIN(X)
	PUSH	word [@@SFACM1]
	CALL	@@SMOVFR  ;MOVE ORIGINAL ARG TO FAC
	CALL	@MATH1@_@SCOS  ;CALCULATE COSINE
	POP	BX  ;RECALL SIN(X)
	POP	DX
	JMP	@@SFDIVS  ;GO DIVIDE TO EFFECT TANGENT
@ATN:
@MATH1@_@SATAN:  ;(FAC)=ARCTANGENT(FAC)
	MOV	AX,word [@@SFAC-1]  ;WANT ONLY POSITIVE X
	OR	AL,AL
	JNS	@MATH1@_ATN10
	MOV	DI,@@SNEG  ;TAKE ADVANTAGE OF IDENTITY
	PUSH	DI  ;ATAN(X)=-ATAN(-X)
	AND	AL,((127) and 0FFh)  ;CLEAR SIGN
	MOV	byte [@@SFAC-1],AL
@MATH1@_ATN10:	CMP	AH,((129) and 0FFh)  ;SEE IF X .GT. TAN(PI/4)
	JB	@MATH1@_ATN20  ;IF NOT PROCEED
	MOV	DI,@MATH1@_ATN100  ;WILL WANT TO FORM
	PUSH	DI  ;PI/2-(FAC) AT THE END
	XOR	DX,DX  ;WILL SET (BXDX)=1.0
	MOV	BX,33024
	CALL	@@SFDIVS  ;THIS PUTS 1/X IN FAC
@MATH1@_ATN20:	MOV	DX,12450  ;FETCH TAN(PI/12)
	MOV	BX,32521
	CALL	@@SFCOMP  ;SEE IF LARGER
	JS	@MATH1@_ATN30  ;IF NOT PROCEED
	MOV	DI,@MATH1@_ATN200  ;WILL WANT (FAC)=(FAC)+PI/6
	PUSH	DI  ;AT THE END
	PUSH	word [@@SFACLO]  ;SAVE X
	PUSH	word [@@SFACM1]
	MOV	DX,46039  ;FETCH SQR(3)
	MOV	BX,33117
	CALL	@@SFADDS  ;(FAC)=X+SQR(3)
	POP	BX
	POP	DX  ;FETCH X BACK
	PUSH	word [@@SFACLO]  ;SAVE X+SQR(3)
	PUSH	word [@@SFACM1]
	CALL	@@SMOVFR  ;X TO FAC
	MOV	BX,@MATH1@_@SATNC1
	CALL	@MATH1@_@SPOLY  ;FORM X*SQR(3)-1
	POP	BX
	POP	DX  ;RECALL X+SQR(3)
	PUSH	word [@@SFACLO]  ;PUSH X*SQR(3)-1 ON STACK
	PUSH	word [@@SFACM1]
	CALL	@@SMOVFR  ;X+SQR(3) TO FAC
	POP	BX
	POP	DX  ;RECALL X*SQR(3)-1
	CALL	@@SFDIVS  ;FORM (X+SQR(3)-1)/(X+SQR(3))
@MATH1@_ATN30:	MOV	BX,@MATH1@_@SATNC2  ;PREPARE FOR HART 4940
	JMP	@MATH1@_@SPOLYX
@MATH1@_ATN100: MOV	DX,4059  ;FETCH PI/2
	MOV	BX,33097
	JMP	@@SFSUBS  ;(FAC)=PI/2-(FAC)

@MATH1@_ATN200: MOV	DX,2706  ;FETCH PI/6
	MOV	BX,32774
	JMP	@@SFADDS  ;ADD PI/6 TO FAC

; SUBTTL	 $FINE	 ROUTINE TO ADJUST INPUT NUMBER FOR EXPONENT
;****************************************************************

;       $FINE   THIS ROUTINE MODIFIES THE CURRENT FAC WHICH HAS
;               THE INPUT SIGNIFICANT DIGITS SO THAT THE EXPONENT
;               IS REFLECTED IN THE NUMBER. FOR EXAMPLE, IF THE
;               NUMBER INPUT IS 1.9876E-17 THEN THE FAC CURRENTLY
;               HAS THE NUMBER 19876. IT MUST BE MULTIPLIED BY
;               10^-21 TO CORRECTLY REFLECT THE INPUT NUMBER.
;               IT IS THE JOB OF THIS ROUTINE TO DETERMINE THE
;               CORRECT MULTIPLIER AND PERFORM THE MULTIPLICATION
;       CALLING SEQUENCE        CALL    $FINE
;               WITH (SI) CONTAINING 0 IF POSITIVE EXPONENT
;               ALL BITS SET IF NEGATIVE EXPONENT. (DX) CONTAINS
;               THE INPUT EXPONENT(FOR THE EXAMPLE ABOVE =17)
;               AND (DI) CONTAINS THE NUMBER PLACES TO THE RIGHT
;               OF THE DECIMAL POINT.

;*****************************************************************

@MATH1@_@SFINE:	OR	SI,SI  ;SEE IF DX SHOULD BE NEGATED
	JNS	@MATH1@_FIN05  ;IF NOT PROCEED
	NEG	DX  ;NEGATE
@MATH1@_FIN05:	SUB	DX,DI  ;SUBTRACT OUT DIGITS TO RIGHT OF DP.
	JO	@MATH1@_FIN80  ;UNDERFLOW IF OVERFLOW FLAG SET
	JZ	@MATH1@_FIN55  ;NUMBER COMPLETE AS IS
;***************************************************************
;HERE WE HAVE THE EXPONENT IN DX. WE HAVE MULTIPLIERS RANGING
;FROM (10^-38,10^38) TO USE IN DETERMINING THE CORRECT FAC. WE
;MAY NEED TO DO SEVERAL MULTIPLIES TO CORRECTLY FORM THE NUMBER.
;FOR EXAMPLE IF THE NUMBER INPUT WAS 1234567.E-40 DX WOULD
;HAVE -40. IF THIS WERE THE CASE WE NEED TO DO A MULTIPLY BY 10^-38
;THEN A MULTIPLY BY 10^-2 TO GET THE RIGHT NUMBER.
;  All calculations are done in double precision and then converted
;back to the original type.  Integers are converted to single precision.
;****************************************************************
@MATH1@_MDPTEN:
	PUSH	BX  ; Preserve text pointer
	CALL	@@SGETYP  ; Get the current type,
	PUSHF  ; And save, so that we can convert back
	JNB	@MATH1@_FIN20  ; If already D.P., no conversion necessary
	CALL	@FRCDBL  ; Force result to be double precision
@MATH1@_FIN20:	OR	DX,DX  ; Test sign of exponent
	JS	@MATH1@_FIN30  ;IF NEGATIVE EXPONENT JUMP
;********************************************************************
;POSITIVE EXPONENT . IF GREATER THAN D^38 THEN WE HAVE OVERFLOW
; Unless the number is zero, in which case just return zero.
;********************************************************************
	TEST	byte [@@SFAC],((255) and 0FFh)  ;Is the number zero?
	JZ	@MATH1@_FIN80  ;Yes, just return zero then.
	CMP	DX,39
	JB	@MATH1@_FIN40  ;OK PROCEED
	POPF  ; Get back type flags
	JNB	@MATH1@_FIN25  ; Already D.P., nothing to convert
	CALL	@@SCSD  ; Convert double to single
@MATH1@_FIN25:	POP	BX  ; Restore text pointer
	JMP	@MATH1@_@SOVFLS  ;OVERFLOW

; Negative exponent.
; Might require two divisions since highest table entry is 10^38.

@MATH1@_FIN30:	CMP	DX,-38  ;Will one pass be enough?
	JGE	@MATH1@_FIN40  ;Yes.
	ADD	DX,38  ;No, will two divisions get it?
	CMP	DX,-38
	JL	@MATH1@_FIN80  ;No, underflow - return zero.
	CALL	@MATH1@_MDP10  ;Yes, do the first one
	MOV	DX,-38  ;Then divide by 10^38.
@MATH1@_FIN40:	CALL	@MATH1@_MDP10  ; Do the division
@MATH1@_FIN45:	POPF  ; Get back type flags
	JNB	@MATH1@_FIN50  ; Already D.P., nothing to convert
	CALL	@@SCSD  ; Convert double to single

; At this point the number is restored to its original type, with the
; exception of integers being converted to single precision.

@MATH1@_FIN50:	POP	BX  ; Restore text pointer
@MATH1@_FIN55:	RET

@MATH1@_FIN80:	CALL	@MATH1@_@SZERO  ;UNDERFLOW!
	JMP	@MATH1@_FIN45  ; Restore proper type

; Multiply or divide by double precision power of ten.
; On entry DX contains the exponent.
; If the exponent is postive, multiply.
; If exponent is negaive, divide.

@MATH1@_MDP10:
	OR	DX,DX  ;Is the exponent negative?
	PUSHF  ;Remember whether to multiply or
;divide.
	JNS	@MATH1@_POSEXP  ;Positive exponent.
	NEG	DX  ;Negative exponent, make it positive.
@MATH1@_POSEXP: MOV	CX,3  ;DX:=DX*8 to get offset into powers
	SHL	DX,CL  ;of ten table.
	ADD	DX,@MATH1@_@SDP00  ;DX:=pointer to power of ten.
	XCHG	BX,DX  ;Move it to BX.
	CALL	@MATH1@_@SMOVAC  ;MOVE D.P. NO. TO ARG
	POPF  ;Divide?
	JS	@MATH1@_DBLDIV  ;Yes.
	JMP	@MATH1@_@SFMULD  ;No, multiply and return to caller
@MATH1@_DBLDIV: JMP	@MATH1@_DDIVFA  ;Double precision divide; FAC=FAC/ARG,
; Return to caller.

; SUBTTL	 $OVFLS  OVERFLOW CODE
;***********************************************************

;       $OVFLS  PLACES CORRECT INFINITY IN THE FAC AND PRINTS
;               OVERFLOW MESSAGE

;       $DIV0S  PLACES CORRECT INFINITY IN THE FAC AND PRINTS
;               DIVIDE-BY-ZERO MESSAGE

;***********************************************************

@MATH1@_@SOVFLS: PUSH	BX
	CALL	@MATH1@_OVFLS  ;DO THE OVERFLOW CODE
	POP	BX  ;RESTORE TEXT POINTER
	RET
@MATH1@_OVFLS:	CALL	@MATH1@_DOINF  ;PUT IN APPROPRIATE INFINITY
	MOV	AX,@OVERR  ;Error trapping routine adr
	MOV	BX,@@SOVMSG  ;ADDRESS APPROPRIATE ERROR MESSAGE
	JMP	@MATH1@_DV010  ;GO PRINT MESSAGE
@@SDIV0S: PUSH	BX  ;SAVE TEXT POINTER
	CALL	@MATH1@_DIV0S  ;DO THE DIVIDE OVERFLOW CODE
	POP	BX
	RET  ;RETURN WITH TEXT POINTER SAVED
@MATH1@_DIV0S:	CALL	@MATH1@_DOINF  ;PUT IN APPROPRIATE INFINITY
	MOV	AX,@DV0ERR  ;Error trapping routine adr
	MOV	BX,@@SDIV0M  ;AND ERROR MESSAGE
@MATH1@_DV010:	CALL	@MATH1@_TRAPER  ;Trap error if error trapping enabled
	CMP	byte [@@SFLGOV],((1) and 0FFh)  ;IF 0,1 PRINT, IF 1 MAKE 2
	JS	@MATH1@_DV015  ;PRINT IF 0
	JNZ	@MATH1@_DV020  ;DON'T PRINT IF 2
	MOV	byte [@@SFLGOV],((2) and 0FFh)  ;MAKE 2 IF 1
@MATH1@_DV015:	CALL	@@SSTPRN
	MOV	AL,((13) and 0FFh)  ;CARRIAGE RETURN
	CALL	@@SCATTY  ;SEND IT
	MOV	AL,((10) and 0FFh)  ;LINE FEED
	CALL	@@SCATTY  ;SEND IT
@MATH1@_DV020:	RET

@MATH1@_DOINF:  ;PUT CORRECT INFINITY IN THE FAC
	CLD  ;CLEAR THE DIRECTION FLAG "DF"
	OR	BH,BH  ;SEE IF ZERO TO A NEG POWER
	MOV	SI,@MATH1@_@SINFPD  ;ASSUME POSITIVE
	JZ	@MATH1@_INF10  ;POSITIVE INFINITY FOR ZERO^-X
	TEST	byte [@@SFAC+1],((128) and 0FFh)  ;NEGATIVE?
	JNS	@MATH1@_INF10  ;IF NOT PROCEED
	MOV	SI,@MATH1@_@SINFMD  ;NEGATIVE INFINITY
@MATH1@_INF10:	CALL	@@SGETYP  ;SET CODES ACCORDING TO TYPE
	JB	@MATH1@_INF20
;***********************************************************
;IT'S DOUBLE PRECISION
;***********************************************************
	MOV	DI,@@SDFACL  ;RECEIPIENT
	MOV	CX,4  ;4 WORDS FOR DOUBLE PRECISION
	JMP	@MATH1@_INF30
@MATH1@_INF20:  ;SINGLE PRECISION
	ADD	SI,4  ;SO WE POINT TO SINGLE PRECISION NO.
	MOV	DI,@@SFACLO
	MOV	CX,2  ;2 WORDS FOR SINGLE
@MATH1@_INF30:  ;MUST FETCH FROM CODE SEGMENT
	movsw  ;TO FAC
	LOOP	@MATH1@_INF30
	RET

@MATH1@_TRAPER: PUSH	AX  ;save Error trapping routine adr
	MOV	AX,word [@ONELIN]
	OR	AX,AX  ;see if we are trapping errors
	JNZ	@MATH1@_TRAPIT  ;branch if errors are being trapped
	POP	AX  ;discard Error trapping routine adr
@MATH1@_TRAPIT: RET  ;return to caller or Error trap routine

; SUBTTL	 $FOFMT  FLOATING FORMAT OF NUMBER IN THE FAC
;**************************************************************

;       $FOFMT  FORMAT THE NUMBER IN THE FAC. IF THE NUMBER CAN BE
;               AS ACCURATELY REPRESENTED IN FIXED FORMAT AS
;               SCIENTIFIC THEN USE FIXED OUTPUT.
;       CALLING SEQUENCE:       CALL    $FOFMT
;               WITH (BX) POINTING TO CURRENT OUTPUT POSITION
;               IN THE OUTPUT BUFFER $FBUFF AND CONDITION CODES
;               SET AS IF $GETYP WAS JUST CALLED

;*****************************************************************

@MATH1@_@SFOFMT: PUSH	BX  ;SAVE BUFFER POINTER

	MOV	AL,((8) and 0FFh)  ;assume single precision - print 7 digits

	JB	@MATH1@_FFM10  ;JUMP IF SINGLE PRECISION
	MOV	AL,((17) and 0FFh)  ;DOUBLE PRECISION POSSIBLE DIGITS
@MATH1@_FFM10:	MOV	CH,AL  ;WILL SAVE A SECOND COPY FOR LATER
	MOV	CL,AL
	PUSH	CX  ;SAVE FOR LATER
	PUSHF  ;SAVE TYPE
	CALL	@MATH1@_@SFOTNV  ;BRACKET THE NUMBER SO THAT SIGNIFICANT
;DIGITS ARE IN THE INTEGER PART AND
;THE NECESSARY EXPONENT IS IN (AL)
	OR	AL,AL  ;IF POSITIVE DON'T CALL SIGD
	JZ	@MATH1@_FFM11
	JNS	@MATH1@_FFM15
@MATH1@_FFM11:	POPF  ;RECALL TYPE FOR TEST TO SEE IF SIGD
;CALLED. IF S.P. AND (AL) SMALLER THAN
;-7 MUST CALL SIG, IF D.P. AND (AL)
;SMALLER THAN -16 THEN MUST CALL SIGD.
;IF (AL) POSITIVE SIGD WILL NOT BE
;CALLED. PURPOSE OF SIGD IS TO
;DETERMINE WHETHER WE CAN PRINT NO. IN
;FIXED FORMAT W/O LOSING SIGNIFICANT
;DIGITS.
	POP	CX  ;RECALL POSIBLE SIGNIFICANT SIGITS
	PUSH	AX  ;SAVE EXP.
	JPO	@MATH1@_FFM16  ;SINGLE PREC.
	ADD	AL,((16) and 0FFh)  ;THIS MUST MAKE POSITIVE TO NOT CALL
	POP	AX
	JNS	@MATH1@_FFM18  ;POP AX AND DO FIXED OUTPUT
	JMP	@MATH1@_FFM17  ;MUST CALL SIGD
@MATH1@_FFM15:
	POPF  ;RECALL TYPE FLAG
	POP	CX  ;RECALL CX
	JMP	@MATH1@_FFM20
@MATH1@_FFM16:
	ADD	AL,((7) and 0FFh)
	POP	AX
	JNS	@MATH1@_FFM18
@MATH1@_FFM17:
	PUSH	AX  ;SAVE NECESSARY EXPONENT IN (AL)
	CALL	@MATH1@_@SSIGD  ;INCREMENT (CL) FOR EACH ZERO DIGIT
;BEGINNING FROM THE RIGHT
	POP	AX  ;RECALL NECESSARY EXPONENT
	MOV	AH,AL  ;WILL PERFORM FIRST TEST ON AH
	ADD	AH,CL  ;IF SF=1 AFTER THIS THEN USE "E" FORMAT
	JLE	@MATH1@_FFM20  ;JUMP IF TOO SMALL
	ADD	CH,AL
	JMP	@MATH1@_FFM19
@MATH1@_FFM18:	ADD	AL,CH
	INC	CH
	CMP	CH,AL
	MOV	CH,((3) and 0FFh)  ;TO FLAG "E" FORMAT IF NECESSARY
	JB	@MATH1@_FFM30
	MOV	CH,AL
@MATH1@_FFM19:	INC	CH  ;(CH)= NUMBER DIGITS+2
	MOV	AL,((2) and 0FFh)  ;THIS WILL CAUSE ZF=1 IN LATER CALC
;AND WILL SIGNAL FIXED OUTPUT
	JMP	@MATH1@_FFM30
@MATH1@_FFM20:	ADD	AL,CH
	MOV	CH,((3) and 0FFh)  ;SIGNALS "E" TYPE FORMAT
@MATH1@_FFM30:	DEC	AL  ;(AL) 2 TOO LARGE
	DEC	AL
	POP	BX  ;RECALL BUFFER POINTER
	PUSH	AX  ;SAVE EXPONENT
	PUSHF  ;SAVE CONDITION CODES
	XOR	CL,CL  ;(CL)=0  (NO COMMAS AFTER EACH 3 DIGITS
	CALL	@MATH1@_@SFOTAN  ;PUT IN DECIMAL POINT AND LEADING
;ZEROS AS NECESSARY
	MOV	byte [BX+0],(("0") and 0FFh)  ;ZF=1 IF THIS "0" NECESSARY
	JNZ	@MATH1@_FFM40
	INC	BX
@MATH1@_FFM40:	CALL	@MATH1@_@SFOTCV  ;CONVERT THE FAC TO DECIMAL DIGITS
;AND PUT IN DECIMAL POINT AS NECESSARY
@MATH1@_FFM50:	DEC	BX  ;WILL NOW SEE IF THERE ARE TRAILING
	CMP	byte [BX+0],(("0") and 0FFh)  ;ZEROS TO SUPPRESS. WE KNOW ZEROS WE
	JZ	@MATH1@_FFM50  ;FIND HERE ARE TRAILING BECAUSE $FOTCV
	CMP	byte [BX+0],((".") and 0FFh)  ;PUTS IN DECIMAL POINT
	JZ	@MATH1@_FFM60  ;CAN WE DELETE THE DECIMAL POINT ALSO?
	INC	BX
@MATH1@_FFM60:	POPF  ;LET'S HAVE A LOOK AT THE POSSIBLE
;EXPONENT
	POP	AX
	JZ	@MATH1@_FFM100  ;IF NO EXPONENT JUST CLEAN-UP AND RET
@MATH1@_@SPUEXP: PUSHF  ;SAVE SF( IF =1 NEGATIVE EXPONENT)
	PUSH	AX  ;SAVE EXPONENT
	CALL	@@SGETYP  ;SET COND. CODES FOR TYPE NUMBER
	MOV	AH,(("E") and 0FFh)  ;ASSUME SINGLE PRECISION
	JPO	@MATH1@_FFM70  ;IF S.P. PROCEED
	MOV	AH,(("D") and 0FFh)  ;IT'S DOUBLE PRECISION
@MATH1@_FFM70:	MOV	byte [BX+0],AH  ;PUT IN EXPONENT DESIGNATOR
	INC	BX  ;POINT TO NEXT BUFFER POSITION
	POP	AX  ;RECALL EXPONENT
	POPF  ;NOW TO SEE IF POSITIVE OR NEGATIVE
	MOV	byte [BX+0],(("+") and 0FFh)  ;ASSUME POSITIVE EXPONENT
	JNS	@MATH1@_FFM80  ;AND JUMP IF SO
	MOV	byte [BX+0],(("-") and 0FFh)
	NEG	AL  ;MUST MAKE EXPONENT POSITIVE
@MATH1@_FFM80:	MOV	AH,(("0"-1) and 0FFh)  ;WILL BUILD DIGIT IN (AL)
@MATH1@_FFM90:	INC	AH  ;INCREMENT TO NEXT DIGIT
	SUB	AL,((10) and 0FFh)
	JNB	@MATH1@_FFM90
	ADD	AL,(("0"+10) and 0FFh)  ;ADD TO DETERMINE SECOND DIGIT
	INC	BX  ;POINT TO NEXT BUFFER POSITION
	XCHG	AL,AH  ;PREPARE FOR WORD STORE
	MOV	word [BX+0],AX  ;STORE 2 DIGITS OF EXPONENT
	INC	BX  ;INCREMENT TO NEXT BUFFER POSITION
	INC	BX
@MATH1@_FFM100: MOV	byte [BX+0],((0) and 0FFh)  ;SIGNAL END OF BUFFER DATA
	XCHG	BX,CX  ;END-OF-BUFFER PTR. IN (CX)
	MOV	BX,@@SFBUFF+1  ;START IN (BX)
	RET

; SUBTTL	 UTILS	   UTILITY ROUTINES

