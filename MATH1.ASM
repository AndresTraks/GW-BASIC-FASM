; SUBTTL	 $SIN	 SINGLE PRECISION SINE/COSINE/TANGENT/ARCTANGENT
;****************************************************************

;       $SIN,$COS,$TAN  CALCULATE THE SINE/COSINE/TAN OF NO.
;                       IN THE $FAC.USES HART POLYNOMIAL EVALUATION
;                       WITH COEFFICIENTS FROM #3341
;       CALLING SEQUENCE:       CALL    $SIN
;                       OR      CALL    $COS
;                       OR      CALL    $TAN
;                       WITH ARGUMENT IN THE $FAC

;       $ATAN           CALCULATE THE ARCTANGENT OF THE VALUE IN THE
;                       FAC. USES COEFFICIENTS FROM HART 4940
;       CALLING SEQUENCE:       CALL    $ATAN
;                       WITH THE ARGUMENT IN THE FAC

;       Changed COS to double precision range reduction 24-JUN-82/NGT

;******************************************************************

@COS:
@MATH1@_@SCOS:
	AND	byte [@@SFACM1],((127) and 0FFh)  ;clear sign bit ( cos(-x) = cos(x) )
	CALL	@MATH1@_RR  ; Do range reduction, FAC=REM(FAC/2pi)
	CALL	@MATH1@_ONEARG  ; Zero the accumulator
	MOV	byte [@@SARG],((127) and 0FFh)  ; ARG = DP 1/4
	CALL	@MATH1@_@SFADDD  ; FAC = reduced angle + PI/2
	CALL	@MATH1@_RR1  ; Make sure we are still in 0 - 2*PI
	JMP	@MATH1@_SIN30

@SIN:
@MATH1@_@SSIN:  ;Will now take advantage of identity SIN(-X)=-SIN(X)
	MOV	AX,word [@@SFAC-1]  ;FETCH SIGN BYTE
	CMP	AH,((119) and 0FFh)  ;IF EXP SMALLER THEN RETURN X
	JNB	@MATH1@_SIN10
	RET
@MATH1@_SIN10:
	OR	AL,AL
	JNS	@MATH1@_SIN20
;(FAC) is negative will make positive and push neg on stack
	AND	AL,((127) and 0FFh)  ;CLEAR SIGN BYTE
	MOV	byte [@@SFAC-1],AL
	MOV	AX,@@SNEG  ;FETCH ADDRESS OF NEG
	PUSH	AX  ;AND PUSH ON STACK
@MATH1@_SIN20:
	CALL	@MATH1@_RR  ; Do DP range reduction

; At this point the FAC has the remainder of the angle / 2*PI

@MATH1@_SIN30:
	MOV	AL,((@@SFAC) and 0FFh)
	OR	AL,AL
	JZ	@MATH1@_SIN31
	ADD	byte [@@SFAC],((2) and 0FFh)  ; FAC = FAC*4 = Reduce angle / PI/2
@MATH1@_SIN31:
	CALL	@MATH1@_RR3  ;ARG= INT(FAC)

; Now we have the reduced angle mod PI/2, so that we can find what quadrant
; it's in.  The FAC should have a value in the range 0-3 corresponding to
; the quadrant.  If the value is 2 or 3, corresponding to the interval
; PI - 2*PI, we must return a negative value for the Sine.  If the value is
; in quadrants 1 or 3, we must subtract the reduced angle from 1 (PI/2).
; Algorithm:
;       FAC = (angle / (2*PI))*4      ; Yields number in 0.LE.FAC.LT.4
;       Save FAC
;       ARG = INT( FAC )            ; ARG = quadrant 0-3
;       Restore FAC
;       FAC = (FAC - ARG)/4         ; FAC = angle in range 0 - PI/2
;       IF quadrant = 1 or 3 THEN
;           FAC = 1 - FAC           ; FAC = PI/2 - angle
;       Calculate polynomial
;       IF quadrant = 2 or 3 THEN
;           Negate result           ; Negative for PI - 2*PI

;         LOW              HIGH (octal bytes)
; D.P. 0 = 0,0,0,0,0,0,000,000
; D.P. 1 = 0,0,0,0,0,0,000,201
; D.P. 2 = 0,0,0,0,0,0,000,202      ; Which implies that FAC = 202 for 2 and 3
; D.P. 3 = 0,0,0,0,0,0,100,202

	MOV	AX,word [@@SARG-1]
	CMP	AH,((130) and 0FFh)  ; ARG now has quadrant information
	PUSHF  ; Z set if we need to negate when done
	TEST	AH,((1) and 0FFh)  ; Now set NZ if in quadrant 1
	JNZ	@MATH1@_SIN40
	TEST	AL,((64) and 0FFh)  ; Set NZ if in quadrant 3
@MATH1@_SIN40:
	PUSHF  ; NZ if we must subtract from 1
	CALL	@MATH1@_RR2  ; FAC = X-INT(X) = angle MOD PI/2
	POPF
	JZ	@MATH1@_SIN50  ; Nothing more to do, calculate the SIN
	MOV	BX,@MATH1@_@SDP00  ; Point to a D.P. 1 (10^0)
	CALL	@MATH1@_@SMOVAC  ; ARG = 1
	CALL	@@SFSUBD  ; FAC = 1 - FAC = PI/2 - angle MOD PI/2
@MATH1@_SIN50:
	SUB	byte [@@SFAC],((2) and 0FFh)  ; FAC = FAC/4 = ( angle / 2*PI )
	JNB	@MATH1@_SIN51
	CALL	@@SDZERO  ;Return 0 if Underflow
@MATH1@_SIN51:
	CALL	@@SCSD  ; Convert DP reduced angle back to SP
	MOV	AL,byte [@@SFAC]  ;WILL SEE IF SMALL ENOUGH
;SUCH THAT X=SIN(X)
	CMP	AL,((116) and 0FFh)  ;IF FAC SMALLER THAN THIS JUST
	JNB	@MATH1@_SIN60
	MOV	DX,4059  ;2*PI
	MOV	BX,33609
	CALL	@@SFMULS
	JMP	@MATH1@_SIN65  ; Go set sign properly
@MATH1@_SIN60:
	MOV	BX,@MATH1@_@SSINCN  ;POINT TO HART 3341 COEFFS.
	CALL	@MATH1@_@SPOLYX  ;EVALUATE THE POLYNOMIAL
@MATH1@_SIN65:
	POPF  ;RECALL SIGN
	JNZ	@MATH1@_SIN70
	XOR	byte [@@SFAC-1],((128) and 0FFh)  ;FLIP SIGN
@MATH1@_SIN70:
	RET

; Converts FAC to double precision and reduces the result to a
