	CALL	@MATH1@_@SFMULD  ;X
@MATH1@_RR1:
	CALL	@MATH1@_RR3
@MATH1@_RR2:
	CALL	@@SFSUBD  ;INT(X)-X
	JMP	@@SNEG  ;X-INT(X)
@MATH1@_RR3:
	CALL	@@SVPSHF  ;SAVE X
	CALL	@MATH1@_@SDINT  ;($FAC)=INT(X)
	CALL	@MATH1@_@SMOVAF  ;SAVE IN ARG
	CALL	@MATH1@_@SVPOPF  ;FETCH X
	RET
@MATH1@_ONEARG:
