	POP	BX  ;[H,L]=POINTER AT VALUE #2
	MOV	DX,@SWPTMP  ;LOCATION OF VALUE #1
	CALL	@VMOVE  ;TRANSFER SWPTMP=VALUE #1 INTO VALUE #2'S
