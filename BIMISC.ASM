	JNZ	@BIMISC@_GFCERR  ;IF ITS CHANGED, ERROR
	POP	DX  ;[D,E]=POINTER AT VALUE #2
	POP	BX  ;[H,L]=TEXT POINTER
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;SAVE THE TEXT POINTER ON THE STACK
