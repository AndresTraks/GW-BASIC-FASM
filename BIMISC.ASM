@BIMISC@_GCLERC:	JMP	@CLEARC  ;IFE LABEL  GO TO CLEARC

;Syntax: CLEAR [[a][,b [,c]]]

; a is a relic of pre-fiveo memory management and is ignored
; b is the highest memory location available to BASIC-80
; b is the the number of bytes in the data segment for BASIC-86
; c is the number of bytes to be used as stack space by BASIC

@CLEAR:
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH
	XOR	AL,AL  ;Since FILTAB is reset below,
	MOV	byte [@NLONLY],AL  ; close all files - even file 0,
	CALL	@CLSALL  ; because of DYNAMIC FDB's
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF
	JZ	@BIMISC@_GCLERC  ;IF NO FORMULA JUST CLEAR
	CMP	AL,((44) and 0FFh)  ;ALLOW NO STRING SPACE
	JZ	@BIMISC@_CSKPCM
	CALL	@INTID2  ;Get Dummy Integer Parameter into [D,E]
	DEC	BX
	CALL	@CHRGTR  ;SEE IF ITS THE END
	JZ	@BIMISC@_GCLERC
@BIMISC@_CSKPCM:	CALL	@SYNCHR
	DB	44
	JZ	@BIMISC@_GCLERC
	MOV	DX,[@TOPMEM]  ;Use current top of memory as default
	CMP	AL,((44) and 0FFh)
	JZ	@BIMISC@_CLEARS  ;SHOULD FINISH THERE
	CALL	@BIMISC@_GETMPM  ;GET MEMORY SIZE PARAMETER
	PUSH	BX  ;save text pointer
end if
