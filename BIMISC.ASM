; SUBTTL TRAP ROUTINES - ON, OFF, STOP, INIT, REQUEST, FREE, RESET

;Trap flag bit definitions(Routines shift bits - don't change)

; PUBLIC	T_ON
	@T_ON=1  ;Trap on
; PUBLIC	T_STOP
	@T_STOP=2  ;Trap stop
; PUBLIC	T_REQ
	@T_REQ=4  ;Trap request

;TURN TRAP ON

; PUBLIC	ONTRP
@ONTRP:	CLI
	MOV	AL,byte [BX]
	AND	AL,((@T_REQ) and 0FFh)  ;LEAVE REQUEST BIT
	OR	AL,((@T_ON) and 0FFh)  ;ADD ON BIT
	CMP	AL,byte [BX]
	MOV	byte [BX],AL
	JZ	@BIMISC@_ONTRP0  ;NO CHANGE IN STATUS
	AND	AL,((@T_REQ) and 0FFh)
	JNZ	@BIMISC@_SETTP2  ;DELAYED TRAP REQUEST
@BIMISC@_ONTRP0:	STI
	RET

;TURN TRAP OFF

; PUBLIC	OFFTRP
@OFFTRP:	CLI
	MOV	AL,byte [BX]
	MOV	byte [BX],((0) and 0FFh)
	JMP	@BIMISC@_FRECHK  ;FREE OUTSTANDING REQUEST

;STOP TRAP

; PUBLIC	STPTRP
@STPTRP:	CLI
	MOV	AL,byte [BX]
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH
	OR	AL,((@T_STOP) and 0FFh)
	MOV	byte [BX],AL
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF
@BIMISC@_FRECHK:	XOR	AL,((@T_ON+@T_REQ) and 0FFh)  ;STOP OR OFF ACTIVE REQUEST?
	JZ	@BIMISC@_FRETP2  ;YES, FREE ACTIVE REQUEST COUNT
	STI
	RET

;RESET STOP ON TRAP

; PUBLIC	RSTTRP
@RSTTRP:	CLI
	MOV	AL,byte [BX]
	AND	AL,((@T_ON+@T_REQ) and 0FFh)
	CMP	AL,byte [BX]
	MOV	byte [BX],AL
	JNZ	@BIMISC@_SETCHK  ;IF NEW STATUS, CHECK FOR SETTRP
	STI
	RET

;REQUEST TRAP

; PUBLIC	REQTRP
@REQTRP:	CLI
	MOV	AL,byte [BX]
	AND	AL,((@T_ON) and 0FFh)
	JZ	@BIMISC@_REQTPX  ;TRAP NOT ON
	MOV	AL,byte [BX]
	OR	AL,((@T_REQ) and 0FFh)
	CMP	AL,byte [BX]
	JZ	@BIMISC@_REQTPX  ;NO CHANGE
	MOV	byte [BX],AL
@BIMISC@_SETCHK:	XOR	AL,((@T_ON+@T_REQ) and 0FFh)
	JZ	@BIMISC@_SETTP2  ;GO SET TRAP GLOBAL FLAG
@BIMISC@_REQTPX:	STI
	RET

;SET TRAP GLOBAL FLAG

