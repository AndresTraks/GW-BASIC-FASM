; PUBLIC	ERASE
@ERASE:
	MOV	AL,((1) and 0FFh)
	MOV	byte [@SUBFLG],AL  ;THAT THIS IS "ERASE" CALLING PTRGET
	CALL	@PTRGET  ;GO FIND OUT WHERE TO ERASE
	JNZ	@BIMISC@_GFCERR  ;PTRGET DID NOT FIND VARIABLE!
	PUSH	BX  ;SAVE THE TEXT POINTER
	MOV	byte [@SUBFLG],AL  ;ZERO OUT SUBFLG TO RESET "ERASE" FLAG
	MOV	BH,CH  ;[B,C]=START OF ARRAY TO ERASE
	MOV	BL,CL
	DEC	CX  ;BACK UP TO THE FRONT
	DEC	CX  ;NO VALUE TYPE WITHOUT LENGTH=2
	DEC	CX  ;BACK UP ONE MORE
@BIMISC@_LPBKNM:	MOV	SI,CX
	MOV	AL,[SI]  ;GET A CHARACTER. ONLY THE COUNT HAS HIGH BIT=0
	DEC	CX  ;SO LOOP UNTIL WE SKIP OVER THE COUNT
	OR	AL,AL  ;SKIP ALL THE EXTRA CHARACTERS
	JNS	@BIMISC@_@Q@QL006
	JMP	@BIMISC@_LPBKNM
@BIMISC@_@Q@QL006:
	DEC	CX
	DEC	CX
	ADD	BX,DX  ;[H,L]=THE END OF THIS ARRAY ENTRY
	XCHG	BX,DX  ;[D,E]=END OF THIS ARRAY
	MOV	BX,[@STREND]  ;[H,L]=LAST LOCATION TO MOVE UP
@BIMISC@_ERSLOP:	CMP	BX,DX  ;SEE IF THE LAST LOCATION IS GOING TO BE MOVED
	MOV	SI,DX
	MOV	AL,[SI]  ;DO THE MOVE
	MOV	DI,CX
	STOSB
	LAHF
	INC	DX  ;UPDATE THE POINTERS
	SAHF
	LAHF
	INC	CX
	SAHF
	JNZ	@BIMISC@_ERSLOP  ;MOVE THE REST
	DEC	CX
	MOV	BX,CX  ;SETUP THE NEW STORAGE END POINTER
	MOV	[@STREND],BX
	POP	BX  ;GET BACK THE TEXT POINTER
	MOV	AL,byte [BX]  ;SEE IF MORE ERASURES NEEDED
	CMP	AL,((44) and 0FFh)  ;ADDITIONAL VARIABLES DELIMITED BY COMMA
	JZ	$+3
	RET  ;ALL DONE IF NOT
	CALL	@CHRGTR
	JMP	@ERASE

