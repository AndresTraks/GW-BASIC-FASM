@BIMISC@_CLEARS:	DEC	BX  ;BACK UP
	CALL	@CHRGTR  ;GET CHAR
	PUSH	DX  ;SAVE NEW HIGH MEM
	JZ	@BIMISC@_CDFSTK  ;USE SAME STACK SIZE
	CALL	@SYNCHR
