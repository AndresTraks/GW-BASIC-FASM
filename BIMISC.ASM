@BIMISC@_GOTRP2:
	PUSH	CX  ;SAVE STATE IN CASE ADDR IS ZERO
	LAHF
	INC	BX
	SAHF
	MOV	DL,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	DH,byte [BX]  ;DE=TRAP GOSUB ADDR
	LAHF
	DEC	BX
	SAHF
	LAHF
	DEC	BX  ;HL:=TRAP FLAG
	SAHF
	MOV	AL,DH
	OR	AL,DL
	POP	CX  ;RESTORE COUNTER
	JZ	@BIMISC@_GOTRP1  ;GOSUB ADDR NOT SPECIFIED,TRY NEXT RTRAP
