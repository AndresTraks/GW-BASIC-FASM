	CMP	AL,((@T_ON+@T_REQ) and 0FFh)
	JZ	@BIMISC@_GOTRP2  ;ENABLED AND REQUESTED
@BIMISC@_GOTRP1:	LAHF
	INC	BX  ;NEXT ENTRY
	SAHF
	LAHF
	INC	BX
	SAHF
	LAHF
	INC	BX
	SAHF
	DEC	CH
	JNZ	@BIMISC@_GOTRPL
@BIMISC@_GOTRPX:	POP	BX  ;RESTORE TEXT POINTER
	RET

