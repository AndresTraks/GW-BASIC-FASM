; TITLE   BIPRTU  BASIC Interpreter PRINT USING Driver/WHG

@BIPRTU@_TRSHHC=0
@BIPRTU@_NECPPC=0

; SUBTTL  PRINT USING DRIVER

; COME HERE AFTER THE "USING" CLAUSE IN A PRINT STATEMENT
; IS RECOGNIZED. THE IDEA IS TO SCAN THE USING STRING UNTIL
; THE VALUE LIST IS EXHAUSTED, FINDING STRING AND NUMERIC
; FIELDS TO PRINT VALUES OUT OF THE LIST IN,
; AND JUST OUTPUTING ANY CHARACTERS THAT AREN'T PART OF
; A PRINT FIELD.

end if
; EXTRN	FACLO:WORD

; EXTRN	USFLG:WORD
if @GW_PASS = 1

; Code segment ( terminated by END at bottom of file )

; EXTRN	CHRGTR:NEAR,SYNCHR:NEAR
; EXTRN	CHKSTR:NEAR,CRDO:NEAR,FCERR:NEAR,FRETM2:NEAR,FRMCHK:NEAR
; EXTRN	FRMEVL:NEAR
; EXTRN	OUTDO:NEAR,PUFOUT:NEAR,SNERR:NEAR,STROUT:NEAR,STRPRT:NEAR
; EXTRN	LEFTUS:NEAR
; PUBLIC	PRINUS
	@BIPRTU@_CSTRNG=92
	@BIPRTU@_CURNCY=36  ;USE DOLLAR SIGN AS DEFAULT

@PRINUS:	CALL	@FRMCHK  ;EVALUATE THE "USING" STRING
	CALL	@CHKSTR  ;MAKE SURE IT IS A STRING
	CALL	@SYNCHR
	DB	59  ;MUST BE DELIMITED BY A SEMI-COLON
	XCHG	BX,DX  ;[D,E]=TEXT POINTER
	MOV	BX,[@FACLO]  ;GET POINTER TO "USING" STRING DESCRIPTOR
	JMP	@BIPRTU@_INIUS  ;DONT POP OFF OR LOOK AT USFLG
@BIPRTU@_REUSST:	MOV	AL,byte [@USFLG]  ;DID WE PRINT OUT A VALUE LAST SCAN?
	OR	AL,AL  ;SET CC'S
	JZ	@BIPRTU@_FCERR3  ;NO, GIVE ERROR
	POP	DX  ;[D,E]=POINTER TO "USING" STRING DESCRIPTOR
	XCHG	BX,DX  ;[D,E]=TEXT POINTER
@BIPRTU@_INIUS:	PUSH	BX  ;SAVE THE POINTER TO "USING" STRING DESCRIPTOR
	XOR	AL,AL  ;INITIALLY INDICATE THERE ARE MORE
;VALUES IN THE VALUE LIST
	MOV	byte [@USFLG],AL  ;RESET THE FLAG THAT SAYS VALUES PRINTED
	INC	AL  ;TURN THE ZERO FLAG OFF
;TO INDICATE THE VALUE LIST HASN'T ENDED
	PUSHF  ;SAVE FLAG INDICATING WHETHER THE VALUE
;LIST HAS ENDED
	PUSH	DX  ;SAVE THE TEXT POINTER INTO THE VALUE LIST
	MOV	CH,byte [BX]  ;[B]=LENGTH OF THE "USING" STRING
	INC	CH  ;Is the using string null?
	DEC	CH
@BIPRTU@_FCERR3:	JNZ	@BIPRTU@_@Q@QL000
	JMP	@FCERR  ;IF SO, "ILLEGAL FUNCTION CALL"
@BIPRTU@_@Q@QL000:
	INC	BX  ;[H,L]=POINTER AT THE "USING" STRING'S
	MOV	BX,[BX]  ;DATA
	JMP	@BIPRTU@_PRCCHR  ;GO INTO THE LOOP TO SCAN
;THE "USING" STRING
;NECPPC does not have string formatter
; because of ROM space
@BIPRTU@_BGSTRF:	MOV	DL,CH  ;SAVE THE "USING" STRING CHARACTER COUNT
	PUSH	BX  ;SAVE THE POINTER INTO THE "USING" STRING
	MOV	CL,((2) and 0FFh)  ;THE \\ STRING FIELD HAS 2 PLUS
;NUMBER OF ENCLOSED SPACES WIDTH
@BIPRTU@_LPSTRF:	MOV	AL,byte [BX]  ;GET THE NEXT CHARACTER
	INC	BX  ;ADVANCE THE POINTER AT THE "USING" STRING
;DATA
	CMP	AL,((@BIPRTU@_CSTRNG) and 0FFh)  ;THE FIELD TERMINATOR?
	JNZ	@BIPRTU@_@Q@QL001
	JMP	@BIPRTU@_ISSTRF  ;GO EVALUATE A STRING AND PRINT
@BIPRTU@_@Q@QL001:
	CMP	AL,((" ") and 0FFh)  ;A FIELD EXTENDER?
	JNZ	@BIPRTU@_NOSTRF  ;IF NOT, ITS NOT A STRING FIELD
	INC	CL  ;INCREMENT THE FIELD WIDTH
;SEE IF THERE ARE MORE CHARACTERS
	DEC	CH
	JNZ	@BIPRTU@_LPSTRF  ;KEEP SCANNING FOR THE FIELD TERMINATOR

; SINCE  STRING FIELD WASN'T FOUND, THE "USING" STRING
; CHARACTER COUNT AND THE POINTER INTO IT'S DATA MUST
; BE RESTORED AND THE "\" PRINTED

@BIPRTU@_NOSTRF:	POP	BX  ;RESTORE THE POINTER INTO "USING" STRING'S DATA
	MOV	CH,DL  ;RESTORE THE "USING" STRING CHARACTER COUNT
	MOV	AL,((@BIPRTU@_CSTRNG) and 0FFh)  ;RESTORE THE CHARACTER

; HERE TO PRINT THE CHARACTER IN [A] SINCE IT WASN'T PART OF ANY FIELD

@BIPRTU@_NEWUCH:	CALL	@BIPRTU@_PLSPRT  ;IF A "+" CAME BEFORE THIS CHARACTER
;MAKE SURE IT GETS PRINTED
	CALL	@OUTDO  ;PRINT THE CHARACTER THAT WASN'T
;PART OF A FIELD

@BIPRTU@_PRCCHR:	XOR	AL,AL  ;SET [D,E]=0 SO IF WE DISPATCH
	MOV	DL,AL  ;SOME FLAGS ARE ALREADY ZEROED
	MOV	DH,AL  ;DON'T PRINT "+" TWICE
@BIPRTU@_PLSFIN:	CALL	@BIPRTU@_PLSPRT  ;ALLOW FOR MULTIPLE PLUSES
;IN A ROW
	MOV	DH,AL  ;SET "+" FLAG
	MOV	AL,byte [BX]  ;GET A NEW CHARACTER
	INC	BX
	CMP	AL,(("!") and 0FFh)  ;CHECK FOR A SINGLE CHARACTER
	JNZ	@BIPRTU@_@Q@QL002
	JMP	@BIPRTU@_SMSTRF  ;STRING FIELD
@BIPRTU@_@Q@QL002:
	CMP	AL,(("#") and 0FFh)  ;CHECK FOR THE START OF A NUMERIC FIELD 
	JZ	@BIPRTU@_NUMNUM  ;GO SCAN IT
	CMP	AL,(("&") and 0FFh)  ;SEE IF ITS A VARIABLE LENGTH STRING FIELD
	JNZ	@BIPRTU@_@Q@QL003
	JMP	@BIPRTU@_VARSTR  ;GO PRINT ENTIRE STRING
@BIPRTU@_@Q@QL003:
	DEC	CH  ;ALL THE OTHER POSSIBILITIES
;REQUIRE AT LEAST 2 CHARACTERS
	JNZ	@BIPRTU@_@Q@QL004
	JMP	@BIPRTU@_REUSIN  ;IF THE VALUE LIST IS NOT EXHAUSTED
@BIPRTU@_@Q@QL004:
;GO REUSE "USING" STRING
	CMP	AL,(("+") and 0FFh)  ;A LEADING "+" ?
	MOV	AL,((8) and 0FFh)  ;SETUP [D] WITH THE PLUS-FLAG ON IN
	JZ	@BIPRTU@_PLSFIN  ;CASE A NUMERIC FIELD STARTS
	DEC	BX  ;POINTER HAS ALREADY BEEN INCREMENTED
	MOV	AL,byte [BX]  ;GET BACK THE CURRENT CHARACTER
	INC	BX  ;REINCREMENT THE POINTER
	CMP	AL,((".") and 0FFh)  ;NUMERIC FIELD WITH TRAILING DIGITS
	JZ	@BIPRTU@_DOTNUM  ;IF SO GO SCAN WITH [E]=
;NUMBER OF DIGITS BEFORE THE "."=0
	CMP	AL,(("_") and 0FFh)  ;CHECK FOR LITERAL CHARACTER DECLARATION
	JNZ	@BIPRTU@_@Q@QL005
	JMP	@BIPRTU@_LITCHR
@BIPRTU@_@Q@QL005:
	CMP	AL,((@BIPRTU@_CSTRNG) and 0FFh)  ;CHECK FOR A BIG STRING FIELD STARTER
	JZ	@BIPRTU@_BGSTRF  ;GO SEE IF IT REALLY IS A STRING FIELD
	CMP	AL,byte [BX]  ;SEE IF THE NEXT CHARACTER MATCHES THE
;CURRENT ONE
	JNZ	@BIPRTU@_NEWUCH  ;IF NOT, CAN'T HAVE $$ OR ** SO ALL THE
;POSSIBILITIES ARE EXHAUSTED
	CMP	AL,((@BIPRTU@_CURNCY) and 0FFh)  ;IS IT $$ ?
	JZ	@BIPRTU@_DOLRNM  ;GO SET UP THE FLAG BIT
	CMP	AL,(("*") and 0FFh)  ;IS IT ** ?
	JNZ	@BIPRTU@_NEWUCH  ;IF NOT, ITS NOT PART
;OF A FIELD SINCE ALL THE POSSIBILITIES
;HAVE BEEN TRIED
	INC	BX  ;CHECK FOR $
	MOV	AL,CH  ;SEE IF THE "USING" STRING IS LONG
	CMP	AL,((2) and 0FFh)  ;ENOUGH FOR THE SPECIAL CASE OF
	JB	@BIPRTU@_NOTSPC  ; **$
	MOV	AL,byte [BX]
	CMP	AL,((@BIPRTU@_CURNCY) and 0FFh)  ;IS THE NEXT CHARACTER $ ?
@BIPRTU@_NOTSPC:	MOV	AL,((32) and 0FFh)  ;SET THE ASTERISK BIT
	JNZ	@BIPRTU@_SPCNUM  ;IF IT NOT THE SPECIAL CASE, DON'T
;SET THE DOLLAR SIGN FLAG
	DEC	CH  ;DECREMENT THE "USING" STRING CHARACTER COUNT
;TO TAKE THE $ INTO CONSIDERATION
	INC	DL  ;INCREMENT THE FIELD WIDTH FOR THE
;FLOATING DOLLAR SIGN
	DB	190  ; SKIP	;"CPI" OVER THE NEXT BYTE
;MVI SI,  IN 8086
@BIPRTU@_DOLRNM:	XOR	AL,AL  ;CLEAR [A]
	ADD	AL,((16) and 0FFh)  ;SET BIT FOR FLOATING DOLLAR SIGN FLAG
	INC	BX  ;POINT BEYOND THE SPECIAL CHARACTERS
@BIPRTU@_SPCNUM:	INC	DL  ;SINCE TWO CHARACTERS SPECIFY
;THE FIELD SIZE, INITIALIZE [E]=1
	ADD	AL,DH  ;PUT NEW FLAG BITS IN [A]
	MOV	DH,AL  ;INTO [D]. THE PLUS FLAG MAY HAVE
;ALREADY BEEN SET
@BIPRTU@_NUMNUM:	INC	DL  ;INCREMENT THE NUMBER OF DIGITS BEFORE
;THE DECIMAL POINT
	MOV	CL,((0) and 0FFh)  ;SET THE NUMBER OF DIGITS AFTER
;THE DECIMAL POINT = 0
	DEC	CH  ;SEE IF THERE ARE MORE CHARACTERS
	JZ	@BIPRTU@_ENDNUS  ;IF NOT, WE ARE DONE SCANNING THIS
;NUMERIC FIELD
	MOV	AL,byte [BX]  ;GET THE NEW CHARACTER
	INC	BX  ;ADVANCE THE POINTER AT THE "USING" STRING DATA
	CMP	AL,((".") and 0FFh)  ;DO WE HAVE TRAILING DIGITS?
	JZ	@BIPRTU@_AFTDOT  ;IF SO, USE SPECIAL SCAN LOOP
	CMP	AL,(("#") and 0FFh)  ;MORE LEADING DIGITS ?
	JZ	@BIPRTU@_NUMNUM  ;INCREMENT THE COUNT AND KEEP SCANNING
	CMP	AL,((44) and 0FFh)  ;DOES HE WANT A COMMA
;EVERY THREE DIGITS?
	JNZ	@BIPRTU@_FINNUM  ;NO MORE LEADING DIGITS, CHECK FOR ^^^
	MOV	AL,DH  ;TURN ON THE COMMA BIT
	OR	AL,((64) and 0FFh)
	MOV	DH,AL
	JMP	@BIPRTU@_NUMNUM  ;GO SCAN SOME MORE

; HERE WHEN A "." IS SEEN IN THE "USING" STRING
; IT STARTS A NUMERIC FIELD IF AND ONLY IF
; IT IS FOLLOWED BY A "#"

@BIPRTU@_DOTNUM:	MOV	AL,byte [BX]  ;GET THE CHARACTER THAT FOLLOWS
	CMP	AL,(("#") and 0FFh)  ;IS THIS A NUMERIC FIELD?
	MOV	AL,((".") and 0FFh)  ;IF NOT, GO BACK AND PRINT "."
	JZ	@BIPRTU@_@Q@QL006
	JMP	@BIPRTU@_NEWUCH
@BIPRTU@_@Q@QL006:
	MOV	CL,((1) and 0FFh)  ;INITIALIZE THE NUMBER OF
;DIGITS AFTER THE DECIMAL POINT
	INC	BX
@BIPRTU@_AFTDOT:	INC	CL  ;INCREMENT THE NUMBER OF DIGITS
;AFTER THE DECIMAL POINT
	DEC	CH  ;SEE IF THE "USING" STRING HAS MORE
	JZ	@BIPRTU@_ENDNUS  ;CHARACTERS, AND IF NOT, STOP SCANNING
	MOV	AL,byte [BX]  ;GET THE NEXT CHARACTER
	INC	BX
	CMP	AL,(("#") and 0FFh)  ;MORE DIGITS AFTER THE DECIMAL POINT?
	JZ	@BIPRTU@_AFTDOT  ;IF SO, INCREMENT THE COUNT AND KEEP
;SCANNING

; CHECK FOR THE "^^^^" THAT INDICATES SCIENTIFIC NOTATION

@BIPRTU@_FINNUM:	PUSH	DX  ;SAVE [D]=FLAGS AND [E]=LEADING DIGITS
	MOV	DX,@BIPRTU@_NOTSCI  ;PLACE TO GO IF ITS NOT SCIENTIFIC
	PUSH	DX  ;NOTATION
	MOV	DH,BH  ;REMEMBER [H,L] IN CASE
	MOV	DL,BL  ;ITS NOT SCIENTIFIC NOTATION
	CMP	AL,(("^") and 0FFh)  ;IS THE FIRST CHARACTER "^" ?
	JZ	$+3
	RET
	CMP	AL,byte [BX]  ;IS THE SECOND CHARACTER "^" ?
	JZ	$+3
	RET
	INC	BX
	CMP	AL,byte [BX]  ;IS THE THIRD CHARACTER "^" ?
	JZ	$+3
	RET
	INC	BX
	CMP	AL,byte [BX]  ;IS THE FOURTH CHARACTER "^" ?
	JZ	$+3
	RET
	INC	BX
	MOV	AL,CH  ;WERE THERE ENOUGH CHARACTERS FOR "^^^^"
	SUB	AL,((4) and 0FFh)  ;IT TAKES FOUR
	JNB	$+3
	RET
	POP	DX  ;POP OFF THE NOTSCI RETURN ADDRESS
	POP	DX  ;GET BACK [D]=FLAGS [E]=LEADING DIGITS
	MOV	CH,AL  ;MAKE [B]=NEW CHARACTER COUNT
	INC	DH  ;TURN ON THE SCIENTIFIC NOTATION FLAG
	INC	BX
	JMP	@BIPRTU@_ENDNUS
@BIPRTU@_NOTSCI:	XCHG	BX,DX  ;RESTORE THE OLD [H,L]
	POP	DX  ;GET BACK [D]=FLAGS [E]=LEADING DIGITS
@BIPRTU@_ENDNUS:	MOV	AL,DH  ;IF THE LEADING PLUS FLAG IS ON
	DEC	BX
	INC	DL  ;INCLUDE LEADING "+" IN NUMBER OF DIGITS
	AND	AL,((8) and 0FFh)  ;DON'T CHECK FOR A TRAILING SIGN
	JNZ	@BIPRTU@_ENDNUM  ;ALL DONE WITH THE FIELD IF SO
;IF THERE IS A LEADING PLUS
	DEC	DL  ;NO LEADING PLUS SO DON'T INCREMENT THE
;NUMBER OF DIGITS BEFORE THE DECIMAL POINT
	MOV	AL,CH
	OR	AL,AL  ;SEE IF THERE ARE MORE CHARACTERS
	JZ	@BIPRTU@_ENDNUM  ;IF NOT, STOP SCANNING
	MOV	AL,byte [BX]  ;GET THE CURRENT CHARACTER
	SUB	AL,(("-") and 0FFh)  ;TRAIL MINUS?
	JZ	@BIPRTU@_SGNTRL  ;SET THE TRAILING SIGN FLAG
	CMP	AL,(("+"-"-") and 0FFh)  ;A TRAILING PLUS?
	JNZ	@BIPRTU@_ENDNUM  ;IF NOT, WE ARE DONE SCANNING
	MOV	AL,((8) and 0FFh)  ;TURN ON THE POSITIVE="+" FLAG
@BIPRTU@_SGNTRL:	ADD	AL,((4) and 0FFh)  ;TURN ON THE TRAILING SIGN FLAG
	ADD	AL,DH  ;INCLUDE WITH OLD FLAGS
	MOV	DH,AL
	DEC	CH  ;DECREMENT THE "USING" STRING CHARACTER
;COUNT TO ACCOUNT FOR THE TRAILING SIGN
@BIPRTU@_ENDNUM:	POP	BX  ;[H,L]=THE OLD TEXT POINTER
	POPF  ;POP OFF FLAG THAT SAYS WHETHER THERE
;ARE MORE VALUES IN THE VALUE LIST
	JZ	@BIPRTU@_FLDFIN  ;IF NOT, WE ARE DONE WITH THE "PRINT"
	PUSH	CX  ;SAVE [B]=# OF CHARACTERS REMAINING IN
;"USING" STRING AND [C]=TRAILING DIGITS
	PUSH	DX  ;SAVE [D]=FLAGS AND [E]=LEADING DIGITS
	CALL	@FRMEVL  ;READ A VALUE FROM THE VALUE LIST
	POP	DX  ;[D]=FLAGS & [E]=# OF LEADING DIGITS
	POP	CX  ;[B]=# CHARACTER LEFT IN "USING" STRING
;[C]=NUMBER OF TRAILING DIGITS
	PUSH	CX  ;SAVE [B] FOR ENTERING SCAN AGAIN
	PUSH	BX  ;SAVE THE TEXT POINTER
	MOV	CH,DL  ;[B]=# OF LEADING DIGITS
	MOV	AL,CH  ;MAKE SURE THE TOTAL NUMBER OF DIGITS
	ADD	AL,CL  ;DOES NOT EXCEED TWENTY-FOUR
	CMP	AL,((25) and 0FFh)
	JNAE	@BIPRTU@_@Q@QL007
	JMP	@FCERR  ;IF SO, "ILLEGAL FUNCTION CALL"
@BIPRTU@_@Q@QL007:
	MOV	AL,DH  ;[A]=FLAG BITS
	OR	AL,((128) and 0FFh)  ;TURN ON THE "USING" BIT
	CALL	@PUFOUT  ;PRINT THE VALUE
; EXTRN	DSOUT:NEAR
	CALL	@DSOUT  ;PRINT FROM THE DATA SEGMENT
@BIPRTU@_FNSTRF:	POP	BX  ;GET BACK THE TEXT POINTER
	DEC	BX  ;SEE WHAT THE TERMINATOR WAS
	CALL	@CHRGTR
	STC  ;SET FLAG THAT CRLF IS DESIRED
	JZ	@BIPRTU@_CRDNUS  ;IF IT WAS A END-OF-STATEMENT
;FLAG THAT THE VALUE LIST ENDED
;AND THAT  CRLF SHOULD BE PRINTED
	MOV	byte [@USFLG],AL  ;FLAG THAT VALUE HAS BEEN PRINTED.
;DOESNT MATTER IF ZERO SET, [A]
;MUST BE NON-ZERO OTHERWISE
	CMP	AL,((59) and 0FFh)  ;A SEMI-COLON?
	JZ	@BIPRTU@_SEMUSN  ;A LEGAL DELIMITER
	CMP	AL,((44) and 0FFh)  ;A COMMA ?
	JZ	@BIPRTU@_@Q@QL008
	JMP	@SNERR  ;THE DELIMETER WAS ILLEGAL
@BIPRTU@_@Q@QL008:
@BIPRTU@_SEMUSN:	CALL	@CHRGTR  ;IS THERE ANOTHER VALUE?
@BIPRTU@_CRDNUS:	POP	CX  ;[B]=CHARACTERS REMAINING IN "USING" STRING
	XCHG	BX,DX  ;[D,E]=TEXT POINTER
	POP	BX  ;[H,L]=POINT AT THE "USING" STRING
	PUSH	BX  ;DESCRIPTOR. RESAVE IT.
	PUSHF  ;SAVE THE FLAG THAT INDICATES
;WHETHER OR NOT THE VALUE LIST TERMINATED
	PUSH	DX  ;SAVE THE TEXT POINTER

; SINCE FRMEVL MAY HAVE FORCED GARBAGE COLLECTION
; WE HAVE TO USE THE NUMBER OF CHARACTERS ALREADY SCANNED
; AS AN OFFSET TO THE POINTER TO THE "USING" STRING'S DATA
; TO GET A NEW POINTER TO THE REST OF THE CHARACTERS TO
; BE SCANNED

	MOV	AL,byte [BX]  ;GET THE "USING" STRING'S LENGTH
	SUB	AL,CH  ;SUBTRACT THE NUMBER OF CHARACTERS
;ALREADY SCANNED
	INC	BX  ;[H,L]=POINTER AT
	MOV	DH,((0) and 0FFh)  ;SETUP [D,E] AS A DOUBLE BYTE OFFSET
	MOV	DL,AL
	MOV	BX,[BX]  ;THE "USING" STRING'S STRING DATA
	ADD	BX,DX  ;ADD ON THE OFFSET TO GET
;THE NEW POINTER
@BIPRTU@_CHKUSI:	MOV	AL,CH  ;[A]=THE NUMBER OF CHARACTERS LEFT TO SCAN
	OR	AL,AL  ;SEE IF THERE ARE ANY LEFT
	JZ	@BIPRTU@_@Q@QL009
	JMP	@BIPRTU@_PRCCHR  ;IF SO, KEEP SCANNING
@BIPRTU@_@Q@QL009:
	JMP	@BIPRTU@_FINUSI  ;SEE IF THERE ARE MORE VALUES
@BIPRTU@_REUSIN:	CALL	@BIPRTU@_PLSPRT  ;PRINT A "+" IF NECESSARY
	CALL	@OUTDO  ;PRINT THE FINAL CHARACTER
@BIPRTU@_FINUSI:	POP	BX  ;POP OFF THE TEXT POINTER
	POPF  ;POP OFF THE INDICATOR OF WHETHER OR NOT
;THE VALUE LIST HAS ENDED
	JZ	@BIPRTU@_@Q@QL010
	JMP	@BIPRTU@_REUSST  ;IF NOT, REUSE THE "USING" STRING
@BIPRTU@_@Q@QL010:
@BIPRTU@_FLDFIN:	JNB	@BIPRTU@_@Q@QL011
	CALL	@CRDO  ;IF NOT COMMA OR SEMI-COLON
@BIPRTU@_@Q@QL011:
;ENDED THE VALUE LIST
;PRINT A CRLF
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;SAVE THE TEXT POINTER
;[H,L]=POINT AT THE "USING" STRING'S
;DESCRIPTOR
	CALL	@FRETM2  ;FINALLY FREE IT UP
	POP	BX  ;GET BACK THE TEXT POINTER
; EXTRN	FINPRT:NEAR
	JMP	@FINPRT  ;ZERO [PTRFIL]

; HERE TO HANDLE A LITERAL CHARACTER IN THE USING STRING PRECEDED
; BY "_"

@BIPRTU@_LITCHR:	CALL	@BIPRTU@_PLSPRT  ;PRINT PREVIOUS "+" IF ANY
	DEC	CH  ;DECREMENT COUNT FOR ACTUAL CHARACTER
	MOV	AL,byte [BX]  ;FETCH LITERAL CHARACTER
	INC	BX
	CALL	@OUTDO
	JMP	@BIPRTU@_CHKUSI  ;GO SEE IF USING STRING ENDED

; HERE TO HANDLE VARIABLE LENGTH STRING FIELD SPECIFIED WITH "&"

@BIPRTU@_VARSTR:	MOV	CL,((0) and 0FFh)  ;SET LENGTH TO 0 TO FLAG VARIABLE LENGTH
	JMP	@BIPRTU@_ISSTR1
;NECPPC does not have string formatter
; because of ROM space

; HERE WHEN THE "!" INDICATING A SINGLE CHARACTER
; STRING FIELD HAS BEEN SCANNED

@BIPRTU@_SMSTRF:	MOV	CL,((1) and 0FFh)  ;SET THE FIELD WIDTH TO 1
	JMP	@BIPRTU@_ISSTR1
@BIPRTU@_ISSTRF:	POP	AX  ;GET RID OF THE [H,L] THAT WAS BEING
;SAVED IN CASE THIS WASN'T A STRING FIELD
@BIPRTU@_ISSTR1:	DEC	CH  ;DECREMENT THE "USING" STRING CHARACTER COUNT
	CALL	@BIPRTU@_PLSPRT  ;PRINT A "+" IF ONE CAME BEFORE THE FIELD
	POP	BX  ;TAKE OFF THE TEXT POINTER
	POPF  ;TAKE OF THE FLAG WHICH SAYS
;WHETHER THERE ARE MORE VALUES IN THE
;VALUE LIST
	JZ	@BIPRTU@_FLDFIN  ;IF THERE ARE NO MORE VALUES
;THEN WE ARE DONE
	PUSH	CX  ;SAVE [B]=NUMBER OF CHARACTERS YET TO
;BE SCANNED IN "USING" STRING
	CALL	@FRMEVL  ;READ A VALUE
	CALL	@CHKSTR  ;MAKE SURE ITS A STRING
	POP	CX  ;[C]=FIELD WIDTH
	PUSH	CX  ;RESAVE [B]
	PUSH	BX  ;SAVE THE TEXT POINTER
	MOV	BX,[@FACLO]  ;GET A POINTER TO THE DESCRIPTOR
	MOV	CH,CL  ;[B]=FIELD WIDTH
	MOV	CL,((0) and 0FFh)  ;SET UP FOR "LEFT$"
	MOV	AL,CH  ;GET FIELD WITH IN [A]
	PUSH	AX  ;SAVE THE FIELD WIDTH FOR SPACE PADDING
	MOV	AL,CH  ;SEE IF VARIABLE LENGTH FIELD
	OR	AL,AL
	JZ	@BIPRTU@_@Q@QL012
	CALL	@LEFTUS
@BIPRTU@_@Q@QL012:
	CALL	@STRPRT  ;PRINT THE STRING
	MOV	BX,[@FACLO]  ;SEE IF IT NEEDS TO BE PADDED
	POP	AX  ;[A]=FIELD WIDTH
	OR	AL,AL  ;IF FIELD LENGTH IS 0 MUST BE "&" SO
	JNZ	@BIPRTU@_@Q@QL013
	JMP	@BIPRTU@_FNSTRF  ;DONT PRINT ANY TRAILING SPACES
@BIPRTU@_@Q@QL013:
	SUB	AL,byte [BX]  ;[A]=AMOUNT OF PADDING NEEDED
	MOV	CH,AL
	MOV	AL,((" ") and 0FFh)  ;SETUP THE PRINT CHARACTER
	INC	CH  ;DUMMY INCREMENT OF NUMBER OF SPACES
@BIPRTU@_UPRTSP:	DEC	CH  ;SEE IF MORE SPACES
	JNZ	@BIPRTU@_@Q@QL014
	JMP	@BIPRTU@_FNSTRF  ;NO, GO SEE IF THE VALUE LIST ENDED AND
@BIPRTU@_@Q@QL014:
;RESUME SCANNING
	CALL	@OUTDO  ;PRINT A SPACE
	JMP	@BIPRTU@_UPRTSP  ;AND LOOP PRINTING THEM

; WHEN A "+" IS DETECTED IN THE "USING" STRING
; IF A NUMERIC FIELD FOLLOWS A BIT IN [D] SHOULD
; BE SET, OTHERWISE "+" SHOULD BE PRINTED.
; SINCE DECIDING WHETHER A NUMERIC FIELD FOLLOWS IS VERY
; DIFFICULT, THE BIT IS ALWAYS SET IN [D].
; AT THE POINT IT IS DECIDED A CHARACTER IS NOT PART
; OF A NUMERIC FIELD, THIS ROUTINE IS CALLED TO SEE
; IF THE BIT IN [D] IS SET, WHICH MEANS
; A PLUS PRECEDED THE CHARACTER AND SHOULD BE
; PRINTED.

@BIPRTU@_PLSPRT:	PUSH	AX  ;SAVE THE CURRENT CHARACTER
	MOV	AL,DH  ;CHECK THE PLUS BIT
