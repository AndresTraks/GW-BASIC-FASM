; SUBTTL FILINP AND FILGET -- SCAN A FILE NUMBER AND SETUP PTRFIL

; EXTRN	FILINP:NEAR,FILSCN:NEAR,FILSET:NEAR

; SUBTTL FILSCN, FILFRM, AND FILIDX

; SUBTTL  Conversion Routines
@MKI@S:	MOV	AL,((2) and 0FFh)  ;VALUE TYPE FOR INTEGER AND NUMBER
;OF CHARACTERS RESULT WILL NEED
	DB	185  ; SKIP	;SKIP NEXT TWO BYTES WITH "LXI  B,"
@MKS@S:	MOV	AL,((4) and 0FFh)  ;VALUE TYPE OF SINGLE PRECISION
	DB	185  ; SKIP	;SKIP NEXT TWO BYTES
@MKD@S:	MOV	AL,((8) and 0FFh)  ;VALUE TYPE OF DOUBLE-PRECISION
	PUSH	AX  ;SAVE THE NUMBER OF BYTES OF
;STRING SPACE WE NEED
	CALL	@DOCNVF  ;CONVERT FAC TO PROPER TYPE
	POP	AX  ;GET THE NUMBER OF BYTES NEEDED
	CALL	@STRINI  ;GET A PLACE FOR THE STRING DATA
end if
; EXTRN	DSCPTR:WORD
if @GW_PASS = 1
	MOV	BX,[@DSCPTR]  ;POINT TO THE PLACE TO STORE THE DATA
	CALL	@VMOVMF  ;MOVE THE FAC VALUE INTO THE STRING CREATION
	JMP	@FINBCK

@CVI:	MOV	AL,((1) and 0FFh)  ;SET [A] TO BE VALTYP-1
	DB	185  ; SKIP	;SKIP THE NEXT TWO BYTES WITH "LXI B,"
@CVS:	MOV	AL,((3) and 0FFh)  ;ALSO SET [A] TO NUMBER OF CHARACTERS REQUIRED -1
	DB	185  ; SKIP	;SKIP THE NEXT TWO BYTES
@CVD:	MOV	AL,((7) and 0FFh)  ;DOUBLE PRECISION VALUE TYPE -1
	PUSH	AX  ;SAVE THE VALTYP
	CALL	@FRESTR  ;MAKE SURE THE ARGUMENT IS A STRING
;AND GET A POINTER TO THE DESCRIPTOR
	POP	AX  ;GET BACK NUMBER OF CHARACTERS REQUIRED-1
	CMP	AL,byte [BX]  ;MAKE SURE THE STRING IS LONGER THAN THAT
	JNAE	@DSKCOM@_@Q@QL000
	JMP	@FCERR  ;IF NOT, "ILLEGAL FUNCTION CALL"
@DSKCOM@_@Q@QL000:
	INC	AL  ;[A]=TRUE VALUE TYPE
	MOV	byte [@VALTYP],AL  ;SETUP VALUE TYPE FOR MOVE
	INC	BX
	MOV	BX,[BX]  ;[H,L]=POINTER AT STRING DATA
;AND FOR IDENTIFICATION
	JMP	@VMOVFM

; SUBTTL  Read Items From A Sequential File

@FILIND:
	CALL	@GETYPR  ;SEE IF INPUT IS STRING OR NUMBER
	MOV	CX,@DOASIG  ;RETURN ADDRESS TO SETUP [FAC]
	@DSKCOM@_CON1=0+(44*256)+32
	MOV	DX,@DSKCOM@_CON1  ;SETUP TERMINATORS SPACE AND COMMA
	JNZ	@DSKCOM@_INPDOR  ;IF NUMERIC, GO READ THE FILE
	MOV	DL,DH  ;MAKE BOTH TERMINATORS COMMA
	JMP	@DSKCOM@_INPDOR  ;GO READ THE FILE

; Entry for line input and read code for item fetching from
; sequential input files

@DLINE:
	CALL	@FILINP  ;GET FILE NUMBER SET UP
	CALL	@PTRGET  ;READ STRING TO STORE INTO
	CALL	@FRCSTR  ;MAKE SURE IT WAS A STRING
	MOV	CX,@FINPRT  ;RESET TO CONSOLE WHEN DONE READING
	PUSH	CX  ;SAVE ON STACK
	PUSH	DX  ;SAVE POINTER AT VARIABLE
; EXTRN	LETCON:NEAR
	MOV	CX,@LETCON  ;GOOD RETURN ADDRESS FOR ASSIGNMENT
	XOR	AL,AL  ;SET A=0 FOR STRING VALUE TYPE
	MOV	DH,AL  ;ZERO OUT BOTH TERMINATORS
	MOV	DL,AL
@DSKCOM@_INPDOR:	PUSH	AX  ;SAVE VALUE TYPE
	PUSH	CX  ;SAVE RETURN ADDRESS
	PUSH	BX  ;SAVE POINTER AT DATA COMING IN
;A DUMMY POINTER AT BUFMIN
@DSKCOM@_NOTNWT:
; EXTRN	INCHR:NEAR
	CALL	@INCHR  ;Read a character from file PTRFIL
	CMP	AL,((" ") and 0FFh)  ;SKIP LEADING SPACES
	JNZ	@DSKCOM@_NOTSPC  ;EXCEPT FOR LINE INPUT
	INC	DH  ;CHECK FOR LINEINPUT
	DEC	DH
	JNZ	@DSKCOM@_NOTNWT  ;SKIP ANY NUMBER
@DSKCOM@_NOTSPC:	CMP	AL,((34) and 0FFh)  ;QUOTED STRING COMING IN?
	JNZ	@DSKCOM@_NOTQTE
	MOV	AL,DL  ;MUST BE INPUT OF A STRING
	CMP	AL,((44) and 0FFh)  ;WHICH HAS [E]=44 (",")
	MOV	AL,((34) and 0FFh)  ;QUOTE BACK INTO [A]
	JNZ	@DSKCOM@_NOTQTE
	MOV	DH,AL  ;TERMINATORS ARE QUOTES ONLY
	MOV	DL,AL
	CALL	@INDSKC  ;READ PAST QUOTATION
	JB	@DSKCOM@_QUITSI  ;IF EOF, ALL DONE
@DSKCOM@_NOTQTE:
	MOV	BX,@BUF  ;BUFFER FOR DATA
	MOV	CH,((255) and 0FFh)  ;MAXIMUM NUMBER OF CHARACTERS (255)
@DSKCOM@_LOPCRS:	MOV	CL,AL  ;SAVE CHARACTER IN [C]
	MOV	AL,DH  ;CHECK FOR QUOTED STRING
	CMP	AL,((34) and 0FFh)
	MOV	AL,CL  ;RESTORE CHARACTER
	JZ	@DSKCOM@_NOTQTL  ;DON'T IGNORE CR OR STOP ON LF
	CMP	AL,((13) and 0FFh)  ;CR?
	PUSH	BX  ;SAVE DEST PTR. ON STACK
	JZ	@DSKCOM@_ICASLF  ;EAT LINE FEED IF ONE
	POP	BX  ;RESTORE DEST. PTR.
	CMP	AL,((10) and 0FFh)  ;LF?
	JNZ	@DSKCOM@_NOTQTL  ;NO, TEST OTHER TERMINATORS
@DSKCOM@_LPISLF:  ;** 5/14/82 BUG FIX(MULTIPLE LF FOR UNQUOTED STRING)
	MOV	CL,AL  ;SAVE CURRENT CHAR
	MOV	AL,DL  ;GET TERMINATOR 2
	CMP	AL,((44) and 0FFh)  ;CHECK FOR COMMA (UNQUOTED STRING)
	MOV	AL,CL  ;RESTORE CHARACTER
	JZ	@DSKCOM@_@Q@QL001
	CALL	@DSKCOM@_STRCHR  ;IF NOT, STORE LF (?)
@DSKCOM@_@Q@QL001:
	CALL	@INDSKC  ;GET NEXT CHAR
	JB	@DSKCOM@_QUITSI  ;IF EOF, ALL DONE.
	CMP	AL,((10) and 0FFh)  ;** 5/14/82 BUG FIX(MULTIPLE LF FOR UNQUOTED STRING)
	JZ	@DSKCOM@_LPISLF  ;** 5/14/82 BUG FIX(MULTIPLE LF FOR UNQUOTED STRING)
	CMP	AL,((13) and 0FFh)  ;IS IT A CR?
	JNZ	@DSKCOM@_NOTQTL  ;IF NOT SEE IF STORE NORMALLY
	MOV	AL,DL  ;GET TERMINATOR
	CMP	AL,((" ") and 0FFh)  ;IS IT NUMERIC INPUT?
	JZ	@DSKCOM@_LPCRGT  ;IF SO, IGNORE CR, DONT PUT IN BUFFER
	CMP	AL,((44) and 0FFh)  ;IS IT NON-QUOTED STRING (TERM=,)
	MOV	AL,((13) and 0FFh)  ;GET BACK CR.
	JZ	@DSKCOM@_LPCRGT  ;IF SO, IGNORE CR.
@DSKCOM@_NOTQTL:	OR	AL,AL  ;IS CHAR ZERO
	JZ	@DSKCOM@_LPCRGT  ;ALWAYS IGNORE, AS IT IS TERMINATOR
;FOR STRLIT (SEE QUIT2B)
	CMP	AL,DH  ;TERMINATOR ONE?
	JZ	@DSKCOM@_QUITSI  ;STOP THEN
	CMP	AL,DL  ;TERMINATOR TWO?
	JZ	@DSKCOM@_QUITSI
	CALL	@DSKCOM@_STRCHR  ;SAVE THE CHAR
@DSKCOM@_LPCRGT:	CALL	@INDSKC  ;READ ANOTHER CHARACTER
	JAE	@DSKCOM@_LOPCRS  ;IF NOT, CHECK AS TERMINATOR
@DSKCOM@_QUITSI:	PUSH	BX  ;SAVE PLACE TO STUFF ZERO
	CMP	AL,((34) and 0FFh)  ;STOPPED ON QUOTE?
	JZ	@DSKCOM@_MORSPC  ;DON'T SKIP SPACES THEN
;BUT DO SKIP FOLLOWING COMMA OR
;CRLF THOUGH
	CMP	AL,((" ") and 0FFh)  ;STOPPED ON SPACE?
	JNZ	@DSKCOM@_NOSKCR  ;NO, DON'T SKIP SPACES
;OR ANY FOLLOWING COMMAS OR CRLFS EITHER
@DSKCOM@_MORSPC:	CALL	@INDSKC  ;READ SPACES
	JB	@DSKCOM@_NOSKCR  ;EOF, ALL DONE.
	CMP	AL,((" ") and 0FFh)
	JZ	@DSKCOM@_MORSPC
	CMP	AL,((44) and 0FFh)  ;COMMA?
	JNZ	@DSKCOM@_@Q@QL002
	JMP	@DSKCOM@_NOSKCR  ;OK, SKIP IT
@DSKCOM@_@Q@QL002:
	CMP	AL,((13) and 0FFh)  ;CARRIAGE RETURN?
	JNZ	@DSKCOM@_BAKUPT  ;BACK UP PAST THIS CHARACTER
@DSKCOM@_ICASLF:
	CALL	@INDSKC  ;READ ANOTHER
	JB	@DSKCOM@_NOSKCR  ;EOF, ALL DONE.
	CMP	AL,((10) and 0FFh)  ;LINE FEED?
	JZ	@DSKCOM@_NOSKCR  ;OK, SKIP IT TOO
@DSKCOM@_BAKUPT:
; EXTRN	BAKCHR:NEAR
	CALL	@BAKCHR  ;backup file PTRFIL
@DSKCOM@_NOSKCR:	POP	BX  ;GET BACK PLACE TO STORE TERMINATOR
@DSKCOM@_QUIT2B:	MOV	byte [BX],((0) and 0FFh)  ;STORE THE TERMINATOR
	MOV	BX,@BUF-1  ;ITEM IS NOW STORED AT THIS POINT +1
	MOV	AL,DL  ;WAS IT A NUMERIC INPUT?
	SUB	AL,((" ") and 0FFh)  ;IF SO, [E]=" "
	JZ	@DSKCOM@_NUMIMK  ;USE FIN TO SCAN IT
; EXTRN	STRLT2:NEAR
	MOV	CH,DH  ;SET [B]=44 IF SCANNING UNQUOTED STRING
	MOV	DH,((0) and 0FFh)
	CALL	@STRLT2
	POP	BX  ;GET BACK [H,L]
	RET  ;DO ASSIGNMENT

@DSKCOM@_NUMIMK:
	CALL	@GETYPR  ;GET TYPE OF NUMERIC VARIABLE BEING READ
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH  ;SAVE IT
	CALL	@CHRGTR  ;READ FIRST CHARACTER
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF  ;RESTORE TYPE OF VARIABLE
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH  ;SAVE BACK
	JNB	@DSKCOM@_@Q@QL003
	CALL	@FIN  ;SINGLE PRECISION INPUT
@DSKCOM@_@Q@QL003:
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF  ;GET BACK TYPE OF VAR
; EXTRN	FINDBL:NEAR
	JNAE	@DSKCOM@_@Q@QL004
	CALL	@FINDBL
@DSKCOM@_@Q@QL004:  ;DOUBLE PRECISION INPUT
	POP	BX  ;GET [H,L]
	RET  ;DO THE ASSIGNMENT

@DSKCOM@_STRCHR:	OR	AL,AL  ;TRYING TO STORE NULL BYTE
	JNZ	$+3
	RET  ;RETURN, DONT STORE IT
	MOV	byte [BX],AL  ;STORE THE CHARACTER
	INC	BX
	DEC	CH  ;128 YET?
	JZ	$+3
	RET  ;MORE SPACE IN BUFFER, RETURN
	POP	CX  ;GET RID OF SUPERFLUOUS STACK ENTRY
	JMP	@DSKCOM@_QUIT2B  ;SPECIAL QUIT

; SUBTTL  LOAD and RUN routines

@PRGFLI:	MOV	DH,((@MD_SQI) and 0FFh)  ;SEQUENTIAL INPUT MODE
@PRGFL2:	XOR	AL,AL  ;INTERNAL FILE NUMBER IS ALWAYS ZERO
	JMP	@PRGFIL  ;SCAN FILE NAME AND DISK NUMMER
;AND DO THE RIGHT THING USING MD.KIL
;AS A FLAG

@LRUN:
@DSKCOM@_LRUN2:	MOV	AL,((1) and 0FFh)
	JMP	@DSKCOM@_LRUN3  ;1 INDICATES, CLOSE FILES, RUN
@LOAD:	XOR	AL,AL  ;FLAG ZERO FOR "LOAD"
@DSKCOM@_LRUN3:  ;A=1 INDICATES CLOSE FILES, RUN
;A=0 INDICATES CLOSE FILES, NO RUN
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH  ;SAVE "RUN"/"LOAD" FLAG
	CALL	@PRGFLI  ;FIND THAT FILE AND SETUP FOR
;USING INDSKC SUBROUTINE
	DEC	BX  ;SEE IF NO RUN OPTION
	CALL	@CHRGTR
	JZ	@DSKCOM@_NOTRNL  ;NO, JUST LOAD
	CALL	@SYNCHR
	DB	44  ;GOTTA HAVE A COMMA
	CALL	@SYNCHR
	DB	"R"  ;ONLY OPTION IS RUN
	JZ	@DSKCOM@_@Q@QL005
	JMP	@SNERR  ;AND THAT BETTER BE THE END
@DSKCOM@_@Q@QL005:
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF  ;GET RID OF "RUN"/"LOAD" FLAG
; RUN fn closes all files, loads program, and executes program
; RUN fn,R loads program, and executes program
; LOAD fn closes all files, loads program
; LOAD fn,R loads program, and executes program
; MERGE fn merges an ASCII program
; CHAIN fn loads/merges a program, and executes program (leaving files opened)

; PUBLIC	CHNENT
end if
; EXTRN	RUNFLG:WORD
if @GW_PASS = 1
@CHNENT:
	MOV	AL,((129) and 0FFh)  ;A=LEAVE FILES OPEN, RUN
	JMP	@DSKCOM@_NOTRN1
@DSKCOM@_NOTRNL:	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF  ;restore [A]=1 for RUN, 0 for LOAD
@DSKCOM@_NOTRN1:
;Variable  ",R"    CHAIN   LOAD   RUN
	MOV	byte [@RUNFLG],AL  ;RUNFLG=  ^O201    ^O201      0     1
	OR	AL,((1) and 0FFh)
	MOV	byte [@NLONLY],AL  ;NLONLY=  ^O201    ^O201      1     1
;If NLONLY and 200 <> 0, don't close any files
;If NLONLY and 001 <> 0, don't close file 0
	CALL	@SCRTCH  ;Clear variables, close files
; BELOW IS FIX (TO LABEL NOTINI) SO THAT IF ^C DURING MBASIC FOO, WONT EXIT TO SYSTEM
	MOV	BX,[@CURLIN]  ;GET LINE NUMBER
	LAHF
	INC	BX  ;SEE IF IN INITIALIZATION
	SAHF
	MOV	AL,BH
	AND	AL,BL
	INC	AL
	JNZ	@DSKCOM@_NOTINI  ;NO
	MOV	[@CURLIN],BX  ;SAVE DIRECT LINE NUMBER
@DSKCOM@_NOTINI:
	CALL	@INDSKC  ;READ THE FIRST CHARACTER
	JAE	@DSKCOM@_@Q@QL006
	JMP	@MAIN  ;ALL DONE IF NOTHING IN FILE
@DSKCOM@_@Q@QL006:
	CMP	AL,((254) and 0FFh)  ;IS THIS A PROTECTED FILE?
	JNZ	@DSKCOM@_NTPROL  ;NO
	MOV	byte [@PROFLG],AL  ;SET PROTECTED FILE
	JMP	@DSKCOM@_BINLOD  ;DO BINARY LOAD
@DSKCOM@_NTPROL:
	INC	AL  ;IS IT A BINARY FILE?
	JZ	@DSKCOM@_@Q@QL007
	JMP	@DSKCOM@_MAINGO  ;NO, SINCE PTRFIL IS NON-ZERO
@DSKCOM@_@Q@QL007:
;INCHR WILL USE INDSKC INSTEAD OF POLLING
;THE TERMINAL
;WHEN EOF IS HIT PTRFIL WILL BE RESTORED
;AND LSTFRE WILL BE USED AS A FLAG
;TO INDICATE WHETHER TO RUN THE
;LOADED PROGRAM

; TIME FOR A BINARY LOAD.
; AFTER THE LOAD, THE FILE IS LINKED TOGETHER
; LSTFRE IS USED AS A FLAG WHETHER TO RUN OR NOT

@DSKCOM@_BINLOD:	MOV	BX,[@TXTTAB]  ;GET PLACE TO START STORING INTO

; EXTRN	FSTLOD:NEAR
	CALL	@FSTLOD  ;USE FAST LOAD CODE IN DCPM.MAC
; EXTRN	PROLOD:NEAR
	MOV	[@VARTAB],BX  ;SAVE END TEMP FOR DECODING
	MOV	AL,byte [@PROFLG]  ;IS THIS A PROTECTED FILE?
	OR	AL,AL  ;SET CC'S
	JZ	@DSKCOM@_@Q@QL008
	CALL	@PROLOD
@DSKCOM@_@Q@QL008:  ;TRANSLATE TO GOOD STUFF
	CALL	@LINKER  ;FIX THE LINKS
	INC	BX  ;WHEN LINKER RETURNS, [H,L]
	INC	BX  ;POINTS TO DOUBLE ZERO
	MOV	[@VARTAB],BX  ;UPDATE [VARTAB]
	CALL	@RUNC  ;SETUP ARYTAB, STREND
end if
; EXTRN	CHNFLG:WORD
if @GW_PASS = 1
; EXTRN	CHNRET:NEAR
	MOV	AL,byte [@CHNFLG]  ;CHAIN IN PROGRESS
	OR	AL,AL  ;TEST
	JZ	@DSKCOM@_@Q@QL009
	JMP	@CHNRET  ;YES, GO BACK TO CHAIN CODE
@DSKCOM@_@Q@QL009:
end if
; EXTRN	NLONLY:WORD
if @GW_PASS = 1
	XOR	AL,AL
	MOV	byte [@NLONLY],AL  ;allow all files to be closed
	CALL	@FINPRT  ;reset PTRFIL to 0 and close file 0
end if
; EXTRN	RUNFLG:WORD
if @GW_PASS = 1
	MOV	AL,byte [@RUNFLG]  ;RUN OR NOT?
	OR	AL,AL
	JNZ	@DSKCOM@_@Q@QL010
	JMP	@READY
@DSKCOM@_@Q@QL010:
	JMP	@NEWSTT

@PRGFIN:	CALL	@FINPRT  ;ZERO PTRFIL
	CALL	@CLSFIL  ;CLOSE FILE ZERO
	JMP	@GTMPRT  ;REFETCH TEXT POINTER
; PUBLIC	OUTLOD
@OUTLOD:	CALL	@SCRTCH
	JMP	@OMERR

;MERGE filespec  Statement
; (OKGETM is called by CHAIN MERGE ... in FIVEO)

@MERGE:	POP	CX  ;ELIMINATE NEWSTT RETURN
	CALL	@PRGFLI  ;READ THE NAME AND DISK
	DEC	BX  ;MUST END THERE
	CALL	@CHRGTR
	JZ	@OKGETM  ;READ THE FILE
	CALL	@PRGFIN  ;CLOSE OUT TIME
	JMP	@SNERR  ;AND "SYNTAX ERROR"
@OKGETM:	XOR	AL,AL  ;NO RUN OPTION WITH "MERGE"
end if
; EXTRN	RUNFLG:WORD
if @GW_PASS = 1
	MOV	byte [@RUNFLG],AL  ;SET UP THE RUN FLAG
	INC	AL
	MOV	byte [@NLONLY],AL  ;NLONLY=1, don't close file 0
; PUBLIC	OKGET2
@OKGET2:
	CALL	@INDSKC  ;READ FROM [PTRFIL] FILE
	JAE	@DSKCOM@_@Q@QL011
	JMP	@MAIN  ;GO BACK IF EOF
@DSKCOM@_@Q@QL011:
	INC	AL  ;IS IT A BINARY FILE??
	JNZ	@DSKCOM@_@Q@QL012
	JMP	@DERBFM  ;BINARY IS WRONG FILE MODE
@DSKCOM@_@Q@QL012:
	INC	AL  ;OR PROTECTED BINARY FILE??
	JNZ	@DSKCOM@_@Q@QL013
	JMP	@DERBFM  ;ALSO GIVE BAD FILE MODE
@DSKCOM@_@Q@QL013:
	DEC	AL  ;adjust [A] for 1st INR A above
;so we can put it back (backup input file)
@DSKCOM@_MAINGO:
	DEC	AL  ;[A]=character which was just read from file
	CALL	@BAKCHR  ;backup file PTRFIL
; EXTRN	SCDASC:NEAR
	CALL	@SCDASC  ;set File Code to ASCII overridding user setting)
	JMP	@MAIN

; SUBTTL DISPATCH FOR DIRECT STATEMENT

; MAKE SURE WE'RE NOT READING A FILE IN

; SUBTTL  SAVE COMMAND -- ASCII OR BINARY

@SAVE:
	PUSH	BX  ;save text pointer for rescan of filename
	CALL	@FRMEVL  ;skip filename
	PUSH	BX
	CALL	@FRESTR  ;release string temporary
	POP	BX
	DEC	BX
	CALL	@CHRGTR
	JNZ	@DSKCOM@_@Q@QL014
	JMP	@DSKCOM@_ENDOFS  ;branch if end-of-statement
@DSKCOM@_@Q@QL014:
	CALL	@SYNCHR
	DB	44  ;eat comma
	CMP	AL,(("A") and 0FFh)
	JNZ	@DSKCOM@_@Q@QL015
	JMP	@DSKCOM@_GOODSV  ;branch if got "A"
@DSKCOM@_@Q@QL015:
	CMP	AL,(("P") and 0FFh)
	JZ	@DSKCOM@_@Q@QL016
	JMP	@SNERR  ;branch if not "A" or "P"
@DSKCOM@_@Q@QL016:
@DSKCOM@_GOODSV:	PUSH	BX  ;save text pointer
	PUSH	AX  ;save "A" or "P"
	CALL	@CHRGTR  ;check for end-of-statement
	JZ	@DSKCOM@_@Q@QL017
	JMP	@SNERR  ;error if not end-of-statement
@DSKCOM@_@Q@QL017:
	POP	AX
	POP	BX  ;leave text pointer pointing at "A" or "P"
@DSKCOM@_ENDOFS:	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;save End-Of-Statement text pointer
;HL = text pointer to filename
	PUSH	AX  ;save "A", "P" or null option
	MOV	DH,((@MD_SQO) and 0FFh)  ;ELIMINATE EARLIER VERSION OF FILE
;AND CREATE EMPTY FILE
	CALL	@PRGFL2  ;parse file name and open it
	POP	AX  ;[A]="A", "P" or null option
	POP	BX  ;restore End-Of-Statement text pointer
; EXTRN	PROSAV:NEAR
	CMP	AL,(("P") and 0FFh)  ;PROTECTED SAVE?
	JNZ	@DSKCOM@_@Q@QL018
	JMP	@PROSAV  ;DO IT
@DSKCOM@_@Q@QL018:
	CMP	AL,(("A") and 0FFh)  ;Ascii save?
	JZ	@DSKCOM@_@Q@QL019
	JMP	@BINSAV  ;if not, must be Binary Save
@DSKCOM@_@Q@QL019:
	CALL	@CHRGTR  ;skip "A"
