; PUBLIC	BUFLIN
@BUFLIN:	MOV	CX,@BUF  ;GET START OF TEXT BUFFER
	MOV	DH,((@BUFLEN) and 0FFh)  ;GET ITS LENGTH INTO [D]
	XOR	AL,AL  ;SET MODE OF DECRUNCH
	MOV	byte [@DORES],AL  ;BIT0 IS QUOTE BIT1 IS DATA BIT2 IS REM
	XOR	AL,AL  ;SET ON SPECIAL CHAR FOR SPACE INSERTION
	MOV	byte [@TEMPA],AL
	CALL	@PROCHK  ;ONLY PROCEED IF OK
	JMP	@PLOOP2  ;START HERE

@GWLIST@_PLOOP:	INC	CX  ;INCREMENT DEPOSIT PTR.
	INC	BX  ;ADVANCE TEXT PTR
	DEC	DH  ;BUMP DOWN COUNT
	JNZ	$+3
	RET  ;IF BUFFER FULL, RETURN
; PUBLIC	PLOOP2
@PLOOP2:
	MOV	AL,byte [BX]  ;GET CHAR FROM BUF
	OR	AL,AL  ;SET CC'S
	MOV	DI,CX
	STOSB  ;SAVE THIS CHAR
	JNZ	$+3
	RET  ;IF END OF SOURCE BUFFER, ALL DONE.
	CMP	AL,((@OCTCON) and 0FFh)  ;IS IT SMALLER THAN SMALLEST EMBEDDED CONSTANT?
	JB	@GWLIST@_NTEMBL  ;YES, DONT TREAT AS ONE
	CMP	AL,((@DBLCN1) and 0FFh)  ;IS IT EMBEDED CONSTANT?
	MOV	DL,AL  ;SAVE CHAR IN [E]
	JB	@GWLIST@_PRTVAR  ;PRINT LEADING SPACE IF NESC.
	CMP	AL,((34) and 0FFh)  ;IS IT A QUOTATION
	JNZ	@GWLIST@_BFCHKC  ;IF NOT CHECK FOR COLON
	MOV	AL,byte [@DORES]  ;COMPLEMENT THE QUOTE BIT
	XOR	AL,((1) and 0FFh)
	MOV	byte [@DORES],AL
	MOV	AL,((34) and 0FFh)  ;RESTORE THE CHARACTER
@GWLIST@_BFCHKC:	CMP	AL,((":") and 0FFh)  ;IS IT A COLON ENDING DATA?
	JNZ	@GWLIST@_NTEMBL
	MOV	AL,byte [@DORES]  ;DON'T END IF IN QUOTE
	RCR	AL,1
	JB	@GWLIST@_QTCOLN
	RCL	AL,1
	AND	AL,((253) and 0FFh)  ;TURN OFF BIT1 (DATA BIT)
	MOV	byte [@DORES],AL
@GWLIST@_QTCOLN:	MOV	AL,((":") and 0FFh)
@GWLIST@_NTEMBL:	OR	AL,AL  ;SET CC'S
	JNS	@GWLIST@_@Q@QL005
	JMP	@GWLIST@_PLOOPR  ;RESERVED WORD OF SOME KIND
@GWLIST@_@Q@QL005:
	MOV	DL,AL  ;SAVE CHAR IN [E]
	CMP	AL,((".") and 0FFh)  ;DOT IS PART OF VAR NAME
	JZ	@GWLIST@_PRTVAR
	CALL	@TSTANM  ;IS CHAR ALPHANUMERIC
	JAE	@GWLIST@_PRTVAR  ;ALPHANUMERIC
	XOR	AL,AL  ;MAKE SPECIAL
	JMP	@GWLIST@_PLOOPH
@GWLIST@_PRTVAR:	MOV	AL,byte [@TEMPA]  ;WHAT DID WE DO LAST?
	OR	AL,AL  ;SET CONDITION CODES
	JZ	@GWLIST@_PLOOPG  ;SPECIAL, NEVER INSERT SPACE
	INC	AL  ;IN RESERVED WORD?
	JNZ	@GWLIST@_PLOOPG  ;NO
	MOV	AL,((" ") and 0FFh)  ;PUT OUT SPACE BEFORE RESWORD
	MOV	DI,CX
	STOSB  ;STORE IN BUFFER
	INC	CX  ;INCRMENT POINTER INTO BUFFER
	DEC	DH  ;SPACE LEFT?
	JNZ	$+3
	RET  ;NO, DONE
@GWLIST@_PLOOPG:	MOV	AL,((1) and 0FFh)  ;STORE FLAG SAYING IN VAR
@GWLIST@_PLOOPH:	MOV	byte [@TEMPA],AL
	MOV	AL,DL  ;GET BACK CHAR WE HAD
	CMP	AL,((@OCTCON) and 0FFh)  ;IS IT SMALLER THAN SMALLEST EMBEDDED CONSTANT?
	JB	@GWLIST@_PLOOPZ  ;YES, DONT TREAT AS ONE
	CMP	AL,((@DBLCN1) and 0FFh)  ;IS IT EMBEDED CONSTANT?
	JAE	@GWLIST@_@Q@QL006
	JMP	@GWLIST@_NUMLIN  ;YES, UNPACK IT
@GWLIST@_@Q@QL006:
@GWLIST@_PLOOPZ:	MOV	DI,CX
	STOSB  ;MAKE SURE BYTE STORED AFTER SPACE
	JMP	@GWLIST@_PLOOP  ;STORE IN BUFFER
@GWLIST@_PLOOPR:
	MOV	AL,byte [@DORES]  ;SEEWHAT OUR UNCRUNCH MODE IS
	RCR	AL,1  ;THE LSB IS THE QUOTE BIT
	JB	@GWLIST@_GPLOOP
	RCR	AL,1  ;GET THE REM BIT
	RCR	AL,1  ;AND SEE IF SET
	JAE	@GWLIST@_CHKDRS  ;IF NOT JUST CHECK DATA BIT
	MOV	AL,byte [BX]  ;MUST SEE IF ITS SNGQTK
	CMP	AL,((@SNGQTK) and 0FFh)  ;AND PRECEDED BY ":REM"
	PUSH	BX
	PUSH	CX  ;SAVE BUFFER POINTER
	MOV	BX,@GWLIST@_NOSNGQ  ;PLACE TO RETURN ON FAILURE
	PUSH	BX
	JZ	$+3
	RET
	DEC	CX
	MOV	SI,CX
	MOV	AL,[SI]
	CMP	AL,(("M") and 0FFh)
	JZ	$+3
	RET
	DEC	CX
	MOV	SI,CX
	MOV	AL,[SI]
	CMP	AL,(("E") and 0FFh)
	JZ	$+3
	RET
	DEC	CX
	MOV	SI,CX
	MOV	AL,[SI]
	CMP	AL,(("R") and 0FFh)
	JZ	$+3
	RET
	DEC	CX
	MOV	SI,CX
	MOV	AL,[SI]
	CMP	AL,((":") and 0FFh)
	JZ	$+3
	RET
	POP	AX  ;GET RID OF RETURN ON FAIL ADDRESS
	POP	AX  ;GET RID OF BAD BUFFER POINTER
	POP	BX  ;GET BACK POINTER INTO LINE
	INC	DH  ;UPDATE CHAR COUNT
	INC	DH
	INC	DH
	INC	DH
	JMP	@GWLIST@_RESEXP

@GWLIST@_NOSNGQ:	POP	CX  ;GET BACK THE BUFFERPOINTER
	POP	BX  ;GET BACK SOURCE LINE POINTER
	MOV	AL,byte [BX]  ;GET BACK THE CHARACTER
@GWLIST@_GPLOOP:	JMP	@GWLIST@_PLOOP

@GWLIST@_DATSET:	MOV	AL,byte [@DORES]  ;BIT INDICATING INSIDE DATA
	OR	AL,((2) and 0FFh)  ;IS BIT1
@GWLIST@_SETDRS:	MOV	byte [@DORES],AL
	XOR	AL,AL
	RET

@GWLIST@_REMSET:	MOV	AL,byte [@DORES]
	OR	AL,((4) and 0FFh)
	JMP	@GWLIST@_SETDRS

@GWLIST@_CHKDRS:	RCL	AL,1  ;GET DATA BIT INTO CARRY
	JB	@GWLIST@_GPLOOP
	MOV	AL,byte [BX]  ;GET BACK THE CHARACTER
	CMP	AL,((@@SDATA) and 0FFh)  ;NEED TO SET A BIT
	JNZ	@GWLIST@_@Q@QL007
	CALL	@GWLIST@_DATSET
@GWLIST@_@Q@QL007:
	CMP	AL,((@@SREM) and 0FFh)
	JNZ	@GWLIST@_@Q@QL008
	CALL	@GWLIST@_REMSET
@GWLIST@_@Q@QL008:
@GWLIST@_RESEXP:	MOV	AL,byte [BX]

	INC	AL  ;SET ZERO IF FN TOKEN
	MOV	AL,byte [BX]  ;GET CHAR BACK
	JNZ	@GWLIST@_NTFNTK  ;NOT FUNCTION JUST TREAT NORMALLY
	INC	BX  ;BUMP POINTER
	MOV	AL,byte [BX]  ;GET CHAR
	AND	AL,((127) and 0FFh)  ;TURN OFF HIGH BIT
@GWLIST@_NTFNTK:	INC	BX  ;ADVANCE TO POINT AFTER
@GWLIST@_NTQTTK:	CMP	AL,((@@SELSE) and 0FFh)  ;ELSE?
	JNZ	@GWLIST@_NOTELS
	DEC	CX
	INC	DH
@GWLIST@_NOTELS:
	CMP	AL,((@@SWHILE) and 0FFh)  ;MIGHT HAVE AN EXTRA "+" IN WHILE FORMULA
	JNZ	@GWLIST@_BFNTWH  ;SO SKIP OVER IT IF ITS THERE
	MOV	AL,byte [BX]  ;GET CHARACTER TO SEE IF ITS PLUSTK
	INC	BX  ;ASSUME IS PLUSTK
	CMP	AL,((@PLUSTK) and 0FFh)  ;MIGHT NOT BE PLUS IF BINARY SAVED IN
	MOV	AL,((@@SWHILE) and 0FFh)  ;RESTORE TOKEN VALUE
	JZ	@GWLIST@_BFNTWH  ;VERSION OF BASIC BEFORE CRUNCH CHANGED
	DEC	BX  ;MOVE POINTER BACK
@GWLIST@_BFNTWH:

	PUSH	BX  ;SAVE TEXT PTR.
	PUSH	CX  ;SAVE DEPOSIT PTR.
	PUSH	DX  ;SAVE CHAR COUNT.
; EXTRN	LISTX:NEAR
	CALL	@LISTX  ;Handle extended reserved words.
	MOV	BX,@RESLST-1  ;GET PTR TO START OF RESERVED WORD LIST
	MOV	CH,AL  ;SAVE THIS CHAR IN [B]
	MOV	CL,(("A"-1) and 0FFh)  ;INIT LEADING CHAR VALUE
@GWLIST@_RESSR3:	INC	CL  ;BUMP LEADING CHAR VALUE.
@GWLIST@_RESSR1:	INC	BX  ;BUMP POINTER INTO RESLST
@GWLIST@_RESSRC:	MOV	DH,BH  ;SAVE PTR TO START OF THIS RESWRD
	MOV	DL,BL
@GWLIST@_RESSR2:
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET CHAR FROM RESLST
	OR	AL,AL  ;SET CC'S
	JZ	@GWLIST@_RESSR3  ;IF END OF THIS CHARS TABLE, GO BACK & BUMP C
	LAHF
	INC	BX  ;BUMP SOURCE PTR
	SAHF
	JS	@GWLIST@_@Q@QL009
	JMP	@GWLIST@_RESSR2  ;IF NOT END OF THIS RESWRD, THEN KEEP LOOKING
@GWLIST@_@Q@QL009:
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET PTR TO RESERVED WORD VALUE
	CMP	AL,CH  ;SAME AS THE ONE WE SEARCH FOR?
	JNZ	@GWLIST@_RESSR1  ;NO, KEEP LOOKING.
	XCHG	BX,DX  ;SAVE FOUND PTR IN [H,L]
	CMP	AL,((@@SUSR) and 0FFh)  ;USR FUNCTION TOKEN?
	JZ	@GWLIST@_NOISPA  ;DONT INSERT SPACE
	CMP	AL,((@@SFN) and 0FFh)  ;IS IT FUNCTION TOKEN?
@GWLIST@_NOISPA:
	MOV	AL,CL  ;GET LEADING CHAR
	POP	DX  ;RESTORE LINE CHAR COUNT
	POP	CX  ;RESTORE DEPOSIT PTR
	MOV	DL,AL  ;SAVE LEADING CHAR
	JNZ	@GWLIST@_NTFNEX  ;NOT "FN" EXPANSION
	MOV	AL,byte [@TEMPA]  ;SET CC'S ON TEMPA
	OR	AL,AL
	MOV	AL,((0) and 0FFh)  ;CLEAR RESWRD FLAG - MARK AS SPECIAL
	MOV	byte [@TEMPA],AL  ;SET FLAG
	JMP	@GWLIST@_MORLNZ  ;DO EXPANSION
@GWLIST@_NTFNEX:
	CMP	AL,(("Z"+1) and 0FFh)  ;WAS IT A SPECIAL CHAR?
	JNZ	@GWLIST@_NTSPCH  ;NON-SPECIAL CHAR
	XOR	AL,AL  ;SET NON-SPECIAL
	MOV	byte [@TEMPA],AL
	JMP	@GWLIST@_MORPUR  ;PRINT IT
@GWLIST@_NTSPCH:	MOV	AL,byte [@TEMPA]  ;WHAT DID WE DO LAST?
	OR	AL,AL  ;SPECIAL?
	MOV	AL,((255) and 0FFh)  ;FLAG IN RESERVED WORD
	MOV	byte [@TEMPA],AL  ;CLEAR FLAG
@GWLIST@_MORLNZ:	JZ	@GWLIST@_MORLN0  ;GET CHAR AND PROCEED
	MOV	AL,((" ") and 0FFh)  ;PUT SPACE IN BUFFER
	MOV	DI,CX
	STOSB
	INC	CX
	DEC	DH  ;ANY SPACE LEFT IN BUFFER
	JNZ	@GWLIST@_@Q@QL010
	JMP	@PPSWRT  ;NO, RETURN
@GWLIST@_@Q@QL010:
@GWLIST@_MORLN0:	MOV	AL,DL
	JMP	@GWLIST@_MORLN1  ;CONTINUE
@GWLIST@_MORPUR:
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET BYTE FROM RESWRD
	INC	BX  ;BUMP POINTER
@GWLIST@_MORLNP:	MOV	DL,AL  ;SAVE CHAR
@GWLIST@_MORLN1:	AND	AL,((127) and 0FFh)  ;AND OFF HIGH ORDER BIT FOR DISK & EDIT
	MOV	DI,CX
	STOSB  ;STORE THIS CHAR
	INC	CX  ;BUMP PTR
	DEC	DH  ;BUMP DOWN REMAINING CHAR COUNT
	JNZ	@GWLIST@_@Q@QL011
	JMP	@PPSWRT  ;IF END OF LINE, JUST RETURN
@GWLIST@_@Q@QL011:
	OR	AL,DL  ;SET CC'S
	JS	@GWLIST@_@Q@QL012
	JMP	@GWLIST@_MORPUR  ;END OF RESWRD?
@GWLIST@_@Q@QL012:
	CMP	AL,(("("+128) and 0FFh)  ;SPC( OR TAB( ?
	JNZ	@GWLIST@_NTSPCT  ;NO
	XOR	AL,AL  ;CLEAR FLAG
	MOV	byte [@TEMPA],AL  ;TO INSERT SPACE AFTERWARDS
@GWLIST@_NTSPCT:
	POP	BX  ;RESTORE SOURCE PTR.
	JMP	@PLOOP2  ;GET NEXT CHAR FROM LINE
; PUBLIC	TSTANM
@TSTANM:	CALL	@ISLET2  ;LETTER?
	JNAE	$+3
	RET  ;YES
	CMP	AL,(("0") and 0FFh)  ;DIGIT?
	JNB	$+3
	RET  ;TOO SMALL
	CMP	AL,(("9"+1) and 0FFh)  ;LAST DIGIT
	CMC  ;MAKE CARRY RIGHT
	RET  ;NO CARRY=DIGIT
@GWLIST@_NUMLIN:	DEC	BX  ;MOVE POINTER BACK AS CHRGET INX'S
	CALL	@CHRGTR  ;SCAN THE CONSTANT
	PUSH	DX  ;SAVE CHAR COUNT
	PUSH	CX  ;SAVE DEPOSIT PTR
	PUSH	AX  ;SAVE CONSTANT TYPE.
	CALL	@CONFC1  ;MOVE CONSTANT INTO FAC
	POP	AX  ;RESTORE CONSTANT TYPE
	MOV	CX,@GWLIST@_CONLIN  ;PUT RETURN ADDR ON STACK
	PUSH	CX  ;SAVE IT
	CMP	AL,((@OCTCON) and 0FFh)  ;OCTAL CONSTANT?
	JNZ	@GWLIST@_@Q@QL013
	JMP	@FOUTO  ;PRINT IT
@GWLIST@_@Q@QL013:
	CMP	AL,((@HEXCON) and 0FFh)  ;HEX CONSTANT?
	JNZ	@GWLIST@_@Q@QL014
	JMP	@FOUTH  ;PRINT IN HEX
@GWLIST@_@Q@QL014:
	MOV	BX,[@CONLO]  ;GET LINE # VALUE IF ONE.
	JMP	@FOUT  ;PRINT REMAINING POSSIBILITIES.
@GWLIST@_CONLIN:	POP	CX  ;RESTORE DEPOSIT PTR.
	POP	DX  ;RESTORE CHAR COUNT
	MOV	AL,byte [@CONSAV]  ;GET SAVED CONSTANT TOKEN
	MOV	DL,(("O") and 0FFh)  ;ASSUME OCTAL CONSTANT
	CMP	AL,((@OCTCON) and 0FFh)  ;OCTAL CONSTANT?
	JZ	@GWLIST@_SAVBAS  ;YES, PRINT IT
	CMP	AL,((@HEXCON) and 0FFh)  ;HEX CONSTANT?
	MOV	DL,(("H") and 0FFh)  ;ASSUME SO.
	JNZ	@GWLIST@_NUMSLN  ;NOT BASE CONSTANT
@GWLIST@_SAVBAS:
	MOV	AL,(("&") and 0FFh)  ;PRINT LEADING BASE INDICATOR
	MOV	DI,CX
	STOSB  ;SAVE IT
	INC	CX  ;BUMP PTR
	DEC	DH  ;BUMP DOWN CHAR COUNT
	JNZ	$+3
	RET  ;RETURN IF END OF BUFFER
	MOV	AL,DL  ;GET BASE CHAR
	MOV	DI,CX
	STOSB  ;SAVE IT
	INC	CX  ;BUMP PTR
	DEC	DH  ;BUMP DOWN BASE COUNT
	JNZ	$+3
	RET  ;END OF BUFFER, DONE
@GWLIST@_NUMSLN:
	MOV	AL,byte [@CONTYP]  ;GET TYPE OF CONSTANT WE ARE
	CMP	AL,((4) and 0FFh)  ;IS IT SINGLE OR DOUBLE PREC?
	MOV	DL,((0) and 0FFh)  ;NO, NEVER PRINT TRAILING TYPE INDICATOR
	JB	@GWLIST@_TYPSET
	MOV	DL,(("!") and 0FFh)  ;ASSUME SINGLE PREC.
	JZ	@GWLIST@_TYPSET  ;IS CONTYP=4, WAS SINGLE
	MOV	DL,(("#") and 0FFh)  ;DOUBLE PREC INDICATOR
@GWLIST@_TYPSET:
	MOV	AL,byte [BX]  ;GET LEADING CHAR
	CMP	AL,((" ") and 0FFh)  ;LEADING SPACE
	JNZ	@GWLIST@_@Q@QL015
	CALL	@INXHRT  ;GO BY IT
@GWLIST@_@Q@QL015:
@GWLIST@_NUMSL2:	MOV	AL,byte [BX]  ;GET CHAR FROM NUMBER BUFFER
	INC	BX  ;BUMP POINTER
	OR	AL,AL  ;SET CC'S
	JZ	@GWLIST@_NUMDN  ;IF ZERO, ALL DONE.
	MOV	DI,CX
	STOSB  ;SAVE CHAR IN BUF.
	INC	CX  ;BUMP PTR
	DEC	DH  ;SEE IF END OF BUFFER
	JNZ	$+3
	RET  ;IF END OF BUFFER, RETURN
	MOV	AL,byte [@CONTYP]  ;GET TYPE OF CONSTANT TO BE PRINTED
	CMP	AL,((4) and 0FFh)  ;TEST FOR SINGLE OR DOUBLE PRECISION
	JB	@GWLIST@_NUMSL2  ;NO, WAS INTEGER
	LAHF
	DEC	CX  ;PICK UP SAVED CHAR
	SAHF
	MOV	SI,CX
	MOV	AL,[SI]  ;EASIER THAN PUSHING ON STACK
	LAHF
	INC	CX  ;RESTORE TO POINT WHERE IT SHOULD
	SAHF
	JNZ	@GWLIST@_DBLSCN  ;IF DOUBLE, DONT TEST FOR EMBEDED "."
	CMP	AL,((".") and 0FFh)  ;TEST FOR FRACTION
	JZ	@GWLIST@_ZERE  ;IF SINGLE & EMBEDED ., THEN DONT PRINT !
@GWLIST@_DBLSCN:	CMP	AL,(("D") and 0FFh)  ;DOUBLE PREC. EXPONENT?
	JZ	@GWLIST@_ZERE  ;YES, MARK NO VALUE TYPE INDICATOR NESC.
	CMP	AL,(("E") and 0FFh)  ;SINGLE PREC. EXPONENT?
	JNZ	@GWLIST@_NUMSL2  ;NO, PROCEED
@GWLIST@_ZERE:	MOV	DL,((0) and 0FFh)  ;MARK NO PRINTING OF TYPE INDICATOR
	JMP	@GWLIST@_NUMSL2  ;KEEP MOVING NUMBER CHARS INTO BUF

@GWLIST@_NUMDN:
	MOV	AL,DL  ;GET FLAG TO INDICATE WHETHER TO INSERT
	OR	AL,AL  ;A "D" AFTER DOUBLE PREC. #
	JZ	@GWLIST@_NOD  ;NO, DONT INSERT IT
	MOV	DI,CX
	STOSB  ;SAVE IN BUFFER
	INC	CX  ;BUMP POINTER
	DEC	DH  ;DECRMENT COUNT OF CHARS LEFT IN BUFFER
	JNZ	$+3
	RET  ;=0, MUST TRUNCATE LIST OF THIS LINE.
@GWLIST@_NOD:
	MOV	BX,[@CONTXT]  ;GET BACK TEXT POINTER AFTER CONSTANT
	JMP	@PLOOP2  ;GET NEXT CHAR

; THE FOLLOWING CODE IS FOR THE DELETE RANGE
; COMMAND. BEFORE THE LINES ARE DELETED, 'OK'
; IS TYPED.

; PUBLIC	DELETE
@DELETE:
	CALL	@SCNLIN  ;SCAN LINE RANGE
	PUSH	CX
	CALL	@DEPTR  ;CHANGE POINTERS BACK TO NUMBERS
	POP	CX
	POP	DX  ;POP MAX LINE OFF STACK
	PUSH	CX  ;SAVE POINTER TO START OF DELETION
;FOR USE BY CHEAD AFTER FINI
	PUSH	CX  ;SAVE POINTER TO START OF 1ST LINE
	CALL	@FNDLIN  ;FIND THE LAST LINE
	JAE	@GWLIST@_FCERRG  ;MUST HAVE A MATCH ON THE UPPER BOUND
	MOV	DH,BH  ;[D,E]=POINTER AT THE START OF THE LINE
	MOV	DL,BL  ;BEYOND THE LAST LINE IN THE RANGE
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;SAVE THE POINTER TO THE NEXT LINE
	PUSH	BX  ;SAVE THE POINTER TO THE START OF
;THE FIRST LINE IN THE RANGE
	CMP	BX,DX  ;MAKE SURE THE START COMES BEFORE THE END
@GWLIST@_FCERRG:	JNAE	@GWLIST@_@Q@QL016
	JMP	@FCERR  ;IF NOT, "ILLEGAL FUNCTION CALL"
@GWLIST@_@Q@QL016:
;DELETE must now be at EOL
; EXTRN	EOSCHK:NEAR
	MOV	BX,[@TEMP]  ;Get text pointer
	CALL	@EOSCHK  ;Check for end of statement
	MOV	BX,@REDDY  ;PRINT "OK" PREMATURELY
	CALL	@STROUT
	POP	CX  ;GET POINTER TO FIRST IN [B,C]
	MOV	BX,@FINI  ;GO BACK TO FINI WHEN DONE
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;[H,L]=POINTER TO THE NEXT LINE
; ERASE A LINE FROM MEMORY
; [B,C]=START OF LINE BEING DELETED
; [H,L]=START OF NEXT LINE

; PUBLIC	DEL
@DEL:	XCHG	BX,DX  ;[D,E] NOW HAVE THE POINTER TO THE LINE
;BEYOND THIS ONE
	MOV	BX,[@VARTAB]  ;COMPACTIFYING TO VARTAB
@GWLIST@_MLOOP:	MOV	SI,DX
	MOV	AL,[SI]
	MOV	DI,CX
	STOSB  ;SHOVING DOWN TO ELIMINATE A LINE
	INC	CX
	INC	DX
	CMP	BX,DX  ;DONE COMPACTIFYING?
	JNZ	@GWLIST@_MLOOP  ;NO
	MOV	BX,CX
;Clear SCALARS and ARRAYS incase we are replacing line which may force
; garbage collection in BLTU
	MOV	[@VARTAB],BX
	MOV	[@ARYTAB],BX
	MOV	[@STREND],BX
	RET

end if

