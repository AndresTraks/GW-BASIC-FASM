@GWLIST@_@Q@QL002:
	OR	AL,AL
	JNZ	@GWLIST@_@Q@QL003
	CALL	@GWLIST@_LISEOL
@GWLIST@_@Q@QL003:
	JNZ	$+3
	RET  ;IF =0 THEN END OF LINE
