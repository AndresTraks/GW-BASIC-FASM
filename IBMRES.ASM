; SUBTTL  CRUNCH code to handle extended reserved words

; PUBLIC	CRUNCX
@CRUNCX:	POP	BX  ;GET BACK SOURCE POINTER
	PUSH	BX  ;TO TRY AGAIN
	DEC	BX  ;POINT AT CHARACTER
	CALL	@MAKUPL  ;CONVERT TO UPPER CASE
	MOV	BX,@ALPTAX  ;GET POINTER TO ALPHA DISPATCH TABLE
	SUB	AL,(("A") and 0FFh)  ;SUBTRACT ALPHA OFFSET
	ADD	AL,AL  ;MULTIPLY BY TWO
	MOV	CL,AL  ;SAVE OFFSET IN [C] FOR DAD.
	MOV	CH,((0) and 0FFh)  ;MAKE HIGH PART OF OFFSET ZERO
	ADD	BX,CX  ;ADD TO TABLE ADDRESS
	@INS86	56
	MOV	DX,[BX]  ;GET POINTER IN [D,E]
	POP	BX  ;GET BACK SOURCE POINTER
@IBMRES@_TRYAGA:	PUSH	BX  ;SAVE TXTPTR TO START OF SEARCH AREA
@IBMRES@_LOPPSI:
	CALL	@MAKUPL  ;TRANSLATE THIS CHAR TO UPPER CASE
	MOV	CL,AL  ;SAVE CHAR IN [C]
	@INS86	213,362,56,254  ;FETCH FROM CODE SEGMENT
	AND	AL,((127) and 0FFh)  ;GET RID OF HIGH BIT
	JNZ	@IBMRES@_@Q@QL000
	JMP	@NOTRFN  ;IF=0 THEN END OF THIS CHARS RESLT
@IBMRES@_@Q@QL000:
	INC	BX  ;BUMP SOURCE POINTER
	CMP	AL,CL  ;COMPARE TO CHAR FROM SOURCE LINE
	JNZ	@IBMRES@_LOPSKP  ;IF NO MATCH, SEARCH FOR NEXT RESWRD
	@INS86	213,362,56,254  ;FETCH FROM CODE SEGMENT
	INC	DX  ;BUMP RESLST POINTER
	OR	AL,AL  ;SET CC'S
	JS	@IBMRES@_@Q@QL001
	JMP	@IBMRES@_LOPPSI  ;SEE IF REST OF CHARS MATCH
@IBMRES@_@Q@QL001:
	@INS86	213,362,56,254  ;FETCH FROM CODE SEGMENT
	CALL	@MAKUPL  ;GET NEXT CHAR IN LINE (MC 6/22/80)
	CMP	AL,((".") and 0FFh)  ;IS IT A DOT
	JZ	@IBMRES@_ISVARS  ;YES
	CALL	@TSTANM  ;IS IT A LETTER IMMEDIATELY
;FOLLOWING RESWRD
@IBMRES@_ISVARS:	MOV	AL,((0) and 0FFh)  ;SET DONUM TO -1
	JNAE	@IBMRES@_@Q@QL002
	JMP	@NOTRFN  ;IF ALPHA, CANT BE RESERVED WORD
@IBMRES@_@Q@QL002:
	POP	AX  ;GET RID OF SAVED [H,L]
	@INS86	213,362,56,254  ;FETCH FROM CODE SEGMENT
	OR	AL,AL  ;SET CC'S
	POP	CX  ;GET CHAR COUNT OFF STACK
	POP	DX  ;GET DEPOSIT POINTER OFF STACK
	JNS	@IBMRES@_@Q@QL003
	JMP	@IBMRES@_NOTFNT  ;IF MINUS, WASNT FUNCTION TOKEN
@IBMRES@_@Q@QL003:
	OR	AL,((128) and 0FFh)  ;MAKE HIGH ORDER BIT ONE
	STC  ;AND FORCE LEADER BYTE TO BE 375
@IBMRES@_NOTFNT:	PUSH	AX  ;SAVE FN CHAR
	MOV	AL,((254) and 0FFh)  ;GET BYTE WHICH PRECEEDS FNS
	SBB	AL,((0) and 0FFh)  ;MAKE FUNCTION LEADER 375
	JMP	@RENCRN  ;REENTER CRUNCH WITH NEW RESERVED WORD

@IBMRES@_LOPSKP:	POP	BX  ;RESTORE UNDEFILED TEXT POINTER
@IBMRES@_LOPSK2:
	@INS86	213,362,56,254  ;FETCH FROM CODE SEGMENT
	INC	DX  ;BUMP RESLST POINTER
	OR	AL,AL  ;SET CC'S
	JS	@IBMRES@_@Q@QL004
	JMP	@IBMRES@_LOPSK2  ;NOT END OF RESWRD, KEEP SKIPPING
@IBMRES@_@Q@QL004:
	INC	DX  ;POINT AFTER TOKEN
	JMP	@IBMRES@_TRYAGA  ;TRY ANOTHER RESWRD

; SUBTTL  LIST code for extended reserved words

@IBMRES@_BUFRET:	RET

@IBMRES@_NEWFUN:	MOV	AL,byte [BX]  ;GET FUNCTION NUMBER
	AND	AL,((127) and 0FFh)  ;TAKE OFF HIGH BIT
	JMP	@IBMRES@_BUFCON

; PUBLIC	LISTX
@LISTX:	CMP	AL,((253) and 0FFh)  ;IS IT A NEW FUNCTION
	JZ	@IBMRES@_NEWFUN
	CMP	AL,((254) and 0FFh)  ;IS IT A NEW STATEMENT
	JNZ	@IBMRES@_BUFRET  ;NO, JUST CONTINUE NORMAL PATH
	MOV	AL,byte [BX]  ;GET NUMBER OF STATEMENT
@IBMRES@_BUFCON:	POP	BX  ;Get rid of the return address.
	MOV	BX,@IBMRES@_RESLSX-1  ;GET PTR TO START OF RESERVED WORD LIST
	MOV	CH,AL  ;SAVE THIS CHAR IN [B]
	MOV	CL,(("A"-1) and 0FFh)  ;INIT LEADING CHAR VALUE
@IBMRES@_RESSR3:	INC	CL  ;BUMP LEADING CHAR VALUE.
@IBMRES@_RESSR1:	INC	BX  ;BUMP POINTER INTO RESLST
@IBMRES@_RESSRC:	MOV	DH,BH  ;SAVE PTR TO START OF THIS RESWRD
	MOV	DL,BL
@IBMRES@_RESSR2:
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET CHAR FROM RESLST
	OR	AL,AL  ;SET CC'S
	JZ	@IBMRES@_RESSR3  ;IF END OF THIS CHARS TABLE,
;GO BACK & BUMP C
	LAHF
	INC	BX  ;BUMP SOURCE PTR
	SAHF
	JS	@IBMRES@_@Q@QL005
	JMP	@IBMRES@_RESSR2  ;IF NOT END OF THIS RESWRD,
@IBMRES@_@Q@QL005:
;THEN KEEP LOOKING
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET PTR TO RESERVED WORD VALUE
	CMP	AL,CH  ;SAME AS THE ONE WE SEARCH FOR?
	JNZ	@IBMRES@_RESSR1  ;NO, KEEP LOOKING.
	XCHG	BX,DX  ;SAVE FOUND PTR IN [H,L]
	MOV	AL,CL  ;GET LEADING CHAR
	POP	DX  ;RESTORE LINE CHAR COUNT
	POP	CX  ;RESTORE DEPOSIT PTR
	MOV	DL,AL  ;SAVE LEADING CHAR IN [E]

; CODE BELOW NOT NEEDED SINCE NO SPECIAL REVERVED WORDS IN HOOK TABLE

;       CPI     "Z"+1           ;WAS IT A SPECIAL CHAR?
;       JRNZ    NTSPCH          ;NON-SPECIAL CHAR
;       XRA     A               ;SET NON-SPECIAL
;       STA     TEMPA
;       JMPR    MORPUR          ;PRINT IT
@IBMRES@_NTSPCH:	MOV	AL,byte [@TEMPA]  ;WHAT DID WE DO LAST?
	OR	AL,AL  ;SPECIAL?
	MOV	AL,((255) and 0FFh)  ;FLAG IN RESERVED WORD
	MOV	byte [@TEMPA],AL  ;CLEAR FLAG
@IBMRES@_MORLNZ:	JZ	@IBMRES@_MORLN0  ;GET CHAR AND PROCEED
	MOV	AL,((" ") and 0FFh)  ;PUT SPACE IN BUFFER
	MOV	DI,CX
	STOSB
	INC	CX
	DEC	DH  ;ANY SPACE LEFT IN BUFFER
	JNZ	@IBMRES@_@Q@QL006
	JMP	@PPSWRT  ;NO, RETURN
@IBMRES@_@Q@QL006:
@IBMRES@_MORLN0:	MOV	AL,DL
	JMP	@IBMRES@_MORLN1  ;CONTINUE
@IBMRES@_MORPUR:
	@INS86	56  ;FETCH FROM CODE SEGMENT
	MOV	AL,byte [BX]  ;GET BYTE FROM RESWRD
	INC	BX  ;BUMP POINTER
@IBMRES@_MORLNP:	MOV	DL,AL  ;SAVE CHAR
@IBMRES@_MORLN1:	AND	AL,((127) and 0FFh)  ;AND OFF HIGH ORDER BIT FOR DISK & EDIT
	MOV	DI,CX
	STOSB  ;STORE THIS CHAR
	INC	CX  ;BUMP PTR
	DEC	DH  ;BUMP DOWN REMAINING CHAR COUNT
	JNZ	@IBMRES@_@Q@QL007
	JMP	@PPSWRT  ;IF END OF LINE, JUST RETURN
@IBMRES@_@Q@QL007:
	OR	AL,DL  ;SET CC'S
	JS	@IBMRES@_@Q@QL008
	JMP	@IBMRES@_MORPUR  ;END OF RESWRD?
@IBMRES@_@Q@QL008:
	POP	BX  ;RESTORE SOURCE PTR.
	INC	BX  ;SKIP OVER RESERVED WORD
	JMP	@PLOOP2  ;GET NEXT CHAR FROM LINE

; SUBTTL  Extended Statement Dispatching

@IBMRES@_SNERRS:	JMP	@SNERR

; PUBLIC	NEWSTX
@NEWSTX:	CMP	AL,((254-129) and 0FFh)  ;CHECK FOR NEW STATEMENT PREFIX
	JZ	@IBMRES@_GONE4  ;IF SO, DISPATCH
	CMP	AL,((255-129) and 0FFh)  ;FUNCTION?
	JNZ	@IBMRES@_GIIRET
	POP	CX  ;Put return address into B.
	INC	BX
	MOV	AL,byte [BX]
	CMP	AL,((@@SPEN) and 0FFh)  ; PEN as stmt?
	JNZ	@IBMRES@_@Q@QL009
	JMP	@IBMRES@_PENV  ; Brif so.
@IBMRES@_@Q@QL009:
	CMP	AL,((@@SSTRIG) and 0FFh)  ;STRIG as stmt?
	JNZ	@IBMRES@_@Q@QL010
	JMP	@IBMRES@_STRIGV  ; Brif so.
@IBMRES@_@Q@QL010:
	DEC	BX
	MOV	AL,((255-129) and 0FFh)
	PUSH	CX  ;Put the return address back on.
@IBMRES@_GIIRET:	RET  ;MID$ OR SYNTAX ERROR

@IBMRES@_PENV:	CALL	@CHRGTR
	JMP	@PENS
@IBMRES@_STRIGV:	CALL	@CHRGTR
	JMP	@STRIGS

@IBMRES@_GONE4:	POP	CX  ;Get rid of the return address.
	INC	BX  ;LOOK AT NEXT CHAR
	MOV	AL,byte [BX]  ;FETCH IT
	SUB	AL,((129) and 0FFh)  ;GET RELATIVE POSITION IN STMDSX
	JB	@IBMRES@_SNERRS  ;IF TOO SMALL, SYNTAX ERROR
	ADD	AL,AL  ;TURN BYTE INTO OFFSET
	@INS86	62,344  ;XOR AH,AH
	@INS86	213,360  ;MOV SI,AX - GET OFFSET INTO [SI]
	@INS86	56  ;CODE SEGMENT OVERRIDE
	@INS86	377,264,@IBMRES@_STMDSX  ;PUSH STMDSP(SI) - PUSH ADDRESS
	JMP	@CHRGTR  ;START STATEMENT

; SUBTTL  EVAL code for extended functions

; PUBLIC	EVALX
@EVALX:	CMP	AL,((254) and 0FFh)
	JZ	@IBMRES@_EVALNS  ;Brif possible stmt as function
	CMP	AL,((253) and 0FFh)
	JZ	@IBMRES@_EVALNF  ;NEW FUNCTION IF 375 IN FRONT
	RET

@IBMRES@_EVALNS:	INC	BX
	MOV	AL,byte [BX]
	CMP	AL,((@@SDATE@S) and 0FFh)
	JZ	@IBMRES@_DATEV  ;Brif DATE$
	CMP	AL,((@@STIME@S) and 0FFh)
	JZ	@IBMRES@_TIMEV  ;Brif TIME$
	DEC	BX
	MOV	AL,byte [BX]
	RET

@IBMRES@_DATEV:	POP	CX  ;Get rid of the hook return address.
	JMP	@DATEF  ;Do DATE function.

@IBMRES@_TIMEV:	POP	CX  ;Get rid of the hook return address.
	JMP	@TIMEF  ;Do TIME$ function.

@IBMRES@_EVALNF:	POP	CX  ;Get rid of the return address.
	INC	BX
	MOV	AL,byte [BX]
	SUB	AL,((129) and 0FFh)
	MOV	CH,((0) and 0FFh)
	ROL	AL,1
	MOV	CL,AL
	PUSH	CX
	CALL	@CHRGTR
	CALL	@PARCHK
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI
	MOV	DX,@LABBCK
	PUSH	DX
	MOV	AL,((1) and 0FFh)
	MOV	byte [@FLGOVC],AL
	@INS86	213,363  ;MOV SI,BX (GET FUNCTION OFFSET IN SI)
	@INS86	56
	@INS86	377,264,@IBMRES@_FUNDSX
	RET

