	XCHG	BX,DX  ;PUT NEW LINE # IN [D,E], THIS LINE
;PTR IN [H,L]
	INC	BX  ;POINT TO LINE # FIELD.
	MOV	[BX],DX  ;CHANGE TO NEW LINE #
	XCHG	BX,DX  ;GET THIS LINE # IN [H,L]
	ADD	BX,CX  ;ADD INC
	XCHG	BX,DX  ;GET NEW LINE # BACK IN [D,E]
	POP	BX  ;GET PTR TO NEXT LINE
	JMP	@GWMAIN@_RESNX1  ;KEEP RESEQING
@GWMAIN@_SCCALL: MOV	CX,@STPRDY  ;WHERE TO GO WHEN DONE
	PUSH	CX  ;SAVE ON STACK
	DB	60  ; SKIP  ;"CPI AL," CALL SCCPTR
; THE SUBROUTINES SCCLIN AND SCCPTR CONVERT ALL
; LINE #'S TO POINTERS AND VICE-VERSA.
; THE ONLY SPECIAL CASE IS "ON ERROR GOTO 0" WHERE THE "0"
; IS LEFT AS A LINE NUMBER TOKEN SO IT WONT BE CHANGED BY RESEQUENCE.
@GWMAIN@_SCCLIN: DB	13  ; SKIP  ;"ORI AX," OVER NEXT BYTE
; PUBLIC	SCCPTR
@SCCPTR: XOR	AL,AL  ;SET A=0
	MOV	byte [@PTRFLG],AL  ;SET TO SAY WHETER LINES OR PTRS EXTANT
@GWMAIN@_SCNPGM: MOV	BX,[@TXTTAB]  ;GET PTR TO START OF PGM
	DEC	BX  ;NOP NEXT INX.
@GWMAIN@_SCNPLN: INC	BX  ;POINT TO BYTE AFTER ZERO AT END OF LINE
	MOV	AL,byte [BX]  ;GET LINK FIELD INTO [D,E]
	INC	BX  ;BUMP PTR
	OR	AL,byte [BX]  ;SET CC'S
	JNZ	$+3
	RET  ;RETURN IF ALL DONE.
	INC	BX  ;POINT PAST LINE #
	MOV	DX,[BX]  ;GET LOW BYTE OF LINE #
	INC	BX
; PUBLIC	SCNEXT
@SCNEXT: CALL	@CHRGTR  ;GET NEXT CHAR FROM LINE
@GWMAIN@_SCNEX2: OR	AL,AL  ;END OF LINE
	JZ	@GWMAIN@_SCNPLN  ;SCAN NEXT LINE
	MOV	CL,AL  ;SAVE [A]
	MOV	AL,byte [@PTRFLG]  ;CHANGE LINE TOKENS WHICH WAY?
	OR	AL,AL  ;SET CC'S
	MOV	AL,CL  ;GET BACK CURRENT CHAR
	JZ	@GWMAIN@_SCNPT2  ;CHANGING POINTERS TO #'S
	CMP	AL,((@@SERROR) and 0FFh)  ;IS IT ERROR TOKEN?
	JNZ	@GWMAIN@_NTERRG  ;NO.
