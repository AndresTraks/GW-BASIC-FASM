	MOV	AL,byte [BX]  ;GET THE CHARACTER AGAIN
	JZ	@GWMAIN@_NTDATA  ;IF NO CRUNCHING JUST STORE
;THE CHARACTER
@GWMAIN@_STUFFH: INC	BX  ;ENTRY TO BUMP [H,L]
	PUSH	AX  ;SAVE CHAR AS KRNSAV CLOBBERS
	CALL	@GWMAIN@_KRNSAV  ;SAVE CHAR IN KRUNCH BUFFER
	POP	AX  ;RESTORE CHAR
	SUB	AL,((":") and 0FFh)  ;SEE IF IT IS A COLON
	JZ	@GWMAIN@_COLIS  ;IF SO ALLOW CRUNCHING AGAIN
	CMP	AL,((@@SDATCO) and 0FFh)
