	DEC	BX  ;NOP THE INX H IN CHRGET
@GWMAIN@_REMER1: CALL	@CHRGTR  ;GET A CHAR
	OR	AL,AL  ;ZERO IS ALWAYS A TERMINATOR
	JNZ	$+3
	RET
	CMP	AL,CH  ;TEST FOR THE OTHER TERMINATOR
	JNZ	$+3
	RET
	INC	BX
