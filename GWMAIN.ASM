	INC	BX  ;POINT TO HIGH PART
	MOV	CH,byte [BX]
	MOV	AL,((@GWMAIN@_LINCON) and 0FFh)  ;CHANGE TO LINE CONSTANT
@GWMAIN@_MAKPTR: MOV	BX,@GWMAIN@_SCNPOP  ;PLACE TO RETURN TO AFTER CHANGING CONSTANT
