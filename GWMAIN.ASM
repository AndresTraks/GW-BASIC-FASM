;KLUDGE AS HAS TO BE NON-ZERO.
@GWMAIN@_COLIS:	MOV	byte [@DORES],AL  ;SETUP FLAG
	MOV	byte [@DONUM],AL  ;SET NUMBER ALLOWED FLAG
@GWMAIN@_NODATT: SUB	AL,((@@SREMCO) and 0FFh)
	JNZ	@GWMAIN@_KLOOP  ;KEEP LOOPING
	PUSH	AX  ;SAVE TERMINATOR ON STACK
@GWMAIN@_STR1:	MOV	AL,byte [BX]  ;GET A CHAR
	OR	AL,AL  ;SET CONDITION CODES
	POP	AX  ;GET AL BACK WITHOUT AFFECTING PSW
	JZ	@GWMAIN@_CRDONE  ;IF END OF LINE THEN DONE
	CMP	AL,byte [BX]  ;COMPARE CHAR WITH THIS TERMINATOR
	JZ	@GWMAIN@_STUFFH  ;IF YES, DONE WITH STRING
@GWMAIN@_STRNG:
	PUSH	AX  ;SAVE TERMINATOR
	MOV	AL,byte [BX]  ;GET BACK LINE CHAR
@GWMAIN@_STRNG2: INC	BX  ;INCREMENT TEXT POINTER
	CALL	@GWMAIN@_KRNSAV  ;SAVE CHAR IN KRUNCH BUFFER
	JMP	@GWMAIN@_STR1  ;KEEP LOOPING
; NOW CHECK HGHBIT CHARS, ? FOR PRINT
@GWMAIN@_NTDATA:
	INC	BX  ;IF SO SKIP IT
	OR	AL,AL  ;IS THIS A KANA CHARACTER IN A BAD PLACE?
	JNS	@GWMAIN@_@Q@QL019
	JMP	@GWMAIN@_KLOOP  ;MOVE TO THE NEXT CHARACTER
@GWMAIN@_@Q@QL019:
	DEC	BX  ;RESTORE THE TEXT POINTER
	CMP	AL,(("?") and 0FFh)  ;A QMARK?
	MOV	AL,((@@SPRINT) and 0FFh)
	PUSH	DX  ;SAVE STORE POINTER
	PUSH	CX  ;SAVE CHAR COUNT
	JNZ	@GWMAIN@_@Q@QL020
	JMP	@GWMAIN@_NOTFN2  ;THEN USE A "PRINT" TOKEN
@GWMAIN@_@Q@QL020:
;***5.11 DONT ALLOW FOLLOWING LINE #***
	MOV	DX,@SPCTAB  ;ASSUME WE'LL SEARCH SPECIAL CHAR TABLE
	CALL	@MAKUPL  ;TRANSLATE THIS CHAR TO UPPER CASE
	CALL	@ISLET2  ;LETTER?
	JAE	@GWMAIN@_@Q@QL021
	JMP	@GWMAIN@_TSTNUM  ;NOT A LETTER, TEST FOR NUMBER
@GWMAIN@_@Q@QL021:
	PUSH	BX  ;SAVE TEXT POINTER
; ANSI SAYS YOU CAN USE "GO TO" AND "GO SUB" WITH ANY NUMBER OF SPACES
	MOV	DX,@GWMAIN@_GOSTEX  ;CHECK FOR "GO "
	CALL	@GWMAIN@_CHKRES  ;THAT IT?
	JNZ	@GWMAIN@_NOTGOS  ;NOPE
	CALL	@CHRGTR  ;SKIP ANY NUMBER OF SPACES
	MOV	DX,@GWMAIN@_TOTEX  ;IS IT TO?
	CALL	@GWMAIN@_CHKRES  ;CHECK
	MOV	AL,((@@SGOTO) and 0FFh)  ;ASSUME SO
	JNZ	@GWMAIN@_@Q@QL022
	JMP	@GWMAIN@_GPUTRS  ;USE IT
