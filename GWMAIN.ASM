@FNDFOR: MOV	BX,4+0  ;IGNORING EVERYONES "NEWSTT"
;AND THE RETURN ADDRESS OF THIS
	ADD	BX,SP  ;SUBROUTINE, SET [H,L]=SP
@GWMAIN@_LOOPER:

	INC	BX  ;8086 USES TWO BYTE ENTRIES

	MOV	AL,byte [BX]  ;SEE WHAT TYPE OF THING IS ON THE STACK
	INC	BX

	@GWMAIN@_WHLSIZ=6
	CMP	AL,((@@SWHILE) and 0FFh)
	JNZ	@GWMAIN@_STKSRC
	MOV	CX,@GWMAIN@_WHLSIZ
	ADD	BX,CX
	JMP	@GWMAIN@_LOOPER
@GWMAIN@_STKSRC:

	CMP	AL,((@@SFOR) and 0FFh)  ;IS THIS STACK ENTRY A "FOR"?
	JZ	$+3
	RET  ;NO SO OK
	MOV	CL,byte [BX]
	INC	BX  ;DO EQUIVALENT OF PUSHM / XTHL
	MOV	CH,byte [BX]
	INC	BX
	PUSH	BX  ;PUT H  ON
	MOV	BX,CX

	OR	DX,DX  ;"NEXT" STATMENT WITHOUT AN ARGUMENT ?
;WE MATCH ON ANYTHING
	XCHG	BX,DX  ;MAKE SURE WE RETURN [D,E]
	JZ	@GWMAIN@_POPGOF  ;POINTING TO THE VARIABLE
	XCHG	BX,DX

	CMP	BX,DX
	@GWMAIN@_FORSIZ=16

	@GWMAIN@_FORSIZ=17
	@GWMAIN@_FORSIZ=@GWMAIN@_FORSIZ+2  ;For text pointer into NEXT.

; Note - 8086 versions force stack entries to be an even length
; so stack accesses won't cross word boundaries.  This is done
; for speed.  To accomplish this, an extra byte is pushed on
; top of the FOR token.  This extra byte is NOT reflected in
; the value of FORSIZ but is taken care of by the code.

; PUBLIC	FORSZC
	@FORSZC=0+@GWMAIN@_FORSIZ
@GWMAIN@_POPGOF: MOV	CX,@FORSZC-3  ;TO WIPE OUT A "FOR" ENTRY
;Note that the pointer has already
;been incremented three times.
	POP	BX
	JNZ	$+3
	RET  ;IF VARIABLE IN THIS ENTRY MATCHES
;RETURN WITH [H,L] POINTING THE BOTTOM
;OF THE ENTRY
	ADD	BX,CX
	JMP	@GWMAIN@_LOOPER  ;NOW POINTING TO THE START OF THE NEXT
;ENTRY. SEE IF ITS A "FOR" ENTRY
