	JMP	@GWMAIN@_FORTRM  ;MIGHT BE AN EIGTH BIT LITERAL THAT
@GWMAIN@_NTREMR: CMP	AL,((@@SDATA) and 0FFh)  ;ACCIDENTALLY MATCHES THE SEARCH
