; SUBTTL AUTO COMMAND
; THE AUTO [BEGGINNING LINE[,[INCREMENT]]]
; COMMAND IS USED TO AUTOMATICALLY GENERATE LINE NUMBERS
; FOR LINES TO BE INSERTED. BEGINNING LINE IS
; USED TO SPECIFY THE INITAL LINE (10 IS ASSUMED IF OMMITED)
; AND THE INCREMENT IS USED TO SPECIFY THE INCREMENT USED
; TO GENERATE THE NEXT LINE #. IF ONLY A COMMA IS USED AFTER THE
; BEGGINING LINE, THE OLD INCREMENT IS USED.
@AUTO:	MOV	DX,10  ;ASSUME INITIAL LINE # OF 10
	PUSH	DX  ;SAVE IT
	JZ	@GWMAIN@_SNGAUT  ;IF END OF COMMAND USE 10,10
	CALL	@LINSPC  ;GET LINE #, ALLOW USE OF . FOR CURRENT LINE
	XCHG	BX,DX  ;GET TXT PTR IN [D,E]
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;PUT INIT ON STACK, GET 10 IN [H,L]
	JZ	@GWMAIN@_SNGAU1  ;IF TERMINATOR, USE INC OF 10
	XCHG	BX,DX  ;GET TEXT PTR BACK IN [H,L]
	CALL	@SYNCHR
	DB	44  ;COMMA MUST FOLLOW
	MOV	DX,[@AUTINC]  ;GET PREVIOUS INC
	JZ	@GWMAIN@_SNGAUT  ;USE PREVIOUS INC IF TERMINATOR
	CALL	@LINGET  ;GET INC
	JZ	@GWMAIN@_@Q@QL059
	JMP	@SNERR  ;SHOULD HAVE FINISHED.
@GWMAIN@_@Q@QL059:
@GWMAIN@_SNGAUT: XCHG	BX,DX  ;GET INC IN [H,L]
@GWMAIN@_SNGAU1: MOV	AL,BH  ;SEE IF ZERO
	OR	AL,BL
	JNZ	@GWMAIN@_@Q@QL060
	JMP	@FCERR  ;ZERO INC GIVES FCERR
@GWMAIN@_@Q@QL060:
	MOV	[@AUTINC],BX  ;SAVE INCREMENT
	MOV	byte [@AUTFLG],AL  ;SET FLAG TO USE AUTO IN MAIN CODE.
	POP	BX  ;GET INITIAL LINE #
	MOV	[@AUTLIN],BX  ;SAVE IN INTIAL LINE
	POP	CX  ;GET RID OF NEWSTT ADDR
	JMP	@MAIN  ;JUMP INTO MAIN CODE (FOR REST SEE AFTER MAIN:)

; SUBTTL IF ... THEN CODE
@IFS:	CALL	@FRMEVL  ;EVALUATE A FORMULA
	MOV	AL,byte [BX]  ;GET TERMINATING CHARACTER OF FORMULA
	CMP	AL,((44) and 0FFh)
	JNZ	@GWMAIN@_@Q@QL061
	CALL	@CHRGTR  ;IF SO SKIP IT
@GWMAIN@_@Q@QL061:
	CMP	AL,((@@SGOTO) and 0FFh)  ;ALLOW "GOTO" AS WELL
	JZ	@GWMAIN@_OKGOTO
	CALL	@SYNCHR
	DB	@THENTK  ;MUST HAVE A THEN
	DEC	BX
@GWMAIN@_OKGOTO:
	PUSH	BX  ;SAVE THE TEXT POINTER
	CALL	@VSIGN
	POP	BX  ;GET BACK THE TEXT POINTER
	JZ	@GWMAIN@_FALSIF  ;HANDLE POSSIBLE "ELSE"
@GWMAIN@_DOCOND: CALL	@CHRGTR  ;PICK UP THE FIRST LINE # CHARACTER
	JNZ	$+3
	RET  ;RETURN FOR "THEN :" OR "ELSE :"
	CMP	AL,((@GWMAIN@_LINCON) and 0FFh)  ;LINE NUMBER CONSTANT?
	JNZ	@GWMAIN@_@Q@QL062
	JMP	@GOTO  ;DO A "GOTO"
@GWMAIN@_@Q@QL062:
	CMP	AL,((@GWMAIN@_PTRCON) and 0FFh)  ;POINTER CONSTANT
	JZ	@GWMAIN@_@Q@QL063
	JMP	@GWMAIN@_GONE2  ;EXECUTE STATEMENT, NOT GOTO
@GWMAIN@_@Q@QL063:
	MOV	BX,[@CONLO]  ;GET TEXT POINTER
	RET  ;FETCH NEW STATMENT

; "ELSE" HANDLER. HERE ON FALSE "IF" CONDITION

@GWMAIN@_FALSIF: MOV	DH,((1) and 0FFh)  ;NUMBER OF "ELSE"S THAT MUST
;BE SEEN. "DATA" INCREMENTS THIS
;COUNT EVERY TIME AN "IF" IS SEEN
@GWMAIN@_SKPMRF: CALL	@DATA  ;SKIP A STATEMENT
;":" IS STUCK IN FRONT OF "ELSE"S
;SO THAT "DATA" WILL STOP BEFORE "ELSE" CLAUSES
	OR	AL,AL  ;END OF LINE?
	JNZ	$+3
	RET  ;IF SO, NO "ELSE" CLAUSE
	CALL	@CHRGTR  ;SEE IF WE HIT AN "ELSE"
	CMP	AL,((@@SELSE) and 0FFh)
	JNZ	@GWMAIN@_SKPMRF  ;NO, STILL IN THE "THEN" CLAUSE
	DEC	DH  ;DECREMENT THE NUMBER OF "ELSE"S THAT
;MUST BE SEEN
	JNZ	@GWMAIN@_SKPMRF  ;SKIP MORE IF HAVEN'T SEEN
;ENOUGH
	JMP	@GWMAIN@_DOCOND  ;FOUND THE RIGHT "ELSE" -- GO EXECUTE

; SUBTTL PRINT CODE

; EXTRN	LPRINT:NEAR,LPRINT:NEAR,FINPRT:NEAR

; SUBTTL LINE INPUT, INPUT AND READ CODE
@LINE:
; EXTRN	GLINE:NEAR
	CMP	AL,((@@SINPUT) and 0FFh)
	JZ	@GWMAIN@_@Q@QL064
	JMP	@GLINE  ;MUST BE GRAPHICS TYPE LINE
@GWMAIN@_@Q@QL064:
	CALL	@SYNCHR
	DB	@@SINPUT
	CMP	AL,(("#") and 0FFh)  ;SEE IF THERE IS A FILE NUMBER
; EXTRN	DLINE:NEAR
	JNZ	@GWMAIN@_@Q@QL065
	JMP	@DLINE  ;DO DISK INPUT LINE
@GWMAIN@_@Q@QL065:
	CALL	@SCNSEM  ;SCAN SEMICOLON FOR NO-CR
	CALL	@GWMAIN@_QTINP  ;PRINT QUOTED STRING IF ONE
	CALL	@PTRGET  ;READ STRING TO STORE INTO
	CALL	@CHKSTR  ;MAKE SURE ITS A STRING
	PUSH	DX  ;SAVE POINTER AT VARIABLE
	PUSH	BX  ;SAVE TEXT POINTER
; EXTRN	SINLIN:NEAR
	CALL	@SINLIN  ;READ A LINE OF INPUT
	POP	DX  ;GET TEXT POINTER
	POP	CX  ;GET POINTER AT VARIABLE
	JAE	@GWMAIN@_@Q@QL066
	JMP	@STPEND  ;IF CONTROL-C, STOP
@GWMAIN@_@Q@QL066:
@GWMAIN@_RELINE: PUSH	CX  ;SAVE BACK VARIABLE POINTER
	PUSH	DX  ;SAVE TEXT POINTER
	MOV	CH,((0) and 0FFh)  ;SETUP ZERO AS ONLY TERMINATOR
	CALL	@STRLT3  ;LITERALIZE THE INPUT
	POP	BX  ;RESTORE [H,L]=TEXT POINTER
	MOV	AL,((3) and 0FFh)  ;SET THREE FOR STRING
	JMP	@GWMAIN@_LETCN2  ;DO THE ASSIGNMENT

@GWMAIN@_TRYAGN:
	DB "?Redo from start"
	@ACRLF
	DB	0

; HERE WHEN PASSING OVER STRING LITERAL IN SUBSCRIPT OF VARIABLE IN INPUT LIST
; ON THE FIRST PASS OF INPUT CHECKING FOR TYPE MATCH AND NUMBER

@GWMAIN@_SCNSTR: INC	BX  ;LOOK AT THE NEXT CHARACTER
	MOV	AL,byte [BX]  ;FETCH IT
	OR	AL,AL  ;END OF LINE?
	JNZ	@GWMAIN@_@Q@QL067
	JMP	@SNERR  ;ENDING IN STRING IN SUBSCRIPT IS BAD SYNTAX
@GWMAIN@_@Q@QL067:
	CMP	AL,((34) and 0FFh)  ;ONLY OTHER TERMINATOR IS QUOTE
	JNZ	@GWMAIN@_SCNSTR  ;CONTINUE UNTIL QUOTE OR 0 IS FOUND
	JMP	@GWMAIN@_SCNCON  ;CONTINUE MATCHING PARENS SINCE STRING ENDED

@GWMAIN@_INPBAK: POP	BX  ;GET RID OF PASS1 DATA POINTER
	POP	BX  ;GET RID OF PASS2 DATA POINTER
	JMP	@GWMAIN@_RDOIN2  ;GET RID OF PASS2 VARLST POINTER AND RETRY

; HERE WHEN THE DATA THAT WAS TYPED IN OR IN "DATA" STATEMENTS
; IS IMPROPERLY FORMATTED. FOR "INPUT" WE START AGAIN.
; FOR "READ" WE GIVE A SYNTAX ERROR AT THE DATA LINE

@GWMAIN@_TRMNOK:
	MOV	AL,byte [@FLGINP]  ;WAS IT READ OR INPUT?
	OR	AL,AL  ;ZERO=INPUT
	JZ	@GWMAIN@_@Q@QL068
	JMP	@GWMAIN@_DATSNE  ;GIVE ERROR AT DATA LINE
@GWMAIN@_@Q@QL068:
@GWMAIN@_RDOIN2: POP	CX  ;GET RID OF THE POINTER INTO THE VARIABLE LIST
@GWMAIN@_RDOINP:
	MOV	BX,@GWMAIN@_TRYAGN
	CALL	@STROUT  ;PRINT "?REDO FROM START"
	MOV	BX,[@SAVTXT]  ;GET SAVED TEXT POINTER
	RET  ;GO BACK TO NEWSTT
;OF THE "INPUT" STATEMENT
@GWMAIN@_FILSTI: CALL	@FILINP
	PUSH	BX  ;PUT THE TEXT POINTER ON THE STACK
	MOV	BX,@BUFMIN  ;POINT AT A COMMA
	JMP	@GWMAIN@_INPCN3
@INPUT:

	CMP	AL,(("#") and 0FFh)
	JZ	@GWMAIN@_FILSTI
	CALL	@SCNSEM  ;SCAN SEMICOLON FOR NO-CR
	MOV	CX,@GWMAIN@_NOTQTI  ;WHERE TO GO
	PUSH	CX  ;WHEN DONE WITH QUOTED STRING
@GWMAIN@_QTINP:	CMP	AL,((34) and 0FFh)  ;IS IT A QUOTE?
	MOV	AL,((0) and 0FFh)  ;BE TALKATIVE
	MOV	byte [@CNTOFL],AL  ;FORCE OUTPUT
	MOV	AL,((255) and 0FFh)  ;MAKE NON-ZERO VALUE
	MOV	byte [@TEMPA+1],AL  ;FLAG TO DO "? "
	JZ	$+3
	RET  ;JUST RETURN
	CALL	@STRLTI  ;MAKE THE MESSAGE A STRING
	MOV	AL,byte [BX]  ;GET CHAR
	CMP	AL,((44) and 0FFh)  ;COMMA?
	JNZ	@GWMAIN@_NTICMA  ;NO
	XOR	AL,AL  ;FLAG NOT TO DO IT
	MOV	byte [@TEMPA+1],AL
	CALL	@CHRGTR  ;FETCH NEXT CHAR
	JMP	@GWMAIN@_INPCMA  ;CONTINUE
@GWMAIN@_NTICMA:
	CALL	@SYNCHR
	DB	59  ;MUST END WITH SEMI-COLON
@GWMAIN@_INPCMA:
	PUSH	BX  ;REMEMBER WHERE IT ENDED
	CALL	@STRPRT  ;PRINT IT OUT
	POP	BX  ;GET BACK SAVED TEXT PTR
	RET  ;ALL DONE
@GWMAIN@_NOTQTI:
	PUSH	BX
@GWMAIN@_GETAGN:
	MOV	AL,byte [@TEMPA+1]  ;DO "? "
	OR	AL,AL
	JZ	@GWMAIN@_SUPPRS  ;THEN SUPPRESS "?"
	MOV	AL,(("?") and 0FFh)  ;TYPE "?" AND INPUT A LINE OF TEXT
	CALL	@OUTDO
	MOV	AL,((" ") and 0FFh)
	CALL	@OUTDO
@GWMAIN@_SUPPRS:
	CALL	@SINLIN
	POP	CX  ;TAKE OFF SINCE MAYBE LEAVING
	JAE	@GWMAIN@_@Q@QL069
	JMP	@STPEND  ;IF EMPTY LEAVE
@GWMAIN@_@Q@QL069:
	PUSH	CX  ;PUT BACK  SINCE DIDN'T LEAVE

; THIS IS THE FIRST PASS DICTATED BY ANSI REQUIRMENT THAN NO VALUES BE ASSIGNED
; BEFORE CHECKING TYPE AND NUMBER. THE VARIABLE LIST IS SCANNED WITHOUT EVALUATING
; SUBSCRIPTS AND THE INPUT IS SCANNED TO GET ITS TYPE. NO ASSIGNMENT
; IS DONE

	XOR	AL,AL  ;FLAG AS INPUT SO SCNVAL WILL WORK
	MOV	byte [@FLGINP],AL  ;WHEN SCANNING STRINGS WITH ":"
	MOV	byte [BX],((44) and 0FFh)  ;PUT A COMMA IN FRONT OF BUF
	XCHG	BX,DX  ;SAVE DATA POINTER IN [D,E]
	POP	BX  ;GET THE VARLST POINTER INTO [H,L]
	PUSH	BX  ;RESAVE THE VARLST POINTER
	PUSH	DX  ;SAVE A COPY OF THE DATA POINTER FOR PASS2
	PUSH	DX  ;SAVE THE DATA POINTER FOR PASS1
	DEC	BX  ;READ THE FIRST VARIABLE NAME
@GWMAIN@_VARLOP: MOV	AL,((128) and 0FFh)  ;DON'T ALLOW SUBSCRIPTS -- RETURN POINTING TO "("
	MOV	byte [@SUBFLG],AL
	CALL	@CHRGTR  ;ADVANCE TEXT POINTER
; EXTRN	PTRGTN:NEAR
	CALL	@PTRGTN  ;SCAN NAME AND RETURN POINTER IN [D,E]
	MOV	AL,byte [BX]  ;SEE IF IT ENDED ON "("
	DEC	BX  ;RESCAN THE TERMINATOR
	CMP	AL,(("[") and 0FFh)  ;allow brackets also
	JZ	@GWMAIN@_SCNBKT
	CMP	AL,(("(") and 0FFh)  ;ARRAY OR NOT?
	JNZ	@GWMAIN@_ENDSCN  ;IF NOT, VARIABLE NAME IS DONE
@GWMAIN@_SCNBKT: INC	BX  ;NOW SCAN THE SUBSCRIPT EXPRESSION
	MOV	CH,((0) and 0FFh)  ;INITIALIZE THE PAREN COUNT
@GWMAIN@_SCNOPN: INC	CH  ;UP THE COUNT FOR EVERY "("
@GWMAIN@_SCNCON: CALL	@CHRGTR  ;GET THE NEXT CHARACTER
	JNZ	@GWMAIN@_@Q@QL070
	JMP	@SNERR  ;SHOULDN'T END STATEMENT IN EXPRESSION
@GWMAIN@_@Q@QL070:
	CMP	AL,((34) and 0FFh)  ;IS THERE A QUOTED STRING CONSTANT
	JNZ	@GWMAIN@_@Q@QL071
	JMP	@GWMAIN@_SCNSTR  ;GO SCAN THE ENDTIRE CONSTANT (MAY CONTAIN PARENS)
@GWMAIN@_@Q@QL071:
	CMP	AL,(("(") and 0FFh)  ;ANOTHER LEVEL OF NESTING?
	JZ	@GWMAIN@_SCNOPN  ;INCREMENT COUTN AND KEEP SCANNING
	CMP	AL,(("[") and 0FFh)  ;left bracket?
	JZ	@GWMAIN@_SCNCON  ;yes, ok
	CMP	AL,(("]") and 0FFh)  ;left bracket?
	JZ	@GWMAIN@_LEFPRN  ;yes
	CMP	AL,((")") and 0FFh)  ;ONE LESS LEVEL OF PARENS?
	JNZ	@GWMAIN@_SCNCON  ;NO, KEEP SCANNING
;DECREMENT PAREN COUNT. OUT OF SUBSCRIPT?
@GWMAIN@_LEFPRN: DEC	CH
	JNZ	@GWMAIN@_SCNCON  ;IF NOT AT ZERO LEVEL, KEEP SCANNING
@GWMAIN@_ENDSCN: CALL	@CHRGTR  ;GET TERMINATING CHARACTER
	JZ	@GWMAIN@_OKVLST  ;LAST VARIABLE IN INPUT LIST
	CMP	AL,((44) and 0FFh)  ;OTHERWISE IT MUST BE A COMMA
	JZ	@GWMAIN@_@Q@QL072
	JMP	@SNERR  ;BADLY FORMED INPUT -- SYNTAX ERROR
@GWMAIN@_@Q@QL072:
@GWMAIN@_OKVLST: POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;SAVE THE VARLST POINTER 
;GET THE DATA POINTER INTO [H,L]
	MOV	AL,byte [BX]  ;DATA SHOULD ALWAYS HAVE A LEADING COMMA
	CMP	AL,((44) and 0FFh)  ;IS IT PROPERLY FORMED?
	JZ	@GWMAIN@_@Q@QL073
	JMP	@GWMAIN@_INPBAK  ;NO, ASK FOR COMPLETE REINPUT
@GWMAIN@_@Q@QL073:
	MOV	AL,((1) and 0FFh)  ;SET OVCSTR=1
	MOV	byte [@OVCSTR],AL
	MOV	byte [@FLGSCN],AL  ;Flag to SCNVAL that call is from INPUT
	CALL	@GWMAIN@_SCNVAL  ;GO INTO PASS2 CODE AND SCAN A VALUE
	MOV	AL,byte [@FLGSCN]
	DEC	AL  ;Restore flag
	MOV	byte [@FLGSCN],AL
	MOV	AL,byte [@OVCSTR]  ;SEE IF IT WAS TOO BIG
	DEC	AL
	JZ	@GWMAIN@_@Q@QL074
	JMP	@GWMAIN@_INPBAK
@GWMAIN@_@Q@QL074:
	PUSH	BX  ;SAVE THE RETURNED DATA POINTER
	CALL	@GETYPR  ;RELEASE STRING
	JNZ	@GWMAIN@_@Q@QL075
	CALL	@FREFAC
@GWMAIN@_@Q@QL075:
	POP	BX
	DEC	BX  ;SKIP OVER SPACES LEFT AFTER VALUE SCAN
	CALL	@CHRGTR

; NOTE CHECK FOR OVERFLOW OF INPUT VALUE HERE

	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;SAVE THE DATA POINTER
;[H,L]=DATA LIST POINTER
	MOV	AL,byte [BX]  ;DID VARIABLE LIST CONTINUE?
	CMP	AL,((44) and 0FFh)  ;MUST HAVE HAD A COMMA
	JNZ	@GWMAIN@_@Q@QL076
	JMP	@GWMAIN@_VARLOP  ;GO CHECK ANOTHER
@GWMAIN@_@Q@QL076:
	POP	BX  ;GET FINAL DATA POINTER
	DEC	BX  ;SKIP OVER ANY TRAILING SPACES
	CALL	@CHRGTR
	OR	AL,AL  ;IS IT A TRUE END?
	POP	BX  ;GET THE START OF DATA POINTER FOR PASS2
	JZ	@GWMAIN@_@Q@QL077
	JMP	@GWMAIN@_RDOIN2  ;IF DATA ENDED BADLY ASK FOR REINPUT
@GWMAIN@_@Q@QL077:
@GWMAIN@_INPCN3:
	MOV	byte [BX],((44) and 0FFh)  ;SETUP COMMA AT BUFMIN
	JMP	@GWMAIN@_INPCON
@READ:
	PUSH	BX  ;SAVE THE TEXT POINTER
	MOV	BX,[@DATPTR]  ;GET LAST DATA LOCATION
	DB	13  ; SKIP  ;"ORI" TO SET [A] NON-ZERO
@GWMAIN@_INPCON: XOR	AL,AL  ;SET FLAG THAT THIS IS AN INPUT
	MOV	byte [@FLGINP],AL  ;STORE THE FLAG

; IN THE PROCESSING OF DATA AND READ STATEMENTS:
; ONE POINTER POINTS TO THE DATA (IE THE NUMBERS BEING FETCHED)
; AND ANOTHER POINTS TO THE LIST OF VARIABLES

; THE POINTER INTO THE DATA ALWAYS STARTS POINTING TO A
; TERMINATOR -- A , : OR END-OF-LINE

	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;[H,L]=VARIABLE LIST POINTER
;DATA POINTER GOES ON THE STACK
	JMP	@GWMAIN@_LOPDAT
@GWMAIN@_LOPDT2: CALL	@SYNCHR
	DB	44  ;MAKE SURE THERE IS A ","
@GWMAIN@_LOPDAT: CALL	@PTRGET  ;READ THE VARIABLE LIST
;AND GET THE POINTER TO A VARIABLE INTO [D,E]
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;PUT THE VARIABLE LIST POINTER ONTO THE
;STACK AND TAKE THE
;DATA LIST POINTER OFF

; NOTE AT THIS POINT WE HAVE A VARIABLE WHICH WANTS DATA
; AND SO WE MUST GET DATA OR COMPLAIN

	PUSH	DX  ;SAVE THE POINTER TO THE VARIABLE WE
;ARE ABOUT TO SET UP WITH A VALUE
	MOV	AL,byte [BX]  ;SINCE THE DATA LIST POINTER ALWAYS POINTS
;AT A TERMINATOR LETS READ THE
;TERMINATOR INTO [A] AND SEE WHAT
;IT IS
	CMP	AL,((44) and 0FFh)
	JZ	@GWMAIN@_DATBK  ;A COMMA SO A VALUE MUST FOLLOW
	MOV	AL,byte [@FLGINP]  ;SEE WHAT TYPE OF STATEMENT THIS WAS
	OR	AL,AL
;SEARCH FOR ANOTHER DATA STATEMENT
	JZ	@GWMAIN@_@Q@QL078
	JMP	@GWMAIN@_DATLOP
@GWMAIN@_@Q@QL078:
@GWMAIN@_DATBK:
	DB	13  ; SKIP  ;SET A NON-ZERO
@GWMAIN@_SCNVAL: XOR	AL,AL  ;SET ZERO FLAG IN [A]
	MOV	byte [@INPPAS],AL  ;STORE SO EARLY RETURN CHECK WORKS
; EXTRN	ISFLIO:NEAR
	CALL	@ISFLIO  ;SEE IF A FILE READ
	JZ	@GWMAIN@_@Q@QL079
	JMP	@FILIND  ;IF SO, SPECIAL HANDLING
@GWMAIN@_@Q@QL079:
	CALL	@GETYPR  ;IS IT A STRING?
	PUSH	AX  ;SAVE THE TYPE INFORMATION
	JNZ	@GWMAIN@_NUMINS  ;IF NUMERIC, USE FIN TO GET IT
;ONLY THE VARAIBLE TYPE IS
;CHECKED SO AN UNQUOTED STRING
;CAN BE ALL DIGITS
	CALL	@CHRGTR
	MOV	DH,AL  ;ASSUME QUOTED STRING
	MOV	CH,AL  ;SETUP TERMINATORS
	CMP	AL,((34) and 0FFh)  ;QUOTE ?
	JZ	@GWMAIN@_NOWGET  ;TERMINATORS OK
	MOV	AL,byte [@FLGINP]  ;INPUT SHOULDN'T TERMINATE ON ":"
	OR	AL,AL  ;SEE IF READ OR INPUT
	MOV	DH,AL  ;SET D TO ZERO FOR INPUT
	JZ	@GWMAIN@_NCOLST
	MOV	DH,((":") and 0FFh)  ;UNQUOTED STRING TERMINATORS
@GWMAIN@_NCOLST: MOV	CH,((44) and 0FFh)  ;ARE COLON AND COMMA
;NOTE: ANSI USES [B]=44 AS A FLAG TO
;TRIGGER TRAILING SPACE SUPPRESSION
	DEC	BX  ;BACKUP SINCE START CHARACTER MUST BE INCLUDED
;IN THE QUOTED STRING CASE WE DON'T WANT TO
;INCLUDE THE STARTING OR ENDING QUOTE
@GWMAIN@_NOWGET: CALL	@STRLT2  ;MAKE A STRING DESCRIPTOR FOR THE VALUE
;AND COPY IF NECESSARY
; PUBLIC	DOASIG
@DOASIG: POP	AX  ;POP OFF THE TYPE INFORMATION
	ADD	AL,((3) and 0FFh)  ;MAKE VALTYPE CORRECT
	MOV	CL,AL  ;SAVE VALUE TYPE IN [C]
	MOV	AL,byte [@INPPAS]  ;SEE IF SCANNING VALUES FOR PASS1
	OR	AL,AL  ;ZERO FOR PASS1
	JNZ	$+3
	RET  ;GO BACK TO PASS1
	MOV	AL,CL  ;RECOVER VALTYP
	XCHG	BX,DX  ;[D,E]=TEXT POINTER
	MOV	BX,@GWMAIN@_STRDN2  ;RETURN LOC
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;[H,L]=PLACE TO STORE VARIABLE VALUE
	PUSH	DX  ;TEXT POINTER GOES ON
	JMP	@GWMAIN@_INPCOM  ;DO ASSIGNMENT
@GWMAIN@_NUMINS: CALL	@CHRGTR
	POP	AX  ;GET BACK VALTYPE OF SOURCE
	PUSH	AX  ;SAVE BACK
	CMP	AL,((5) and 0FFh)  ;REGEN CC'S
	MOV	CX,@DOASIG  ;ASSIGNMENT IS COMPLICATED
;EVEN FOR NUMERICS SO USE THE "LET" CODE
	PUSH	CX  ;SAVE ON STACK
	JAE	@GWMAIN@_@Q@QL080
	JMP	@FIN  ;IF NOT DOUBLE, CALL USUAL # INPUTTER
@GWMAIN@_@Q@QL080:
	JMP	@FINDBL  ;ELSE CALL SPECIAL ROUTINE WHICH EXPECTS DOUBLES
@GWMAIN@_STRDN2:
	DEC	BX
	CALL	@CHRGTR
	JZ	@GWMAIN@_TRMOK
	CMP	AL,((44) and 0FFh)
	JZ	@GWMAIN@_@Q@QL081
	JMP	@GWMAIN@_TRMNOK  ;ENDED PROPERLY?
@GWMAIN@_@Q@QL081:
@GWMAIN@_TRMOK:
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI
	DEC	BX  ;LOOK AT TERMINATOR
	CALL	@CHRGTR  ;AND SET UP CONDITION CODES
	JZ	@GWMAIN@_@Q@QL082
	JMP	@GWMAIN@_LOPDT2  ;NOT ENDING, CHECK FOR COMMA
@GWMAIN@_@Q@QL082:
;AND GET ANOTHER VARIABLE
;TO FILL WITH DATA

	POP	DX  ;POP OFF THE POINTER INTO DATA
	MOV	AL,byte [@FLGINP]  ;FETCH THE STATEMENT TYPE FLAG
	OR	AL,AL  ;IF ZERO, INPUT STATEMENT
	XCHG	BX,DX
	JZ	@GWMAIN@_@Q@QL083
	JMP	@RESFIN  ;UPDATE DATPTR
@GWMAIN@_@Q@QL083:
	PUSH	DX  ;SAVE THE TEXT POINTER
@GWMAIN@_FINPRG: POP	BX  ;GET BACK THE TEXT POINTER
	JMP	@FINPRT

; THE SEARCH FOR DATA STATMENTS IS MADE BY USING THE EXECUTION CODE
; FOR DATA TO SKIP OVER STATEMENTS. THE START WORD OF EACH STATEMENT
; IS COMPARED WITH $DATA. EACH NEW LINE NUMBER
; IS STORED IN DATLIN SO THAT IF AN ERROR OCCURS WHILE READING
; DATA THE ERROR MESSAGE WILL GIVE THE LINE NUMBER OF THE
; ILL-FORMATTED DATA

@GWMAIN@_DATLOP: CALL	@DATA
@GWMAIN@_DATFND: OR	AL,AL
	JNZ	@GWMAIN@_NOWLIN
	INC	BX
	MOV	AL,byte [BX]
	INC	BX
	OR	AL,byte [BX]  ;IFE XERPAG
	MOV	DL,((@ERROD) and 0FFh)  ;NO DATA IS ERROR ERROD
	JNZ	@GWMAIN@_@Q@QL084
	JMP	@ERROR  ;IF SO COMPLAIN
@GWMAIN@_@Q@QL084:
	INC	BX  ;SKIP PAST LINE #
	MOV	DX,[BX]  ;GET DATA LINE #
	INC	BX
	MOV	[@DATLIN],DX  ;SAVE DATA LINE NUMBER
@GWMAIN@_NOWLIN: CALL	@CHRGTR  ;GET THE STATEMENT TYPE
	CMP	AL,((@@SDATA) and 0FFh)  ;IS IS "DATA"?
	JNZ	@GWMAIN@_DATLOP  ;NOT DATA SO LOOK SOME MORE
	JMP	@GWMAIN@_DATBK  ;CONTINUE READING

; SUBTTL PEEK AND POKE

; NOTE: IN THE 8K PEEK ONLY ACCEPTS POSITIVE NUMBERS UP TO 32767
; POKE WILL ONLY TAKE AN ADDRESS UP TO 32767 , NO
; FUDGING ALLOWED. THE VALUE IS UNSIGNED.
; IN THE EXTENDED VERSION NEGATIVE NUMBERS CAN BE
; USED TO REFER TO LOCATIONS HIGHER THAN 32767.
; THE CORRESPONDENCE IS GIVEN BY SUBTRACTING 65536 FROM LOCATIONS
; HIGHER THAN 32767 OR BY SPECIFYING A POSITIVE NUMBER UP TO 65535.

@PEEK:	CALL	@FRQINT  ;GET AN INTEGER IN [H,L]
; EXTRN	PRODIR:NEAR
	CALL	@PRODIR  ;DONT ALLOW DIRECT IF PROTECTED FILE
; EXTRN	PEKFLT:NEAR
	@INS86	6  ;PUSH   ES
	@INS86	216,6,@SAVSEG  ;MOV    ES,SAVSEG
	CALL	@PEKFLT  ;Filter the PEEK
	JNZ	@GWMAIN@_@Q@QL085
	JMP	@GWMAIN@_PEKVAL  ;Filter returned the appropriate value
@GWMAIN@_@Q@QL085:
	@INS86	46  ;$ES
	MOV	AL,byte [BX]  ;Fetch the PEEK value
@GWMAIN@_PEKVAL: @INS86	7  ;POP    ES
	JMP	@SNGFLT  ;AND FLOAT IT
@POKE:	CALL	@FRMQNT  ;READ INTEGER FORMULA INTO [D,E]
	PUSH	DX  ;SAVE VALUE FOR LATER
	CALL	@PRODIR  ;DONT ALLOW DIRECT IF PROTECTED FILE
	CALL	@SYNCHR
	DB	44  ;CHECK FOR A COMMA
	CALL	@GETBYT
	POP	DX  ;GET THE ADDRESS BACK
	@INS86	6  ;PUSH ES
	@INS86	216,6,@SAVSEG  ;MOV  ES,SAVSEG
; EXTRN	POKFLT:NEAR
	CALL	@POKFLT  ;Filter POKEs for "special" addresses
	JNZ	@GWMAIN@_@Q@QL086
