	CMP	AL,((@@SGOTO) and 0FFh)  ;ERROR GOTO?
	JNZ	@GWMAIN@_SCNEX2  ;GET NEXT ONE
	CALL	@CHRGTR  ;GET NEXT CHAR
	CMP	AL,((@GWMAIN@_LINCON) and 0FFh)  ;LINE # CONSTANT?
	JNZ	@GWMAIN@_SCNEX2  ;NO, IGNORE.
	PUSH	DX  ;SAVE [D,E]
	CALL	@GWMAIN@_LINGT3  ;GET IT
	OR	DX,DX  ;IS IT LINE # ZERO?
	JNZ	@GWMAIN@_CHGPTR  ;CHANGE IT TO A POINTER
	JMP	@GWMAIN@_SCNEX3  ;YES, DONT CHANGE IT
@GWMAIN@_NTERRG: CMP	AL,((@GWMAIN@_LINCON) and 0FFh)  ;LINE # CONSTANT?
	JNZ	@SCNEXT  ;NOT, KEEP SCANNING
	PUSH	DX  ;SAVE CURRENT LINE # FOR POSSIBLE ERROR MSG
	CALL	@GWMAIN@_LINGT3  ;GET LINE # OF LINE CONSTANT INTO [D,E]
@GWMAIN@_CHGPTR:
	PUSH	BX  ;SAVE TEXT POINTER JUST AT END OF LINCON 3 BYTES
	CALL	@FNDLIN  ;TRY TO FIND LINE IN PGM.
	LAHF
	DEC	CX  ;POINT TO ZERO AT END OF PREVIOUS LINE
	SAHF
	MOV	AL,((@GWMAIN@_PTRCON) and 0FFh)  ;CHANGE LINE # TO PTR
	JB	@GWMAIN@_MAKPTR  ;IF LINE FOUND CHANGE # TO PTR
	CALL	@CRDONZ  ;PRINT CRLF IF REQUIRED
	MOV	BX,@GWMAIN@_LINM  ;PRINT "UNDEFINED LINE" MESSAGE
	PUSH	DX  ;SAVE LINE #
	CALL	@STROUT  ;PRINT IT
	POP	BX  ;GET LINE # IN [H,L]
	CALL	@LINPRT  ;PRINT IT
	POP	CX  ;GET TEXT PTR OFF STACK
	POP	BX  ;GET CURRENT LINE #
	PUSH	BX  ;SAVE BACK
	PUSH	CX  ;SAVE BACK TEXT PTR
	CALL	@INPRT  ;PRINT IT
@GWMAIN@_SCNPOP: POP	BX  ;POP OFF CURRENT TEXT POINTER
@GWMAIN@_SCNEX3: POP	DX  ;GET BACK CURRENT LINE #
	DEC	BX  ;BACKUP POINTER
@GWMAIN@_JSCNXT: JMP	@SCNEXT  ;KEEP SCANNING

@GWMAIN@_LINM:	DB "Undefined line "
	DB	0

@GWMAIN@_SCNPT2: CMP	AL,((@GWMAIN@_PTRCON) and 0FFh)  ;POINTER
