@GWMAIN@_CONCHG: MOV	BX,[@CONTXT]  ;GET TXT PTR AFTER CONSTANT IN [H,L]
@GWMAIN@_CONCH2: PUSH	BX  ;SAVE PTR TO END OF CONSTANT
