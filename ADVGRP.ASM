	DB	"L"+128  ;LEFT
	@ADR	@ADVGRP@_DRLEFT
	DB	"R"+128  ;RIGHT
	@ADR	@ADVGRP@_DRIGHT
	DB	"M"  ;MOVE
	@ADR	@ADVGRP@_DMOVE
	DB	"E"+128  ;-,-
	@ADR	@ADVGRP@_DRWEEE
	DB	"F"+128  ;+,-
	@ADR	@ADVGRP@_DRWFFF
	DB	"G"+128  ;+,+
	@ADR	@ADVGRP@_DRWGGG
	DB	"H"+128  ;-,+
	@ADR	@ADVGRP@_DRWHHH
	DB	"A"+128  ;ANGLE COMMAND
	@ADR	@ADVGRP@_DANGLE
	DB	"B"  ;MOVE WITHOUT PLOTTING
	@ADR	@ADVGRP@_DNOPLT
	DB	"N"  ;DON'T CHANGE CURRENT COORDS
	@ADR	@ADVGRP@_DNOMOV
	DB	"X"  ;EXECUTE STRING
	@ADR	@MCLXEQ
	DB	"C"+128  ;COLOR
	@ADR	@ADVGRP@_DCOLR
	DB	"S"+128  ;SCALE
	@ADR	@ADVGRP@_DSCALE
	DB	0  ;END OF TABLE

@ADVGRP@_DRUP:	@NEGDE  ;MOVE +0,-Y
@ADVGRP@_DRDOWN:  ;MOVE +0,+Y
	MOV	CX,0  ;DX=0
	JMP	@ADVGRP@_DOMOVR  ;TREAT AS RELATIVE MOVE

@ADVGRP@_DRLEFT:	@NEGDE  ;MOVE -X,+0
@ADVGRP@_DRIGHT:  ;MOVE +X,+0
	MOV	CX,DX  ;[BC]=VALUE
	MOV	DX,0  ;DY=0
	JMP	@ADVGRP@_DOMOVR  ;TREAT AS RELATIVE MOVE

@ADVGRP@_DRWHHH:	@NEGDE  ;MOVE -X,-Y
@ADVGRP@_DRWFFF:	MOV	CX,DX  ;MOVE +X,+Y
	JMP	@ADVGRP@_DOMOVR

@ADVGRP@_DRWEEE:	MOV	CX,DX  ;MOVE +X,-Y
@ADVGRP@_DRWHHC:	@NEGDE
	JMP	@ADVGRP@_DOMOVR

@ADVGRP@_DRWGGG:	@NEGDE  ;MOVE -X,+Y
	MOV	CX,DX
	JMP	@ADVGRP@_DRWHHC  ;MAKE DY POSITIVE & GO

@ADVGRP@_DMOVE:	CALL	@FETCHZ  ;GET NEXT CHAR AFTER COMMA
	MOV	CH,((0) and 0FFh)  ;ASSUME RELATIVE
	CMP	AL,(("+") and 0FFh)  ;IF "+" OR "-" THEN RELATIVE
	JZ	@ADVGRP@_MOVREL
	CMP	AL,(("-") and 0FFh)
	JZ	@ADVGRP@_MOVREL
	INC	CH  ;NON-Z TO FLAG ABSOLUTE
@ADVGRP@_MOVREL:	MOV	AL,CH
	PUSH	AX  ;SAVE ABS/REL FLAG ON STACK
	CALL	@DECFET  ;BACK UP SO VALSCN WILL SEE "-"
	CALL	@VALSCN  ;GET X VALUE
	PUSH	DX  ;SAVE IT
	CALL	@FETCHZ  ;NOW CHECK FOR COMMA
	CMP	AL,((44) and 0FFh)  ;COMMA?
	JZ	@ADVGRP@_@Q@QL018
	JMP	@FCERR
@ADVGRP@_@Q@QL018:
	CALL	@VALSCN  ;GET Y VALUE IN D
	POP	CX  ;GET BACK X VALUE

	POP	AX  ;GET ABS/REL FLAG
	OR	AL,AL
	JNZ	@ADVGRP@_DRWABS  ;NZ - ABSOLUTE

@ADVGRP@_DOMOVR:	CALL	@ADVGRP@_DSCLDE  ;ADJUST Y OFFSET BY SCALE
	PUSH	DX  ;SAVE Y OFFSET
	MOV	DX,CX  ;GET X INTO [DE]
	CALL	@ADVGRP@_DSCLDE  ;GO SCALE IT.
	XCHG	BX,DX  ;GET ADJUSTED X INTO [HL]
	POP	DX  ;GET ADJUSTED Y INTO [DE]
	XOR	AL,AL
	MOV	byte [@CSCLXY],AL
	MOV	AL,byte [@DRWANG]  ;GET ANGLE BYTE
	RCR	AL,1  ;LOW BIT TO CARRY
	JAE	@ADVGRP@_ANGEVN  ;ANGLE IS EVEN - DON'T SWAP X AND Y
	PUSH	AX  ;SAVE THIS BYTE
	PUSH	DX  ;SAVE DY
	PUSH	BX  ;SAVE DX
	CALL	@GTASPC  ;GO GET SCREEN ASPECT RATIO
;NOTE: TOSHIBA GTASPC routine does this logic(i.e. it sets CSCLXY if aspect
;                   ratio is greater than one).
	MOV	AL,BH
	OR	AL,AL  ;IS ASPECT RATIO GREATER THAN ONE?
	JZ	@ADVGRP@_ASPLS0  ;BRIF GOOD ASPECT RATIO
	MOV	AL,((1) and 0FFh)
	MOV	byte [@CSCLXY],AL
	XCHG	BX,DX
@ADVGRP@_ASPLS0:
	MOV	CL,BL  ;GET ASPECT RATIO INTO [C] FOR GOSCAL
	POP	BX  ;GET BACK DX
	MOV	AL,byte [@CSCLXY]
	OR	AL,AL
	JZ	@ADVGRP@_ASPLS1  ;branch if aspect ratio less 1.0
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;[HL]=DY, save DX
@ADVGRP@_ASPLS1:
	XCHG	BX,DX  ;1/ASPECT TO [HL]
	PUSH	BX  ;SAVE 1/ASPECT
	CALL	@ADVGRP@_GOSCAL  ;SCALE DELTA X BY ASPECT RATIO
	POP	CX  ;GET BACK 1/ASPECT RATIO
	POP	BX  ;GET DY
	PUSH	DX  ;SAVE SCALED DX
	XCHG	BX,DX  ;DY TO [DE] FOR GOSCAL
	MOV	BX,0
@ADVGRP@_DMULP:	ADD	BX,DX  ;MULTIPLY [DE] BY HI BYTE OF 1/ASPECT
	DEC	CH
	JNZ	@ADVGRP@_DMULP
	PUSH	BX  ;SAVE PARTIAL RESULT
	CALL	@ADVGRP@_GOSCAL  ;MULTIPLY [DE] BY LOW BYTE
	POP	BX  ;GET BACK PARTIAL RESULT
	ADD	BX,DX  ;[HL]=Y * 1/ASPECT
	POP	DX  ;GET BACK SCALED Y
	MOV	AL,byte [@CSCLXY]
	OR	AL,AL
	JZ	@ADVGRP@_ASLSS1  ;branch if aspect ratio less than 1
	XCHG	BX,DX
@ADVGRP@_ASLSS1:
	@NEGDE  ;ALWAYS NEGATE NEW DY
	POP	AX  ;GET BACK SHIFTED ANGLE
@ADVGRP@_ANGEVN:	RCR	AL,1  ;TEST SECOND BIT
	JAE	@ADVGRP@_ANGPOS  ;DON'T NEGATE COORDS IF NOT SET
	@NEGHL
	@NEGDE  ;NEGATE BOTH DELTAS
@ADVGRP@_ANGPOS:	CALL	@ADVGRP@_GTABSC  ;GO CALC TRUE COORDINATES

@ADVGRP@_DRWABS:	MOV	AL,byte [@DRWFLG]  ;SEE WHETHER WE PLOT OR NOT
	ADD	AL,AL  ;CHECK HI BIT
	JB	@ADVGRP@_DSTPOS  ;JUST SET POSITION.
	PUSH	AX  ;SAVE THIS FLAG
	PUSH	CX  ;SAVE X,Y COORDS
	PUSH	DX  ;BEFORE SCALE SO REFLECT DISTANCE OFF
	CALL	@SCALXY  ;SCALE IN CASE COORDS OFF SCREEN
	CALL	@ADVGRP@_CLINE2
	POP	DX
	POP	CX  ;GET THEM BACK
	POP	AX  ;GET BACK FLAG
@ADVGRP@_DSTPOS:	ADD	AL,AL  ;SEE WHETHER TO STORE COORDS
	JB	@ADVGRP@_DNSTOR  ;DON'T UPDATE IF B6=1
	MOV	[@GRPACY],DX  ;UPDATE GRAPHICS AC
	MOV	BX,CX
	MOV	[@GRPACX],BX
@ADVGRP@_DNSTOR:	XOR	AL,AL  ;CLEAR SPECIAL FUNCTION FLAGS
	MOV	byte [@DRWFLG],AL
	RET

@ADVGRP@_DNOMOV:	MOV	AL,((64) and 0FFh)  ;SET BIT SIX IN FLAG BYTE
	JMP	@ADVGRP@_DSTFLG

@ADVGRP@_DNOPLT:	MOV	AL,((128) and 0FFh)  ;SET BIT 7
@ADVGRP@_DSTFLG:	MOV	BX,@DRWFLG
	OR	AL,byte [BX]
	MOV	byte [BX],AL  ;STORE UPDATED BYTE
	RET

@ADVGRP@_DANGLE:	JAE	@ADVGRP@_NCFCER  ;ERROR IF NO ARG
	MOV	AL,DL  ;MAKE SURE LESS THAN 4
	CMP	AL,((4) and 0FFh)
	JAE	@ADVGRP@_NCFCER  ;ERROR IF NOT
	MOV	byte [@DRWANG],AL
	RET

@ADVGRP@_NCFCER:
@ADVGRP@_DSCALE:	JNAE	@ADVGRP@_@Q@QL019
	JMP	@FCERR  ;FC ERROR IF NO ARG
@ADVGRP@_@Q@QL019:
	MOV	AL,DH  ;MAKE SURE LESS THAN 256
	OR	AL,AL
	JZ	@ADVGRP@_@Q@QL020
	JMP	@FCERR
@ADVGRP@_@Q@QL020:
	MOV	AL,DL
	MOV	byte [@DRWSCL],AL  ;STORE SCALE FACTOR
	RET

@ADVGRP@_DSCLDE:	MOV	AL,byte [@DRWSCL]  ;GET SCALE FACTOR
	OR	AL,AL  ;ZERO MEANS NO SCALING
	JNZ	$+3
	RET
	MOV	BX,0
@ADVGRP@_DSCLP:	ADD	BX,DX  ;ADD IN [DE] SCALE TIMES
	DEC	AL
	JNZ	@ADVGRP@_DSCLP
	XCHG	BX,DX  ;PUT IT BACK IN [DE]
	MOV	AL,DH  ;SEE IF VALUE IS NEGATIVE
	ADD	AL,AL
	PUSHF  ;SAVE RESULTS OF TEST
	JAE	@ADVGRP@_DSCPOS
	DEC	DX  ;MAKE IT TRUNCATE DOWN
@ADVGRP@_DSCPOS:	@HLFDE  ;DIVIDE BY FOUR
	@HLFDE
	POPF  ;SEE IF WAS NEGATIVE
	JNAE	$+3
	RET  ;ALL DONE IF WAS POSITIVE
	MOV	AL,DH  ;OR IN HIGH 2 BITS TO MAKE NEGATIVE
	OR	AL,((192) and 0FFh)
	MOV	DH,AL
	INC	DX  ;ADJUST SO TRUNCATING TO LOWER VALUE
	RET

@ADVGRP@_GOSCAL:	MOV	AL,DH  ;SEE IF NEGATIVE
	ADD	AL,AL
	JAE	@ADVGRP@_GOSC2  ;NO, MULTIPLY AS-IS
	MOV	BX,@NEGD  ;NEGATE BEFORE RETURNING
	PUSH	BX
	@NEGDE  ;MAKE POSITIVE FOR MULTIPLY
@ADVGRP@_GOSC2:	MOV	AL,CL  ;GET SCALE FACTOR
	JMP	@ADVGRP@_SCALE2  ;DO THE SCALE

@ADVGRP@_DCOLR:	JAE	@ADVGRP@_NCFCER  ;FC ERROR IF NO ARG
	MOV	AL,DL  ;GO SET ATTRIBUTE
	CALL	@SETATR
	JAE	@ADVGRP@_@Q@QL021
	JMP	@FCERR  ;ERROR IF ILLEGAL ATTRIBUTE
@ADVGRP@_@Q@QL021:
	MOV	byte [@ATRBYT],AL  ;Save as default
	RET

@ADVGRP@_CHKRNG:	PUSH	BX  ;SAVE TXTPTR
	CALL	@SCALXY
	JNAE	@ADVGRP@_@Q@QL022
	JMP	@FCERR  ;OUT OF BOUNDS - ERROR
@ADVGRP@_@Q@QL022:
@ADVGRP@_CHKPHR:	POP	BX  ;REGET TXTPTR
	RET

end if

