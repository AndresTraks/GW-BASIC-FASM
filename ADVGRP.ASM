@PAINT:  ;GET (X,Y) OF START
	CALL	@ADVGRP@_INTQUE  ;INIT QUE
	CALL	@SCAN1
	PUSH	CX  ;SAVE COORDS OF START
	PUSH	DX
	CALL	@ATRSCN  ;SET FILL ATTRIBUTE AS CURRENT
	MOV	AL,byte [@ATRBYT]  ;DEFAULT BORDER COLOR IS SAME AS FILL
	MOV	DL,AL  ;DEFAULT ATTRIBUTE TO [E] LIKE GETBYT
	DEC	BX
	CALL	@CHRGTR
	JZ	@ADVGRP@_GOTBRD  ;NOTHING THERE - USE DEFAULT
	CALL	@SYNCHR
	DB	44  ;MAKE SURE OF COMMA
	CALL	@GETBYT  ;GET BORDER COLOR ARGUMENT
@ADVGRP@_GOTBRD:	MOV	AL,DL  ;BORDER ATTRIBUTE TO A
	CALL	@PNTINI  ;INIT PAINT STUFF & CHECK BORDER ATTRIB
	JAE	@ADVGRP@_@Q@QL000
	JMP	@FCERR
@ADVGRP@_@Q@QL000:

	POP	DX  ;GET BACK START COORDS
	POP	CX
	PUSH	BX  ;SAVE TXTPTR UNTIL DONE
	CALL	@ADVGRP@_CHKRNG  ;MAKE SURE POINT IS ON SCREEN
	CALL	@MAPXYC

	MOV	DX,1  ;ENTRY COUNT IS ONE (SKIP NO BORDER)
	CALL	@ADVGRP@_SCANR1  ;SCAN RIGHT FROM INITIAL POSITION
	JZ	@ADVGRP@_POPTRT  ;STARTED ON BORDER - GET TXTPTR & QUIT
	PUSH	BX  ;SAVE NO. OF POINTED PAINTED TO RIGHT
	CALL	@ADVGRP@_SCANL1  ;NOW SCAN LEFT FROM INITIAL POS.
	POP	DX  ;GET RIGHT SCAN COUNT.
	ADD	BX,DX  ;ADD TO LEFT SCAN COUNT
	XCHG	BX,DX  ;COUNT TO [DE]

	MOV	AL,((64) and 0FFh)  ;MAKE ENTRY FOR GOING DOWN
	CALL	@ADVGRP@_ENTST1

	MOV	CH,((192) and 0FFh)  ;CAUSE PAINTING UP
	JMP	@ADVGRP@_STPAIN  ;START PAINTING UPWARD

@ADVGRP@_POPTRT:	POP	BX  ;GET BACK TEXTPTR
	RET

; MAIN PAINT LOOP

@ADVGRP@_PNTLOP:
	CALL	@ADVGRP@_CKCNTC  ;CHECK FOR CTRL-C ABORT
@ADVGRP@_PNTLP1:	CALL	@ADVGRP@_GETQ  ;GET ONE ENTRY FROM QUEUE
	MOV	AL,CL  ;NOW GO SET UP CURRENT LOCATION
	CALL	@STOREC
@ADVGRP@_STPAIN:	MOV	AL,CH  ;GET DIRECTION
	MOV	byte [@PDIREC],AL
	ADD	AL,AL  ;SEE WHETHER TO GO UP, DOWN, OR QUIT
	JZ	@ADVGRP@_POPTRT  ;IF ZERO, ALL DONE.
	PUSH	DX  ;SAVE SKPCNT IN CASE TUP&TDOWN DON'T
	JAE	@ADVGRP@_PDOWN  ;IF POSITIVE, GO DOWN FIRST
	CALL	@TUPC  ;MOVE UP BEFORE SCANNING
	JMP	@ADVGRP@_PDOWN2

@ADVGRP@_PDOWN:	CALL	@TDOWNC  ;SEE IF AT BOTTOM & MOVE DOWN IF NOT
@ADVGRP@_PDOWN2:	POP	DX  ;GET SKPCNT BACK
	JB	@ADVGRP@_PNTLP1  ;OFF SCREEN - GET NEXT ENTRY
@ADVGRP@_PNTLP2:  ;SCAN RIGHT & SKIP UP TO SKPCNT BORDER
	CALL	@ADVGRP@_SCANR1
	JNZ	@ADVGRP@_@Q@QL001
	JMP	@ADVGRP@_PNTLP1  ;IF NO POINTS PAINTED, GET NEXT ENTRY
@ADVGRP@_@Q@QL001:
	CALL	@ADVGRP@_SCANL1  ;NOW SCAN LEFT FROM START POINT
	MOV	DL,BL  ;[DE] = LEFT MOVCNT
	MOV	DH,BH
	OR	AL,AL  ;SEE IF LINE WAS ALREADY PAINTED
	JZ	@ADVGRP@_PNTLP3  ;IT WAS - DON'T MAKE OVERHANG ENTRY
	DEC	BX  ;IF LMVCNT.GT.1, NEED TO MAKE ENTRY
	DEC	BX  ;IN OPPOSITE DIRECTION FOR OVERHANG.
	MOV	AL,BH
	ADD	AL,AL  ;SEE IF [HL] WAS .GT. 1
	JB	@ADVGRP@_PNTLP3

	MOV	AL,byte [@PDIREC]
	NOT	AL
	LAHF  ; PUSH PSW
	XCHG	AL,AH
	PUSH	AX
	XCHG	AL,AH
	CALL	@FETCHC  ;GET CURRENT POINT ADDRESS
	MOV	CL,AL  ;C=CMASK
	POP	AX  ; POP PSW
	XCHG	AL,AH
	SAHF  ;GET BACK DIRECTION AND INDEX
	MOV	CH,AL
	CALL	@ADVGRP@_PUTQ
@ADVGRP@_PNTLP3:	MOV	BX,[@MOVCNT]  ;GET COUNT PAINTED DURING RIGHT SCAN
	ADD	BX,DX  ;ADD TO LEFT MOVCNT
	XCHG	BX,DX  ;ENTRY COUNT TO [DE]
	CALL	@ADVGRP@_ENTSLR  ;GO MAKE ENTRY.

	MOV	BX,[@CSAVEA]  ;SET CURRENT LOCATION BACK TO END
	MOV	AL,byte [@CSAVEM]  ;OF RIGHT SCAN.
	CALL	@STOREC

@ADVGRP@_PNTLP4:	MOV	BX,[@SKPCNT]  ;CALC SKPCNT - MOVCNT TO SEE IF
	MOV	DX,[@MOVCNT]  ;ANY MORE BORDER TO SKIP
	SUB	BX,DX
	JZ	@ADVGRP@_GOPLOP  ;NO MORE - END OF THIS SCAN
	JB	@ADVGRP@_PNTLP6  ;RIGHT OVERHANG - SEE IF ENTRY NEEDED

	XCHG	BX,DX  ;SKIP COUNT TO [DE] FOR SCANR
	CALL	@ADVGRP@_SCANR1  ;HERE IF NEED TO CONTINUE RIGHT SCAN
	JZ	@ADVGRP@_GOPLOP  ;NO MORE POINTS.
	OR	AL,AL  ;SEE IF LINE ALREADY PAINTED
	JZ	@ADVGRP@_PNTLP4  ;YES, DON'T ENTER ANYTHING
	XCHG	BX,DX  ;ENTRY COUNT TO [DE]
	MOV	BX,[@CSAVEA]  ;MAKE ENTRY AT LOCATION SAVED BY SCANR
	MOV	AL,byte [@CSAVEM]  ;SO WE CAN ENTER A POSITIVE SKPCNT
	MOV	CL,AL
	MOV	AL,byte [@PDIREC]
	MOV	CH,AL
	CALL	@ADVGRP@_ENTSTK  ;MAKE ENTRY
	JMP	@ADVGRP@_PNTLP4  ;CONTINUE UNTIL SKPCNT .LE. 0

@ADVGRP@_PNTLP6:	@NEGHL  ;MAKE NEW SKPCNT POSITIVE
	DEC	BX  ;IF SKPCNT-MOVCNT .LT. -1
	DEC	BX  ;THEN RIGHT OVERHANG ENTRY IS NEEDED.
	MOV	AL,BH  ;SEE IF POSITIVE.
	ADD	AL,AL
	JB	@ADVGRP@_GOPLOP  ;OVERHANG TOO SMALL FOR NEW ENTRY

@ADVGRP@_RTOVH0:	INC	BX  ;NOW MOVE LEFT TO BEGINNING OF SCAN
	PUSH	BX  ;SO WE CAN ENTER A POSITIVE SKPCNT
	XCHG	BX,DX
@ADVGRP@_RTOVH1:	CALL	@LEFTC  ;START IS -(SKPCNT-MOVCNT)-1 TO LEFT
	DEC	DX
	OR	DX,DX
	JNZ	@ADVGRP@_RTOVH1

@ADVGRP@_RTOVH2:	POP	DX  ;GET BACK ENTRY SKPCNT INTO [DE]
	MOV	AL,byte [@PDIREC]  ;MAKE ENTRY IN OPPOSITE DIRECTION
	NOT	AL
	CALL	@ADVGRP@_ENTST1  ;MAKE ENTRY
@ADVGRP@_GOPLOP:	JMP	@ADVGRP@_PNTLOP  ;GO PROCESS NEXT ENTRY

@ADVGRP@_ENTSLR:
	MOV	AL,byte [@LFPROG]  ;DON'T STACK IF SCANNED LINE
	MOV	CL,AL  ;WAS ALREADY PAINTED
	MOV	AL,byte [@RTPROG]
	OR	AL,CL
	JNZ	$+3
	RET  ;Z IF SCAN LINE ALREADY PAINTED

@ADVGRP@_ENTST0:	MOV	AL,byte [@PDIREC]
@ADVGRP@_ENTST1:	MOV	CH,AL  ;DIRECTION IN [B]
	CALL	@FETCHC  ;LOAD REGS WITH CURRENT "C"
	MOV	CL,AL  ;BIT MASK IN [C]
@ADVGRP@_ENTSTK:
@ADVGRP@_ENTST9:	JMP	@ADVGRP@_PUTQ

@ADVGRP@_SCANR1:	CALL	@SCANR  ;PERFORM LOW LEVEL RIGHT SCAN
	MOV	[@SKPCNT],DX  ;SAVE UPDATED SKPCNT
	MOV	[@MOVCNT],BX  ;SAVE MOVCNT
	OR	BX,BX  ;SET CC'S ON MOVCNT
	MOV	AL,CL  ;GET ALREADY-PAINTED FLAG FROM [C]
	MOV	byte [@RTPROG],AL
	RET

@ADVGRP@_SCANL1:	CALL	@FETCHC  ;GET CURRENT LOCATION
	PUSH	BX  ;AND SWAP WITH CSV
	PUSH	AX
	MOV	BX,[@CSAVEA]
	MOV	AL,byte [@CSAVEM]
	CALL	@STOREC  ;REPOS AT BEGINNING OF SCAN
	POP	AX  ;REGET PLACE WHERE RT SCN STOPPED
	POP	BX
	MOV	[@CSAVEA],BX  ;AND SAVE IT IN TEMP LOCATION
	MOV	byte [@CSAVEM],AL
	CALL	@SCANL  ;NOW DO LOW LEVEL LEFT SCAN
	MOV	AL,CL  ;GET ALREADY-PAINTED FLAG FROM [C]
	MOV	byte [@LFPROG],AL  ;WHETHER IT WAS ALREADY PAINTED
	RET

;ROUTINE FOR INITIALISING QUEUE PARAMS
;QUELEN:CONTAINS QUEUE LENGTH
;PSNLEN:CONTAINS PRESENT QUEUE LENGTH
;QUEINP:        QUEINPUT POINTER
;QUEOUT:        QUEOUTPUT POINTER
@ADVGRP@_INTQUE:	PUSH	BX
end if
; EXTRN	STREND:WORD
if @GW_PASS = 1
	MOV	BX,[@STREND]  ;GET BEGINNING OF FREE SPACE
	XCHG	BX,DX
	PUSH	DX
end if
; EXTRN	FRETOP:WORD
if @GW_PASS = 1
	MOV	BX,[@FRETOP]  ;GET END OF FREE SPACE
	SUB	BX,DX  ;HL=FREE SPACE
	MOV	DX,1000
	CMP	BX,DX  ;IS IT LESSTHAN  1000 BYTES
	JNAE	@ADVGRP@_@Q@QL002
	JMP	@ADVGRP@_INTQU2
@ADVGRP@_@Q@QL002:
; EXTRN	GARBA2:NEAR
	CALL	@GARBA2  ;CALL GARBAGE COLLECTION
@ADVGRP@_INTQU2:	POP	DX  ;GET BACK FREE START

	MOV	BX,[@FRETOP]

	SUB	BX,DX
	MOV	DX,12
	CMP	BX,DX
	JAE	@ADVGRP@_@Q@QL003
; EXTRN	OMERR:NEAR
	JMP	@OMERR  ;IF LESS THAN 12 BYTES GIVE MEMORY OVERFLOW
@ADVGRP@_@Q@QL003:
	MOV	[@QUELEN],BX  ;SET LENGTH OF QUEUE
	MOV	BX,0
	MOV	[@PSNLEN],BX  ;SET PRESENT LENGTH
	MOV	BX,[@STREND]  ;HL=BEGINNING OF FREE SPACE
	MOV	[@QUEINP],BX
	MOV	[@QUEOUT],BX  ;INIT QUEUE POINTERS
	POP	BX  ;GET BACK CALLERS HL
	RET
@ADVGRP@_PUTQ:	PUSH	DX
	PUSH	BX
	MOV	BX,[@PSNLEN]  ;GET QUEUE      PRESENT LENGTH
	MOV	DX,6  ;IS ENOUGH SPACE LEFT OUT
	LAHF
	ADD	BX,DX
	RCR	SI,1
	SAHF
	RCL	SI,1
	MOV	[@PSNLEN],BX  ;UPDATE PRESENT LENGTH
	MOV	DX,[@QUELEN]
	CMP	BX,DX
	JNAE	@ADVGRP@_@Q@QL004
	JMP	@OMERR  ;IF THE PRESENT LENGTH IS EQUAL TO MAX OR GREATER THEN GIVE ERROR
@ADVGRP@_@Q@QL004:
	MOV	BX,[@QUEINP]
	CALL	@ADVGRP@_WRAP  ;CHECK FOR WRAP AROUND CASE
	POP	DX
	MOV	byte [BX],DL
	LAHF
	INC	BX
	SAHF
	MOV	byte [BX],DH
	LAHF
	INC	BX
	SAHF
	MOV	byte [BX],CL
	LAHF
	INC	BX
	SAHF
	MOV	byte [BX],CH
	LAHF
	INC	BX
	SAHF
	POP	DX
	MOV	byte [BX],DL
	LAHF
	INC	BX
	SAHF
	MOV	byte [BX],DH
	LAHF
	INC	BX
	SAHF
	MOV	[@QUEINP],BX
	RET
@ADVGRP@_GETQ:	MOV	BX,[@PSNLEN]
	MOV	AL,BH
	OR	AL,BL  ;ANY ENTRYS ON STACK
	MOV	CH,((0) and 0FFh)  ;FOR NO ENTRIES SET B TO ZERO
	JNZ	$+3
	RET
	MOV	DX,6  ;DECREMENT QUEUE LENGTH BY 6
	SUB	BX,DX
	MOV	[@PSNLEN],BX
	MOV	BX,[@QUEOUT]  ;HL=DEQUE POINTER
	CALL	@ADVGRP@_WRAP  ;CHECK FOR WRAP AROUND
	MOV	DL,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	DH,byte [BX]
	LAHF
	INC	BX
	SAHF
	PUSH	DX
	MOV	CL,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	CH,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	DL,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	DH,byte [BX]
	LAHF
	INC	BX
	SAHF
	MOV	[@QUEOUT],BX
	POP	BX
	RET
@ADVGRP@_WRAP:	PUSH	BX
	MOV	DX,6
	LAHF
	ADD	BX,DX
	RCR	SI,1
	SAHF
	RCL	SI,1
	MOV	DX,[@FRETOP]
	CMP	BX,DX  ;ARE WE GOING OUT OF QUEUE END
	POP	BX
	JNB	$+3
	RET  ;NO
	MOV	BX,[@STREND]  ;SET TO BEGINNING OF QUEUE
	RET

; SUBTTL CIRCLE - Draw a circle

;       CIRCLE - DRAW A CIRCLE

; SYNTAX: CIRCLE @(X,Y),RADIUS[,ATRB[,+/-STARTANG[,+/-ENDANG[,ASPECT]]]]

; EXTRN	GTASPC:NEAR
end if
; EXTRN	ASPECT:WORD,CSTCNT:WORD,CENCNT:WORD,CRCSUM:WORD,CPLOTF:WORD
; EXTRN	CLINEF:WORD
; EXTRN	CNPNTS:WORD,CPCNT:WORD,CPCNT8:WORD,VALTYP:WORD,CXOFF:WORD
; EXTRN	CYOFF:WORD,CSCLXY:WORD
if @GW_PASS = 1

; PUBLIC	CIRCLE
@CIRCLE:	CALL	@SCAN1  ;GET (X,Y) OF CENTER INTO GRPACX,Y
	CALL	@SYNCHR
	DB	44  ;EAT COMMA
	CALL	@GETIN2  ;GET THE RADIUS
	PUSH	BX  ;SAVE TXTPTR
	XCHG	BX,DX
	MOV	[@GXPOS],BX  ;SAVE HERE TILL START OF MAIN LOOP
	CALL	@ADVGRP@_MKINTC  ;PUT INTEGER INTO FAC
; EXTRN	FRCSNG:NEAR
	CALL	@FRCSNG  ;CONVERT TO SINGLE PRECISION
	@MOVRI	128,53,4,243  ;LOAD REGS WITH SQR(2)/2
; EXTRN	FMULT:NEAR
	CALL	@FMULT  ;DO FLOATING PT MULTIPLY
; EXTRN	FRCINT:NEAR
	CALL	@FRCINT  ;CONVERT TO INTEGER & GET INTO [HL]
	MOV	[@CNPNTS],BX  ;CNPNTS=RADIUS*SQR(2)/2=# PTS TO PLOT
	XOR	AL,AL  ;ZERO OUT CLINEF - NO LINES TO CENTER
	MOV	byte [@CLINEF],AL
	MOV	byte [@CSCLXY],AL  ;INITIALLY SCALING Y
	POP	BX  ;REGET TXTPTR
	CALL	@ATRSCN  ;SCAN POSSIBLE ATTRIBUTE
	MOV	CL,((1) and 0FFh)  ;SET LO BIT IN CLINEF FOR LINE TO CNTR
	MOV	DX,0  ;DEFAULT START COUNT = 0
	CALL	@ADVGRP@_CGTCNT
	PUSH	DX  ;SAVE COUNT FOR LATER COMPARISON
	MOV	CL,((128) and 0FFh)  ;SET HI BIT IN CLINEF FOR LINE TO CNTR
	MOV	DX,0-1  ;DEFAULT END COUNT = INFINITY
	CALL	@ADVGRP@_CGTCNT
	POP	SI  ;XTHL
	XCHG	SI,BX
	PUSH	SI  ;GET START COUNT, PUSH TXTPTR TILL DONE
	XOR	AL,AL
	XCHG	BX,DX  ;REVERSE REGS TO TEST FOR .LT.
	CMP	BX,DX  ;SEE IF END .GE. START
	MOV	AL,((0) and 0FFh)
	JAE	@ADVGRP@_CSTPLT  ;YES, PLOT POINTS BETWEEN STRT & END
	DEC	AL  ;PLOT POINTS ABOVE & BELOW
	XCHG	BX,DX  ;SWAP START AND END SO START .LT. END
	PUSH	AX  ;Swap sense of center line flags
	MOV	AL,byte [@CLINEF]
	MOV	CL,AL
	ROL	AL,1
	ROL	AL,1
	OR	AL,CL
	ROR	AL,1
	MOV	byte [@CLINEF],AL  ;Store swapped flags
	POP	AX
@ADVGRP@_CSTPLT:	MOV	byte [@CPLOTF],AL  ;SET UP PLOT POLARITY FLAG
	MOV	[@CSTCNT],DX  ;STORE START COUNT
	MOV	[@CENCNT],BX  ;AND END COUNT
	POP	BX  ;GET TXTPTR
	DEC	BX  ;NOW SEE IF LAST CHAR WAS A COMMA
	CALL	@CHRGTR
	JNZ	@ADVGRP@_CIRC1  ;SOMETHING THERE
	PUSH	BX  ;SAVE TXTPTR
	CALL	@GTASPC  ;GET DEFAULT ASPECT RATIO INTO [HL]
	MOV	AL,BH
	OR	AL,AL  ;IS ASPECT RATIO GREATER THAN ONE?
	JZ	@ADVGRP@_CIRC2  ;BRIF GOOD ASPECT RATIO
	MOV	AL,((1) and 0FFh)
	MOV	byte [@CSCLXY],AL
	XCHG	BX,DX  ;ASPECT RATIO IS GREATER THAN ONE, USE INVERSE
	JMP	@ADVGRP@_CIRC2  ;NOW GO CONVERT TO FRACTION OF 256

@ADVGRP@_CIRC1:	CALL	@SYNCHR
	DB	44  ;EAT COMMA
; EXTRN	FRMEVL:NEAR
	CALL	@FRMEVL
	PUSH	BX  ;SAVE TXTPTR
	CALL	@FRCSNG  ;MAKE IT FLOATING POINT
	CALL	@ADVGRP@_CMPONE  ;SEE IF GREATER THAN ONE
	JNZ	@ADVGRP@_CIRC11  ;LESS THAN ONE - SCALING Y
	INC	AL  ;MAKE [A] NZ
	MOV	byte [@CSCLXY],AL  ;FLAG SCALING X
	CALL	@FDIV  ;RATIO = 1/RATIO
;MAKE NUMBER FRACTION OF 256
end if
; EXTRN	FAC:WORD
if @GW_PASS = 1

@ADVGRP@_CIRC11:	MOV	BX,@FAC  ;BY MULTIPLYING BY 2^8 (256)
	MOV	AL,byte [BX]
	ADD	AL,((8) and 0FFh)  ;ADD 8 TO EXPONENT
	MOV	byte [BX],AL
	CALL	@FRCINT  ;MAKE IT AN INTEGER IN [HL]
@ADVGRP@_CIRC2:	MOV	[@ASPECT],BX  ;STORE ASPECT RATIO

;       CIRCLE ALGORITHM

;       [HL]=X=RADIUS * 2 (ONE BIT FRACTION FOR ROUNDING)
;       [DE]=Y=0
;       SUM =0
; LOOP: IF Y IS EVEN THEN
;             REFLECT((X+1)/2,(Y+1)/2) (I.E., PLOT POINTS)
;             IF X.LT.Y THEN EXIT
;       SUM=SUM+2*Y+1
;       Y=Y+1
;       IF SUM.GGWGRP.RNO
;             SUM=SUM-2*X+1
;             X=X-1
;       ENDIF
;       GOTO LOOP

	MOV	DX,0  ;INIT Y = 0
	MOV	[@CRCSUM],DX  ;SUM = 0
	MOV	BX,[@GXPOS]  ;X = RADIUS*2
	ADD	BX,BX

@ADVGRP@_CIRCLP:
	MOV	AL,DL  ;TEST EVENNESS OF Y
	RCR	AL,1  ;TO SEE IF WE NEED TO PLOT
	JB	@ADVGRP@_CRCLP2  ;Y IS ODD - DON'T TEST OR PLOT
	PUSH	DX  ;SAVE Y AND X
	PUSH	BX
	INC	BX  ;ACTUAL COORDS ARE (X+1)/2,(Y+1)/2
	@HLFHL  ;(PLUS ONE BEFORE DIVIDE TO ROUND UP)
	INC	DX
	@HLFDE
	CALL	@ADVGRP@_CPLOT8
	POP	DX  ;RESTORE X AND Y
	POP	BX  ;INTO [DE] AND [HL] (BACKWARDS FOR CMP)
	CMP	BX,DX  ;QUIT IF Y .GE. X
	JNAE	@ADVGRP@_@Q@QL005
	JMP	@ADVGRP@_POPTRT  ;GO POP TXTPTR AND QUIT
@ADVGRP@_@Q@QL005:
