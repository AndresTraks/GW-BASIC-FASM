	DEC	BX  ;ACTUALLY FUNCTIONS CAN GET HERE
;WITH BAD [H,L] BUT NOT SERIOUS
;SET CONDITION CODES ON TERMINATOR
	CALL	@CHRGTR
	MOV	AL,DL  ;RETURN THE RESULT IN [A] AND [E]
	RET

