@GWEVAL@_LPOPER:	PUSH	DX  ;SAVE PRECEDENCE
	MOV	CL,((1) and 0FFh)  ;EXTRA SPACE NEEDED FOR RETURN ADDRESS
	CALL	@GETSTK  ;MAKE SURE THERE IS ROOM FOR RECURSIVE CALLS
	CALL	@EVAL  ;EVALUATE SOMETHING
;RESET OVERFLOW PRINTING BACK TO NORMAL
	XOR	AL,AL  ;(SET TO 1 AT FUNDSP TO SUPPRESS
	MOV	byte [@FLGOVC],AL  ;MULTIPLE OVERFLOW MESSAGES)
; PUBLIC	TSTOP
@TSTOP:	MOV	[@TEMP2],BX  ;SAVE TEXT POINTER
@GWEVAL@_RETAOP:	MOV	BX,[@TEMP2]  ;RESTORE TEXT PTR
	POP	CX  ;POP OFF THE PRECEDENCE OF OLDOP
@GWEVAL@_NOTSTV:	MOV	AL,byte [BX]  ;GET NEXT CHARACTER
	MOV	[@TEMP3],BX  ;SAVE UPDATED CHARACTER POINTER
	CMP	AL,((@GREATK) and 0FFh)  ;IS IT AN OPERATOR?
	JNB	$+3
	RET  ;NO, ALL DONE (THIS CAN RESULT IN OPERATOR
;APPLICATION OR ACTUAL RETURN)
	CMP	AL,((@LESSTK+1) and 0FFh)  ;SOME KIND OF RELATIONAL?
	JB	@GWEVAL@_DORELS  ;YES, DO IT
	SUB	AL,((@PLUSTK) and 0FFh)  ;SUBTRACT OFFSET FOR FIRST ARITHMETIC
	MOV	DL,AL  ;MUST MULTIPLY BY 3 SINCE
;OPTAB ENTRIES ARE 3 LONG
	JNZ	@GWEVAL@_NTPLUS  ;NOT ADDITION OP
	MOV	AL,byte [@VALTYP]  ;SEE IF LEFT PART IS STRING
	CMP	AL,((3) and 0FFh)  ;SEE IF ITS A STRING
	MOV	AL,DL  ;REFETCH OP-VALUE
	JNZ	@GWEVAL@_@Q@QL000
	JMP	@CAT  ;MUST BE CAT
@GWEVAL@_@Q@QL000:
@GWEVAL@_NTPLUS:
	CMP	AL,((@LSTOPK) and 0FFh)  ;HIGHER THAN THE LAST OP?
	JNAE	$+3
	RET  ;YES, MUST BE TERMINATOR
	MOV	BX,@OPTAB  ;CREATE INDEX INTO OPTAB
	MOV	DH,((0) and 0FFh)  ;MAKE HIGH BYTE OF OFFSET=0
	ADD	BX,DX  ;ADD IN CALCULATED OFFSET
	MOV	AL,CH  ;[A] GETS OLD PRECEDENCE
	@INS86	56  ;CODE SEGMENT FETCH
	MOV	DH,byte [BX]  ;REMEMBER NEW PRECEDENCE
	CMP	AL,DH  ;OLD-NEW
	JNAE	$+3
	RET  ;MUST APPLY OLD OP
;IF HAS GREATER OR = PRECEDENCE
;NEW OPERATOR

	PUSH	CX  ;SAVE THE OLD PRECEDENCE
	MOV	CX,@GWEVAL@_RETAOP  ;PUT ON THE ADDRESS OF THE
	PUSH	CX  ;PLACE TO RETURN TO AFTER OPERATOR APPLICATION
	MOV	AL,DH  ;SEE IF THE OPERATOR IS EXPONENTIATION
	CMP	AL,((127) and 0FFh)  ;WHICH HAS PRECEDENCE 127
	JZ	@GWEVAL@_EXPSTK  ;IF SO, "FRCSNG" AND MAKE A SPECIAL STACK ENTRY
	CMP	AL,((81) and 0FFh)  ;SEE IF THE OPERATOR IS "AND" OR "OR"
	JB	@GWEVAL@_ANDORD  ;AND IF SO "FRCINT" AND
;MAKE A SPECIAL STACK ENTRY
	AND	AL,((254) and 0FFh)  ;MAKE 123 AND 122 BOTH MAP TO 122
	CMP	AL,((122) and 0FFh)  ;MAKE A SPECIAL CHECK FOR "MOD" AND "IDIV"
	JZ	@GWEVAL@_ANDORD  ;IF SO, COERCE ARGUMENTS TO INTEGER
; THIS CODE PUSHES THE CURRENT VALUE IN THE FAC
; ONTO THE STACK, EXCEPT IN THE CASE OF STRINGS IN WHICH IT CALLS
; TYPE MISMATCH ERROR. [D] AND [E] ARE PRESERVED.

@GWEVAL@_NUMREL:
	MOV	AL,byte [@VALTYP]  ;FIND OUT WHAT TYPE OF VALUE WE ARE SAVING
	SUB	AL,((3) and 0FFh)  ;SETUP THE CONDITION CODES
;SET ZERO FOR STRINGS
	JNZ	@GWEVAL@_@Q@QL001
	JMP	@TMERR
@GWEVAL@_@Q@QL001:
	@INS86	377,66,@FACLO  ;PUSH FACLO
	JNS	@GWEVAL@_@Q@QL002
	JMP	@GWEVAL@_VPUSHD  ;ALL DONE IF THE DATA WAS AN INTEGER
@GWEVAL@_@Q@QL002:
	@INS86	377,66,@FACLO+2  ;PUSH FAC-1,0 ON THE STACK
	JP	@GWEVAL@_@Q@QL003
	JMP	@GWEVAL@_VPUSHD  ;ALL DONE IF WE HAD A SNG
@GWEVAL@_@Q@QL003:
	@INS86	377,66,@DFACLO  ;PUSH ON LOW BYTES OF DP FAC
	@INS86	377,66,@DFACLO+2  ;PUSH ON NEXT TWO BYES OF DP FAC
@GWEVAL@_VPUSHD:
	ADD	AL,((3) and 0FFh)  ;FIX [A] TO BE THE VALTYP OF THE NUMBER
;JUST PUSHED ON THE STACK
	MOV	CL,DL  ;[C]=OPERATOR NUMBER
	MOV	CH,AL  ;[B]=TYPE OF VALUE ON THE STACK
	PUSH	CX  ;SAVE THESE THINGS FOR APPLOP
	MOV	CX,@GWEVAL@_APPLOP  ;GENERAL OPERATOR APPLICATION
;ROUTINE -- DOES TYPE CONVERSIONS
@GWEVAL@_FINTMP:	PUSH	CX  ;SAVE PLACE TO GO
	MOV	BX,[@TEMP3]  ;REGET THE TEXT POINTER
	JMP	@GWEVAL@_LPOPER
@GWEVAL@_DORELS:	MOV	DH,((0) and 0FFh)  ;ASSUME NO RELATION OPS
;ALSO SETUP THE HIGH ORDER OF THE INDEX INTO OPTAB
@GWEVAL@_LOPREL:	SUB	AL,((@GREATK) and 0FFh)  ;IS THIS ONE RELATION?
	JB	@GWEVAL@_FINREL  ;RELATIONS ALL THROUGH
	CMP	AL,((@NMREL) and 0FFh)  ;IS IT REALLY RELATIONAL?
	JAE	@GWEVAL@_FINREL  ;NO JUST BIG
	CMP	AL,((1) and 0FFh)  ;SET UP BITS BY MAPPING
	RCL	AL,1  ;0 TO 1 1 TO 2 AND 2 TO 4
	XOR	AL,DH  ;BRING IN THE OLD BITS
	CMP	AL,DH  ;MAKE SURE RESULT IS BIGGER
	MOV	DH,AL  ;SAVE THE MASK
	JAE	@GWEVAL@_@Q@QL004
	JMP	@SNERR  ;DON'T ALLOW TWO OF THE SAME
@GWEVAL@_@Q@QL004:
	MOV	[@TEMP3],BX  ;SAVE CHARACTER POINTER
	CALL	@CHRGTR  ;GET THE NEXT CANDIDATE
	JMP	@GWEVAL@_LOPREL

; FOR EXPONENTIATION WE WANT TO FORCE THE CURRENT VALUE IN THE FAC
