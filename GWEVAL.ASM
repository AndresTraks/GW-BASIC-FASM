@GETBYT:	CALL	@FRMEVL  ;EVALUATE A FORMULA
; PUBLIC	CONINT
@CONINT:	CALL	@INTFR2  ;CONVERT THE FAC TO AN INTEGER IN [D,E]
;AND SET THE CONDITION CODES BASED
;ON THE HIGH ORDER
	JZ	@GWEVAL@_@Q@QL048
	JMP	@FCERR  ;WASN'T ERROR
