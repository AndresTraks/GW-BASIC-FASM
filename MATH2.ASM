; SUBTTL	 $FIDIG  ADD TEXT DIGIT TO CURRENT ACCUMULATED NUMBER
;***************************************************************

;       $FIDIG  CONVERTS DIGIT POINTED TO BY (BX) TO BINARY
;               VALUE AND ADDS TO NUMBER ACCUMULATED. AT THE
;               APPROPRIATE TIMES CONVERSION WILL TAKE
;               PLACE TO THE NEXT HIERARCHY OF NUMBERS,I.E.
;               INTEGER-SINGLE PRECISION-DOUBLE PRECISION.
;       CALLING SEQUENCE:       CALL    $FIDIG
;               WITH (BX) POINTING TO NUMBER IN THE
;               TEXT BUFFER. NUMBER IS ACCUMULATED IN THE FAC.

;****************************************************************

;******************************************************************
;AS $FIDIG IS ENTERED CF=1 AND (DI) WILL HOLD PLACES TO THE RIGHT OF
;DECIMAL POINT (IF DECIMAL POINT HAS OCCURRED).(CX) WILL BE EITHER
;ALL BITS SET OR ALL BITS CLEARED. ALL BITS SET INDICATES A DECIMAL
;POINT HAS NOT BEEN SEEN YET AND (CX)=0 INDICATES D. P. SEEN
;******************************************************************
@MATH1@_@SFIDIG: ADC	DI,CX  ;(DI) INCREMENTED ONLY IF D.P. SEEN
	PUSH	BX  ;MUST NOW SAVE ALL NECESSARY REGS.
	PUSH	DI
	PUSH	CX
	SUB	AL,(("0") and 0FFh)  ;SUBTRACT OUT ASCII BIAS
	PUSH	AX  ;SAVE ON STACK
	CALL	@@SGETYP  ;SET CONDITION CODES
	POP	AX  ;RECALL DIGIT
	CBW  ;ZERO AH
	JNS	@MATH1@_FI05  ;MUST BE S.P. OR D.P. ALREADY
	MOV	BX,word [@@SFACLO]  ;FETCH THE INTEGER ALREADY ACCUM.
	CMP	BX,3277  ;IS IT ALREADY TOO BIG TO ADD
;ANOTHER DIGIT TO?
	JNB	@MATH1@_FFI10  ;IF SO GO MAKE S.P. FIRST
	MOV	CX,BX  ;SAVE ORIGINAL (BX)
	SHL	BX,1  ;(BX)=(BX)*2
	SHL	BX,1  ;(BX)=(BX)*4
	ADD	BX,CX  ;(BX)=(BX)*5
	SHL	BX,1  ;(BX)=(BX)*10
	ADD	BX,AX  ;ADD IN THE DIGIT
	JS	@MATH1@_FFI10  ;IF SF=1 WE HAVE 32768 OR 32769
	MOV	word [@@SFACLO],BX  ;STORE IN $FAC
	JMP	@MATH1@_FI50
@MATH1@_FI05:  ;TO GET HERE NUMBER WAS ALREADY S.P. OR D.P.
	PUSH	AX  ;SAVE THE NUMBER
	JB	@MATH1@_FFFI20  ;IT'S CURRENTLY SINGLE PRECISION
	JMP	@MATH1@_FI40  ;DOUBLE PRECISION
@MATH1@_FFI10:  ;TO GET HERE NUMBER WAS PREVIOUSLY AN INTEGER BUT HAS
;GROWN TOO LARGE - MUST MAKE IT SINGLE PRECISION
	PUSH	AX  ;SAVE THE NUMBER
	CALL	@@SCSI  ;CONVERT INTEGER TO S.P.
	JMP	@MATH1@_FI30  ;MUL BY 10 AND ADD IN DIGIT
@MATH1@_FFFI20:  ;TO GET HERE NUMBER WAS ALREADY SINGLE PRECISION
;MUST CHECK TO SEE IF ACCURACY MIGHT BE LOST IF WE
;MULTIPLY OUR FAC BY 10,I.E. FAC MUST BE SMALLER
;THAN 1000000.
	MOV	word [@@SDBUFF+4],9216
	MOV	word [@@SDBUFF+6],38004
	MOV	BX,@@SDBUFF+6
	CALL	@MATH1@_@SCOMPM  ;COMPARE TO $FAC
	JNS	@MATH1@_FI35  ;GO DO D.P. IF TOO LARGE FOR S.P.
@MATH1@_FI30:	CALL	@MATH1@_@SMUL10  ;MULTIPLY $FAC BY 10
	POP	DX  ;RECALL DIGIT
	PUSH	word [@@SFACLO]
	PUSH	word [@@SFAC-1]  ;FAC PUSHED ON STACK
	CALL	@@SFLT  ;CONVERT INTEGER TO S.P.
	POP	BX  ;RECALL FAC
	POP	DX
	CALL	@@SFADDS  ;ADD IN THE NEW DIGIT
	JMP	@MATH1@_FI50  ;GET STACK RIGHT AND RETURN
@MATH1@_FI35:  ;TO GET HERE WE ALREADY HAVE 7 DIGITS AND WOULD
;HAVE A LOSS OF ACCURACY IF WE CONTINUED IN S.P. SO WE
;NEED TO CONVERT TO D.P. MULTIPLY BY 10 AND ADD IN THE DIG.
	CALL	@@SCDS  ;CONVERT THE SINGLE TO D.P.
@MATH1@_FI40:	CALL	@MATH1@_@SMUL10  ;MULTIPLY BY 10
	CALL	@MATH1@_@SMOVAF  ;MOVE $FAC TO $ARG
	POP	DX  ;RECALL DIGIT
	CALL	@@SFLT  ;CONVERT TO S.P.
	CALL	@@SCDS  ;CONVERT TO D.P.
	CALL	@MATH1@_@SFADDD  ;ADD IN THE OLD ACCUMULATED VALUE
@MATH1@_FI50:	POP	CX  ;GET DECIMAL POINT FLAG BACK
	POP	DI  ;GET NO. DIGITS TO RIGHT OF DECIMAL PT.
	POP	BX  ;GET TEXT POINTER BACK
	RET  ;COMPLETE

; SUBTTL	 $FINEX  EXPONENT INPUT ROUTINE
;*************************************************************

;       $FINEX  THE PURPOSE OF THIS ROUTINE IS TO DETERMINE
;               THE INPUT EXPONENT BASE 10 AND LEAVE IN (DX).
;               ADDITIONALLY IF A MINUS "-" SIGN IS ENCOUNTERED
;               $FINEX WILL SET ALL BITS OF (SI). OTHERWISE ALL
;               BITS OF (SI) WILL BE CLEARED.
;       CALLING SEQUENCE:       CALL    $FINEX
;               WITH THE SIGNIFICANT DIGITS OF THE NUMBER IN
;               THE FAC.

;***************************************************************

@MATH1@_@SFINEX: LAHF  ;SAVE STATUS
	CMP	byte [@@SVALTP],((8) and 0FFh)  ;SEE IF ALREADY D.P.
	JNZ	@MATH1@_EXA
	SAHF  ;GET STACK RIGHT
	JMP	@MATH1@_EXB
@MATH1@_EXA:	SAHF  ;RESTORE CODES
	PUSH	BX  ;SAVE IMPORTANT REGISTERS
	PUSH	DI  ;PRECISION ACCORDING TO ZF. IF
	CALL	@MATH1@_@SFINFC  ;ZF=1 S.P.:ZF=0 THEN D.P.
	POP	DI  ;RECALL DIGITS TO RIGHT OF D.P.
	POP	BX  ;RECALL TEXT POINTER
@MATH1@_EXB:	XOR	SI,SI  ;IN CASE EXPONENT IS POSITIVE
	MOV	DX,SI  ;WILL BUILD EXPONENT IN DX
	CALL	@MATH1@_@SCHRGT  ;GET FIRST CHARACTER OF EXPONENT
	JB	@MATH1@_FX20  ;NO SIGN SO DEFAULT POS.
	CMP	AL,(("-") and 0FFh)  ;NEGATIVE EXPONENT
	JNZ	@MATH1@_FX00  ;IF NOT MUST BE POSITIVE
	NOT	SI  ;NEGATIVE EXPONENT
	JMP	@MATH1@_FX10  ;GO GET NEXT CHARACTER
@MATH1@_FX00:	CMP	AL,(("+") and 0FFh)
	JZ	@MATH1@_FX10
;ILLEGAL CHARACTER MUST LEAVE
	RET  ;(BX) POINTING HERE
@MATH1@_FX10:	CALL	@MATH1@_@SCHRGT  ;GET NEXT CHARACTER
	JB	@MATH1@_FX20  ;IF DIGIT PROCESS AS EXPONENT
	RET  ;OTHERWISE RETURN
@MATH1@_FX20:	CMP	DX,3276  ;OVERFLOW IF THIS DOESN'T GET CF=1
	JB	@MATH1@_FX30  ;NO-USE THIS DIGIT
	MOV	DX,32767  ;TO ASSURE OVERFLOW
	JMP	@MATH1@_FX10
@MATH1@_FX30:	PUSH	AX  ;SAVE NEW DIGIT
	MOV	AX,10  ;MUST MULTIPLY DX BY 10
	MUL	DX  ;ANSWER NOW IN AX
	POP	DX  ;RECALL DIGIT TO DX
	SUB	DL,((48) and 0FFh)  ;SUBTRACT OUT ASCII BIAS
	XOR	DH,DH  ;TO BE SURE AX HAS CORRECT NO.
	ADD	DX,AX  ;ADD TO DX
	JMP	@MATH1@_FX10

; SUBTTL	 FINFC	 INPUT FORCE ROUTINES FOR "#","%","!"
;*********************************************************

;       FINFC   THIS MODULE CONTAINS THE ROUTINES $FINI,
;               $FIND, AND $FINS FOR FORCING THE INPUT TO
;               INTEGER, DOUBLE PRECISION OR SINGLE PRECISION
;               RESPECTIVELY IN RESPONSE TO AN INPUT "$","#", OR
;               "!". ADDITIONALLY THIS MODULE CONTAINS
;               THE UTILITY ROUTINES $FI,$FS,$FD,$CSI,$CSD,$CDS
;               FOR FORCING INTEGER,SINGLE,DOUBLE,CONVERTING
;               INTEGER TO SINGLE,CONVERTING DOUBLE TO SINGLE, AND
;               CONVERTING SINGLE TO DOUBLE, RESPECTIVELY
;       CALLING SEQUENCE:       CALL    $FINI
;               OR              CALL    $FIND
;               OR              CALL    $FINS
;               OR              CALL    $FS
;               OR              CALL    $FD
;               OR              CALL    $FI
;               OR              CALL    $CSI
;               OR              CALL    $CSD
;               OR              CALL    $CDS
;               WITH THE FAC CONTAINING THE CURRENT ACCUMULATED
;               NUMBER.

;***********************************************************

@MATH1@_@SFIND:  ;FORCE INPUT TO DOUBLE PRECISION
	OR	AL,((1) and 0FFh)  ;TO SIGNAL DOUBLE PRECISION
@MATH1@_@SFINS:  ;FORCE INPUT TO SINGLE PRECISION (caller has set Z flag)
	PUSH	BX  ;SAVE TEXT POINTER
	PUSH	DI  ;SAVE NO DIGITS AFTER DECIMAL POINT
	JNZ	@MATH1@_FC10  ;Force to double for $FIND callers.
	CALL	@@SFS  ;Force to single for $FINS callers.
	JMP	@MATH1@_FC20  ;Skip over $FD call.

@MATH1@_FC10:	CALL	@MATH1@_@SFD  ;FORCE FAC TO DOUBLE PREC.
@MATH1@_FC20:	POP	DI  ;RECALL NO DIGITS TO RT. OF DEC PT
	POP	BX  ;RECALL TEXT POINTER
	XOR	SI,SI  ;SINCE THIS IS A FORCED
	MOV	DX,SI  ;NO. EXPONENT IS ZERO
	CALL	@MATH1@_@SFINE  ;DO IMPLIED EXPONENT FIX-UP
@MATH1@_FC30:	INC	BX  ;Point past the force character and
	RET  ;return.

@MATH1@_@SFINI:	CALL	@@SGETYP  ;SET COND CODES ACCORDING TO TYPE
	JS	@MATH1@_FC30
	JMP	@@SSNERR  ;CAN'T MAKE INTEGER IF NOT ALREADY
@MATH1@_@SFINFC: JZ	@MATH1@_@SFD  ;IF ZF=1 THEN DOUBLE PRECISION
@FRCSNG:
@@SFS:  ;FORCE SINGLE PRECISION
	CALL	@@SGETYP  ;SET COND CODES ACC. TO TYPE
	JPO	@MATH1@_FC200  ;IF ALREADY S.P. RETURN
	JNZ	@MATH1@_FS10
	JMP	@@STMERR  ;CAN'T FORCE A STRING
@MATH1@_FS10:
	JNS	@@SCSD  ;IF NOT INTEGER FORCE DOUBLE TO S.P.
	CALL	@@SCSI  ;FORCE INTEGER TO SINGLE
	JMP	@MATH1@_FC200
@@SCSD:  ;CONVERT DOUBLE TO SINGLE PRECISION
	MOV	AL,((4) and 0FFh)  ;SINGLE PREC DESIGNATION
	MOV	byte [@@SVALTP],AL
	MOV	BL,byte [@@SFAC-1]  ;FETCH HIGH MANTISSA BITS
	MOV	byte [@@SFAC+1],BL  ;MOVE SIGN TO $FAC+1
	MOV	DX,word [@@SFAC-3]  ;FETCH REST OF MANTISSA
	MOV	AH,byte [@@SFAC-4]  ;FETCH OVERFLOW BITS
	OR	AH,((64) and 0FFh)  ;WANT ROUND-UP IF HIGH BIT SET
	OR	BL,((128) and 0FFh)  ;PUT IN UNDERSTOOD 1
	JMP	@MATH1@_@SROUNM  ;GO ROUND THE NUMBER
@FRCDBL:
@MATH1@_@SFD:  ;FORCE TO DOUBLE PRECISION
	CALL	@@SGETYP  ;DETERMINE CURRENT TYPE
	JNB	@MATH1@_FC200  ;IF ALREADY DOUBLE EXIT
	JNZ	@MATH1@_FD10

	JMP	@@STMERR
@MATH1@_FD10:
	JNS	@@SCDS  ;IF NOT INTEGER PROCEED
	CALL	@@SCSI  ;CONVERT INTEGER TO SINGLE PREC.
@@SCDS:	MOV	AL,((8) and 0FFh)  ;DOUBLE PREC. INDICATOR
	MOV	byte [@@SVALTP],AL  ;SET TYPE TO D.P.
	XOR	AX,AX  ;MUST ZERO OVERFLOW BYTES
	MOV	word [@@SDFACL],AX
	MOV	word [@@SDFACL+2],AX
	RET
@@SCSI:	PUSH	DX  ;SAVE (DX)
	PUSH	SI  ;SAVE (SI)
	MOV	DX,word [@@SFACLO]  ;FETCH THE INTEGER
	CALL	@@SFLT  ;FLOAT THE INTEGER AND STORE IN FAC
	POP	SI  ;GET REGISTERS RIGHT
	POP	DX
@MATH1@_FC200:	RET
@FRCINT:
@@SFI:  ;FORCE INTEGER
	CALL	@@SGETYP  ;SEE WHAT WE'RE IN FOR
	JNS	@MATH1@_FI10  ;IF NOT INTEGER ALREADY - JUMP
	MOV	BX,word [@@SFACLO]
	RET
@MATH1@_FI10:
	JNZ	@MATH1@_FFI20
	JMP	@@STMERR  ;IF STRING - ERROR
@MATH1@_FFI20:
@MATH1@_@SCINC:  ;Single precision, operand in FAC
@MATH1@_@SCIND:  ;Double precision uses same routine
	PUSH	AX
	PUSH	CX
	MOV	AX,word [@@SFACM1]  ;Get exponent
	MOV	CX,word [@@SFACLO]  ;Get mantissa
@MATH1@_CINT:
	XOR	BX,BX  ;Set up zero result
	SUB	AH,((128) and 0FFh)  ;Take bias out of exponent
	JB	@MATH1@_CXRET  ;Return zero if no integer part
	MOV	BH,AL  ;Highest byte of mantissa
	MOV	BL,CH
	XCHG	AX,CX
	MOV	CL,((16) and 0FFh)
	SUB	CL,CH  ;Number of bits to shift mantissa right
	MOV	AH,BH  ;Save sign
	JB	@MATH1@_OVERFLOW  ;If negative shift, it won't fit in 16 bits
	JZ	@MATH1@_OVCHK  ;Only -32768 has 16 bits - go check for it
	OR	BH,((128) and 0FFh)  ;Set implied bit
	SHR	BX,CL  ;Position the integer
	ADC	BX,0  ;Perform rounding
	JO	@MATH1@_POSBOVER
	OR	AH,AH  ;Check sign now
	JNS	@MATH1@_CXRET
	NEG	BX
@MATH1@_CXRET:
	POP	CX
	POP	AX
	MOV	word [@@SFACLO],BX  ;Result in both FAC and BX

@VALINT:
@MATH1@_@SVALNT: MOV	byte [@@SVALTP],((2) and 0FFh)
	RET
@MATH1@_POSBOVER:  ;Here for either -32768 or overflow
	OR	AH,AH  ;If signed then -32768
	JS	@MATH1@_CXRET
	JMP	@MATH1@_OVERFLOW
@MATH1@_OVCHK:
;Come here if no shift is needed on the number, i.e., it requires a full
;16 bits. Only -32768 (8000H) is allowed.
	CMP	BX,32768  ;The 1 is sign bit (negative), not implied bit
	JNZ	@MATH1@_OVERFLOW
	TEST	AL,((128) and 0FFh)  ;Should we be rounding up?
	JZ	@MATH1@_CXRET  ;If so, that causes overflow
@MATH1@_OVERFLOW:
	JMP	@@SOVERR

; SUBTTL	 $FLT	 CONVERT INTEGER IN (DX) TO REAL AND STORE IN FAC
;****************************************************************
;       $FLT    CONVERTS THE SIGNED INTEGER IN (DX) TO A REAL
;               (FLOATING POINT ) NUMBER AND STORES IT IN THE FAC
;               AND SETS $VALTP=4
;*****************************************************************
@@SFLT:	XOR	BX,BX  ;CLEAR HIGH MANTISSA BYTE (BL)
	XOR	AH,AH  ;CLEAR OVERFLOW BYTE
	MOV	SI,@@SFAC+1  ;FETCH $FAC ADDRESS TO (SI)
	MOV	byte [SI-1],((144) and 0FFh)  ;SET EXPONENT TO 16
	MOV	byte [SI+0],((0) and 0FFh)  ;SET SIGN POSITIVE
	OR	DX,DX  ;SETS SF=1 IF NEGATIVE NO.
	JNS	@MATH1@_FLT10  ;IF POSITIVE PROCEED
	NEG	DX  ;NEED POSTIVE MAGNITUDE
	MOV	byte [SI+0],((128) and 0FFh)  ;SET SIGN TO NEGATIVE
@MATH1@_FLT10:	MOV	BL,DH  ;WILL MOVE (DX) TO (BLDH)
	MOV	DH,DL
	MOV	DL,BH  ;SET (DL)=0
	MOV	byte [@@SVALTP],((4) and 0FFh)  ;SET TYPE TO S.P.
	JMP	@@SNORMS  ;GO NORMALIZE

; SUBTTL	 $FMULD  DOUBLE PRECISION MULTIPLICATION
;**************************************************************

;       $FMULD  THIS ROUTINE FORMS THE DOUBLE PRECISION PRODUCT
;               ($FAC):=($FAC)*($ARG)
;               THE TECHNIQUE USED IS DESCRIBED IN KNUTH, VOL II
;               P.233 AND IS CALLED ALGORITHM "M"
;       CALLING SEQUENCE:       CALL    $FMULD
;               WITH THE MULTIPLIER AND MULTIPLICAND IN THE
;               $FAC AND $ARG

;**************************************************************

@DMULT:
@MATH1@_@SFMULD:  ;DOUBLE PRECISION MULT., (FAC)=(FAC)*(ARG)
	MOV	AL,byte [@@SFAC]  ;WILL FIRST SEE IF FAC IS ZERO
	OR	AL,AL  ;AND IF SO JUST RETURN
	JZ	@MATH1@_FMD10
	MOV	AL,byte [@@SARG]  ;WILL NOW SEE IF ARG IS ZERO AND
	OR	AL,AL  ;IF SO SET FAC TO ZERO AND RETURN
	JNZ	@MATH1@_FMD20  ;IF NOT ZERO PROCEED TO MULTIPLY
	JMP	@@SDZERO  ;ZERO THE FAC
@MATH1@_FMD10:	RET
@MATH1@_FMD20:
	MOV	BX,word [@@SARG-1]  ;FETCH SIGN AND EXP. TO BX
	CALL	@MATH1@_@SAEXPS  ;ADD THE EXPONENTS
	PUSH	word [@@SFAC]  ;EXPONENT,SIGN
	MOV	word [@@SARG-1],BX  ;REPLACE UNPACKED MANTISSA
;PUT THE SIGN OF THE PRODUCT IN
;FAC+1
	CALL	@MATH1@_@SSETDB  ;MOVE THE FAC TO $DBUFF SO PRODUCT
;CAN BE FORMED IN THE FAC, AND ZERO
;THE FAC AND RETURNS WITH (AX)=0
	MOV	SI,AX  ;J
	MOV	word [@@SFAC],AX
	MOV	BX,@@SDBUFF
	MOV	word [@@SARG],AX
	MOV	BP,@@SARGLO  ;POINT TO MULTIPLICAND BASE
@MATH1@_M1:	MOV	AX,word [BX+SI+0]  ;FETCH MULTIPLIER V(J)
	OR	AX,AX  ;SEE IF ZERO
	JZ	@MATH1@_M4D  ;IF ZERO W(J)=0
	MOV	DI,0  ;I
	MOV	CX,DI  ;K
@MATH1@_M4:	MOV	AX,word [BX+SI+0]  ;FETCH MULTIPLIER V(J)
	MUL	word [BP+DI+0]  ;FORM PRODUCT V(J)*U(J) IN (DXAX)
	PUSH	BX  ;SAVE PTR. TO MULTIPLIER BASE
	MOV	BX,SI
	ADD	BX,DI  ;I+J
	ADD	BX,@@SDFACL-8  ;W(I+J) ADDRESS IN BX
	ADD	AX,word [BX+0]  ;(DXAX)=U(I)*V(J)+W(I+J)
	JNB	@MATH1@_M4A
	INC	DX
@MATH1@_M4A:	ADD	AX,CX  ;T=U(I)*V(J)+W(I+J)+K
	JNB	@MATH1@_M4B
	INC	DX
@MATH1@_M4B:	MOV	word [BX+0],AX  ;W(I+J)= T MOD 2^16
	MOV	CX,DX  ;K=INT(T/2^16)
	POP	BX  ;RECALL PTR TO MULTIPLIER BASE
	CMP	DI,6  ;FINISHED INNER LOOP?
	JZ	@MATH1@_M4C  ;IF SO JUMP AND SET W(J)
	INC	DI
	INC	DI
	JMP	@MATH1@_M4
@MATH1@_M4C:	MOV	AX,CX  ;(AX)=K
@MATH1@_M4D:	PUSH	BX  ;SAVE PTR TO MULTIPLIER BASE
	MOV	BX,@@SDFACL
	MOV	word [BX+SI+0],AX  ;W(J)=K OR 0 (0 IF V(J) WERE 0)
	POP	BX  ;RECALL PTR TO MULTIPLIER BASE
	CMP	SI,6  ;FINISHED OUTER LOOP?
	JZ	@MATH1@_M5
	INC	SI
	INC	SI
	JMP	@MATH1@_M1
@MATH1@_M5:  ;MULTIPLICATION COMPLETE AND IN FAC
	MOV	SI,@@SDFACL-2  ;WILL NOW SET ST
	STD  ;WANT NON-ZERO BYTE ASAP SO PROB.
;SEEMS HIGHER OF GETTING ONE IF
;(SI) IS DECREMENTED
	MOV	CX,7  ;7-BYTE CHECK
@MATH1@_M5AA:	LODSB  ;FETCH NEXT BYTE
	OR	AL,AL
	LOOPZ	@MATH1@_M5AA
	JZ	@MATH1@_M5AB  ;DON'T NEED TO SET ST
	OR	byte [@@SDFACL-1],((32) and 0FFh)  ;"OR" IN ST BIT
@MATH1@_M5AB:
	MOV	AL,byte [@@SFAC-1]  ;SEE IF WE NEED TO INC EXPONENT
	OR	AL,AL
	POP	word [@@SFAC]  ;RESTORE EXPONENT,SIGN
	JS	@MATH1@_M6
	MOV	BX,@@SDFACL-1  ;MUST SHIFT 1 BIT LEFT
	MOV	CX,4
@MATH1@_M5A:	RCL	word [BX+0],1
	INC	BX
	INC	BX
	LOOP	@MATH1@_M5A
@MATH1@_M5B:	JMP	@MATH1@_@SROUND  ;NOW ROUND
@MATH1@_M6:	INC	byte [@@SFAC]  ;INCREMENT EXPONENT
	JNZ	@MATH1@_M5B
	JMP	@MATH1@_@SOVFLS  ;OVERFLOW!

; SUBTTL	 $FMULS  SINGLE PRECISION 8086 MULTIPLICATION
;**********************************************************
;       $FMULS  FMULS MULTIPLIES THE SINGLE PRECISION
;               FLOATING POINT QUANTITIES (BXDX) AND (FAC)
;               AND RETURNS THE PRODUCT IN THE (FAC). ONLY
;               SEGMENT REGISTERS ARE PRESERVED.
;***********************************************************

@@SFMULS:  ;(FAC)=(BXDX)*(FAC)
	CALL	@@SSIGNS  ;ZF=1 WILL BE SET IF (FAC)=0
	JZ	@MATH1@_FMS00  ;JUST RETURN IF (FAC)=0
	OR	BH,BH  ;IF EXPONENT OF (BXDX) IS ZERO
	JNZ	@MATH1@_FMS05  ;PROCEED IF NON-ZERO
@MATH1@_FMS00:	JMP	@MATH1@_@SZERO  ;THE NUMBER IS ZERO.
@MATH1@_FMS05:
	CALL	@MATH1@_@SAEXPS  ;ADD THE S.P. EXPONENTS
;***************************************************************
;WILL NOW PROCEED TO MULTIPLY THE MANTISSAS. THE MULTIPLICATION
;WILL UTILIZE THE 16 BIT MUL INSTRUCTION AND THUS WILL TAKE
;PLACE AS PARTIAL PRODUCTS SINCE WE HAVE 24 BIT MANTISSAS TO
;MULTIPLY.
;***************************************************************
	MOV	CX,word [@@SFAC-1]  ;(CH)=($FAC):(CL)=($FAC-1)
	XOR	CH,CH  ;(CX) CONTAINS HIGH MANTISSA BITS
	MOV	AX,word [@@SFAC-3]  ;(AX) CONTAINS LOW MANTISSA BITS OF FAC
	MOV	BH,CH  ;SET (BH)=0 AS WELL
;*************************************************************
;AT THIS POINT WE HAVE THE FAC MANTISSA IN (CLAX) AND THE
;(BXDX) MANTISSA IN (BLDX). THE UNDERSTOOD LEADING MANTISSA
;BIT WAS INSTALLED BY $AEXPS AND THE SIGN OF THE PRODUCT
;WAS STORED IN FAC+1
;THE PRODUCT WILL BE FORMED IN (BXCX) BY PARTIAL PRODUCTS.
;FIRST THE NECESSARY ELEMENTS WILL BE PUSHED ON THE STACK
;THEN UTILIZED IN REVERSE ORDER(THAT'S THE BEST WAY TO
;GET THE THEM OFF THE LIFO STACK -TURKEY!)
;************************************************************
	MOV	SI,BX
	MOV	DI,CX
	MOV	BP,DX
	PUSH	CX  ;HIGH FAC MANTISSA BITS
	PUSH	AX  ;LOW FAC MANTISSA BITS
	MUL	DX  ;32 BIT PRODUCT FORMED(ONLY NEED
	MOV	CX,DX  ;MOST 16 SIGNIFICANT BITS)
	POP	AX  ;LOW FAC MANTISSA BITS
	MUL	BX  ;TIMES HIGH MANTISSA BITS OF (BLDX)
	ADD	CX,AX  ;ADD TO PREVIOUS CALCULATION
	JNB	@MATH1@_FMS10  ;IF CARRY NOT PRODUCED PROCEED
	INC	DX
@MATH1@_FMS10:	MOV	BX,DX  ;PROBABLY ONLY 8 BITS HERE
	POP	DX  ;HIGH FAC MANTISSA BITS
	MOV	AX,BP  ;LOW 16 MANTISSA BITS OF (BLDX)
	MUL	DX
	ADD	CX,AX  ;ADD IN LOW ORDER BITS
	JNB	@MATH1@_FMS20  ;JUMP IF CARRY NOT PRODUCED
	INC	DX
@MATH1@_FMS20:	ADD	BX,DX  ;CAN'T PRODUCE CARRY HERE
	MOV	DX,DI  ;HIGH FAC MANTISSA BITS
	MOV	AX,SI  ;HIGH FAC MANTISSA BITS
	MUL	DL  ;(AX) HAS ENTIRE PRODUCT
	ADD	BX,AX  ;ADD IT IN
	JNB	@MATH1@_FMS30  ;IF NO CARRY PROCEED
	RCR	BX,1  ;MOVE EVERYTHING RIGHT
	RCR	CX,1
	INC	byte [@@SFAC]  ;MUST NOW CHECK FOR OVERFLOW
	JNZ	@MATH1@_FMS30  ;PROCEED IF NON-ZERO
	JMP	@MATH1@_@SOVFLS
@MATH1@_FMS30:  ;PRODUCT FORMED, MUST NOW GET MANTISSA IN (BLDXAH) FOR ROUNS
;PRODUCT IS CURRENTLY IN (BXCX)
	OR	BH,BH  ;MUST BE SURE PRODUCT LEFT JUSTIFIED
	JNS	@MATH1@_FMS35  ;IN (BXCX)
	INC	byte [@@SFAC]  ;NEED TO INCREMENT EXP.
	JNZ	@MATH1@_FMS37  ;IF NOT OVERFLOW PROCEED
	JMP	@MATH1@_@SOVFLS  ;OVERFLOW JUMP
@MATH1@_FMS35:
	RCL	CX,1
	RCL	BX,1
@MATH1@_FMS37:
	MOV	DL,CH
	MOV	DH,BL
	MOV	BL,BH
	MOV	AH,CL  ;OVERFLOW BYTE
	JMP	@MATH1@_@SROUNS  ;GO ROUND
	RET

; SUBTTL	 $FOTAN  ROUTINE TO PUT IN DECIMAL POINT AND LEADING ZEROS
;*****************************************************************

;       $FOTAN  THIS ROUTINE IS CALLED BY THE FREE FORMAT OUTPUT
;               CODE TO OUTPUT DECIMAL POINT AND LEADING ZEROS.
;       $FOTED  THIS ROUTINE IS CALLED BY BOTH THE FREE FORMAT
;               OUTPUT ROUTINE AND THE PRINT USING CODE TO OUTPUT
;               THE DECIMAL POINT WHEN NECESSARY AND TO PUT IN
;               COMMAS "," AFTER EACH THREE DIGITS IF THIS OPTION
;               IS INVOKED.
;       CALLING SEQUENCE:       CALL    $FOTAN
;                               CALL    $FOTED
;               WITH $FMTCX CONTAINING NUMBER PLACES PRIOR TO
;               DECIMAL POINT(NEGATIVELY) IN UPPER BYTE AND
;               NO PLACES BEFORE NEXT COMMA IN LOW BYTE

;*******************************************************************

@MATH1@_@SFOTAN:
	DEC	CH  ;IF NEGATIVE THEN LEADING ZEROS
	JNS	@MATH1@_FTD05
	MOV	word [@@SDPADR],BX  ;SAVE DECIMAL POINT COUNT
	MOV	byte [BX+0],((".") and 0FFh)  ;MOVE IN DECIMAL POINT
@MATH1@_FTN10:	INC	BX  ;POINT TO NEXT OUTPUT POSITION
	MOV	byte [BX+0],(("0") and 0FFh)  ;PUT IN LEADING ZERO
	INC	CH  ;WILL INCREMENT CH UNTIL ZERO
	JNZ	@MATH1@_FTN10  ;PUT IN LEADING ZEROS UNTIL CH ZERO
	INC	BX  ;POINT TO NEXT BUFFER POSITION
	XOR	CX,CX  ;ZERO OUT DECIMAL POINT AND COMMA CTS.
	JMP	@MATH1@_FTD20  ;GET STACK RIGHT AND RETURN
@MATH1@_@SFOTED:
	DEC	CH  ;SEE IF TIME FOR D.P.
@MATH1@_FTD05:	JNZ	@MATH1@_FTD10  ;IF NOT D.P. TIME SEE IF COMMA TIME
	MOV	byte [BX+0],((".") and 0FFh)  ;PUT IN D.P.
	MOV	word [@@SDPADR],BX  ;SAVE ADDR OF DECIMAL POINT
	INC	BX  ;INCREMENT PAST D.P.
	XOR	CX,CX  ;ZERO COUNTS & SET ZF=1
	JMP	@MATH1@_FTD20  ;GET STACK RIGHT AND RETURN
@MATH1@_FTD10:	DEC	CL  ;IF ZERO TIME FOR COMMA
	JNZ	@MATH1@_FTD20
	MOV	byte [BX+0],((44) and 0FFh)  ;COMMA
	INC	BX  ;POINT TO NEXT BUFFER POSITION
	MOV	CL,((3) and 0FFh)
@MATH1@_FTD20:	MOV	word [@@SFMTCX],CX  ;UPDATE D.P.&COMMA COUNTS
	RET

; SUBTTL	 $FOTCV  CONVERT FAC TO ASCII DIGITS
;************************************************************

;       $FOTCV  CONVERSION OF SINGLE OR DOUBLE PRECISION
;               NUMBER TO ASCII DIGITS.IF DOUBLE PRECISION
;               10 DIGITS WILL BE CONVERTED WITH DOUBLE
;               PRECISION POWER OF TEN INTEGERS, 3 DIGITS
;               WITH SINGLE PRECISION POWER OF TEN INTEGERS
;               AND 3 DIGITS WITH INTEGER POWERS OF TEN
;       CALLING SEQUENCE:       CALL    $FOTCV
;               WITH THE NUMBER TO BE CONVERTED HAVING PREVIOUSLY
;               BEEN OPERATED ON BY $FOTNV TO BRACKET THE
;               NUMBER AND HAVE ALL DIGITS IN THE INTEGER PORTION
;               OF THE FAC. AND THE CORRESPONDING EXPONENT WILL
;               BE SAVED ON THE STACK AND CONVERTED LATER.

;**************************************************************

@MATH1@_@SFOTCV: CALL	@@SGETYP  ;SET CONDITION CODES FOR VALTYP
	JPO	@MATH1@_FCV40  ;IF SINGLE PRECISION GO PROCESS
	PUSH	CX  ;SAVE DIGIT AND COMMA COUNT
	PUSH	BX  ;SAVE BUFFR PTR.
	MOV	SI,@@SDFACL  ;WILL MOVE FAC TO ARG
	MOV	DI,@@SARGLO
	MOV	CX,4
	CLD
 REP	MOVSW
	CALL	@MATH1@_@SDINT  ;WILL SEE IF FAC ALREADY INTEGER
	PUSH	BX  ;NEED TO CALL VCOMP WITH BX=ARG-1
	MOV	BX,@@SARG-1
	CALL	@MATH1@_@SVCOMP  ;DO COMPARE
	POP	BX  ;GET BUFFER POINTER BACK
	MOV	SI,@@SARGLO  ;WILL MOVIE ARG TO FAC
	MOV	DI,@@SDFACL
	MOV	CX,4
	CLD
 REP	MOVSW
	JZ	@MATH1@_FCV05  ;DON'T ADD .5 IF NO DIFF.
	CALL	@MATH1@_@SDADDH  ;ADD .5 TO NUMBER
@MATH1@_FCV05:	MOV	CL,byte [@@SFAC]  ;SHIFT COUNT IN (CL)
	SUB	CL,((184) and 0FFh)
	NEG	CL  ;MAKE SHIFT COUNT POSITIVE
	CLC  ;TO TELL DINT NOT TO NORMALIZE
	CALL	@MATH1@_@SFTDNT  ;MAKE SURE ITS STILL INTEGER
	POP	BX  ;RECALL BUFFER PTR.
	POP	CX  ;RECALL DIGIT AND COMMA COUNT
	MOV	SI,@MATH1@_@SFODTB  ;DOUBLE PRECISION OUTPUT INTEGERS
	MOV	AL,((9) and 0FFh)  ;9 DIGITS TO BE CONVERTED WITH D.P.
@MATH1@_FCV10:	CALL	@MATH1@_@SFOTED  ;SEE IF DECIMAL POINT NEEDED
	PUSH	AX  ;SAVE DIGIT COUNT
	MOV	AL,(("0"-1) and 0FFh)  ;WILL FORM DIGIT IN (AL)
	PUSH	AX
@MATH1@_FCV20:	POP	AX  ;RECALL DIGIT
	INC	AL  ;INCREMENT TO NEXT DIGIT
	PUSH	AX  ;SAVE DIGIT
	CALL	@MATH1@_DSUBI  ;SUBTRACT POWER OF TEN
	JNB	@MATH1@_FCV20
	CALL	@MATH1@_DADDI  ;ADD POWER 10 BACK IN
;AND ADVANCE SI TO NEXT POWER 10
	POP	AX  ;GET DIGIT BACK
	MOV	byte [BX+0],AL  ;PUT IN ASCII DIGIT
	INC	BX  ;POINT TO NEXT BUFFER POSITION
	POP	AX  ;GET DIGIT COUNT
	DEC	AL  ;SEE IF 10 DIGITS FORMED
	JNZ	@MATH1@_FCV10  ;IF NOT CONTINUE THE ALGORITHM
	PUSH	CX  ;SAVE DECIMAL POINT COUNT
	MOV	SI,@@SDFACL  ;WILL MOVE INTO FAC
	MOV	DI,@@SFACLO
	MOV	CX,2
	CLD
 REP	MOVSW
	POP	CX  ;RECALL DECIMAL POINT COUNT
	JMP	@MATH1@_FCV50  ;GO DO THE REST OF THE DIGITS
@MATH1@_FCV40:
;**************************************************************
;CODE BELOW WORKS WITH SINGLE PRECISION NUMBERS
;***************************************************************
	PUSH	BX  ;SAVE BUFFER PTR
	PUSH	CX  ;SAVE DIGIT AND COMMA COUNTS
	CALL	@MATH1@_@SPUSHF  ;SAVE $FAC ON STACK
	CALL	@MATH1@_@SINT  ;WILL SEE IF INTEGER CURRENTLY
	POP	DX  ;RECALL FAC
	POP	BX
	CALL	@@SFCOMP  ;COMPARE IF EQUAL DON'T ADD .5
	JZ	@MATH1@_FCV45
	MOV	word [@@SFAC-1],BX  ;MOVE BACK TO FAC
	MOV	word [@@SFACLO],DX
	CALL	@MATH1@_@SFADDH  ;ADD .5 TO NUMBER
@MATH1@_FCV45:	MOV	AL,((1) and 0FFh)  ;FLAG TO QINT WE HAVE A POS. NO.
	CALL	@MATH1@_@SQINT  ;GET INTEGER INTO (BLDX)
	MOV	word [@@SFAC-1],BX
	MOV	word [@@SFACLO],DX  ;MOVE TO FAC
	POP	CX  ;RECALL DIGIT AND COMMA COUNTS
	POP	BX  ;RECALL BUFFER PTR

@MATH1@_FCV50:
	MOV	AL,((3) and 0FFh)  ;WILL CONVERT 3 DIGITS IN THIS CODE
	MOV	DX,@MATH1@_@SFOSTB  ;Print S.P. numbers with 7 digits
@MATH1@_FCV60:	CALL	@MATH1@_@SFOTED  ;SEE IF NEED A DECIMAL POINT OR COMMA
	PUSH	AX  ;SAVE DIGIT COUNT
	PUSH	BX  ;SAVE BUFFER POINTER
	PUSH	DX  ;SAVE POWER OF TEN POINTER
	CALL	@@SMOVRF  ;FETCH INTEGER
	POP	BP  ;FETCH POWER TEN POINTER
	MOV	AL,(("0"-1) and 0FFh)  ;WILL BUILD DIGIT IN (AL)
	PUSH	AX  ;SAVE DIGIT
@MATH1@_FCV70:	POP	AX  ;RECALL DIGIT
	INC	AL  ;GO TO NEXT DIGIT
	PUSH	AX
	CALL	@MATH1@_@SRSUBM  ;SUBTRACT NO. POINTED TO BY (BP)
;FROM (BLDX)
	JNB	@MATH1@_FCV70  ;CONTINUE UNTIL CF=1
;POWER TEN TABLE IN CODE SEGMENT
	ADD	DX,word [cs:BP+0]  ;ADD WORD PORTION
	ADC	BL,byte [cs:BP+2]
;SINCE WE SUBTRACTED ONE TOO MANY
	INC	BP  ;INCREMENT TO NEXT POWER OF TEN
	INC	BP
	INC	BP
	CALL	@@SMOVFR  ;SAVE (BLDX) IN FAC
	POP	AX  ;RECALL DIGIT
	XCHG	DX,BP  ;SAVE POWER TEN PTR. IN DX
	POP	BX  ;RECALL BUFFER POINTER
	MOV	byte [BX+0],AL  ;SEND OUT DIGIT
	INC	BX  ;INCREMENT TO NEXT BUFFER POSITION
	POP	AX  ;RECALL DIGIT COUNT
	DEC	AL  ;SEE IF FINISHED
	JNZ	@MATH1@_FCV60  ;IF NOT CONTINUE
	INC	DX  ;NEED TO INCREMENT PAST 1ST
	INC	DX  ;INTEGER SO THAT FOTCI WILL
	MOV	BP,DX  ;FOTCI IS EXPECTING POINTER IN BP
	MOV	AH,((4) and 0FFh)  ;CONVERT ONLY 4 DIGITS
	JMP	@MATH1@_@SFCI4
;INTEGER ARITHMETIC
@MATH1@_DSUBI:  ;SUBTRACT 7 BYTE INTEGER POINTED TO BY (SI) FROM $DFACL
	PUSH	CX  ;FIRST SAVE CX,SI,DI
	PUSH	SI
	MOV	CX,7  ;7 BYTES
	MOV	DI,@@SDFACL
	CLC  ;CF=0
	CLD  ;SO LODC WILL INCREMENT
@MATH1@_DSUBI1:  ;NEED NO. FROM CODE SEGMENT
	lods byte [cs:si]  ;FETCH BYTE TO AL
	SBB	byte [DI+0],AL  ;SUBTRACT
	INC	DI
	LOOP	@MATH1@_DSUBI1
	POP	SI
	POP	CX
	RET
@MATH1@_DADDI:  ;ADD 7 BYTE INTEGER POINTED TO BY (SI) FROM $DFACL
	PUSH	CX  ;SAVE CX,SI,DI
	MOV	CX,7
	MOV	DI,@@SDFACL
	CLC
	CLD  ;SO LODC WILL INCREMENT SI
@MATH1@_DADDI1:  ;WANT NO. FETCHED FROM CODE SEGMENT
	lods byte [cs:si]  ;FETCH NEXT BYTE TO ADD
	ADC	byte [DI+0],AL  ;ADD IT IN
	INC	DI
	LOOP	@MATH1@_DADDI1
	POP	CX
	RET

; SUBTTL	 $FOTNV  BRACKET FAC SO PRINTABLE DIGITS IN INTEGER PART
;****************************************************************

;       $FOTNV  THIS ROUTINE MULTIPLIES THE FAC BY APPROPRIATE
;               VALUES SO THAT THE PRINTABLE DIGITS (7 FOR SINGLE
;               PRECISION, 16 FOR DOUBLE PRECISION) ARE IN THE
;               INTEGER PART OF THE FAC . IT RETURNS THE COMPLEMENT-
;               ING EXPONENT IN (AL).
;       CALLING SEQUENCE:       CALL    $FOTNV
;               WITH THE FAC CONTAINING THE DESIRED VALUE TO PRINT
;               REGISTERS (BX) AND (CX) WILL RETAIN THEIR VALUES

;*****************************************************************

@MATH1@_@SFOTNV:
	PUSH	BX  ;WON'T ALTER (BX) OR (CX)
	PUSH	CX
	XOR	DI,DI  ;INITIALIZE EXPONENT
	PUSH	DI  ;SAVE EXPONENT
@MATH1@_FNV10:	MOV	BX,@MATH1@_@SFOTB  ;ADDRESS OF BRACKET CONTROL TABLE
	MOV	AL,byte [@@SFAC]  ;FETCH THE EXPONENT
;MUST FETCH FROM CODE SEGMENT
	xlat byte [cs:bx]  ;GET MULTIPLIER
	OR	AL,AL  ;IF ZERO - DONE
	JZ	@MATH1@_FNV20
	POP	DI  ;RECALL EXPONENT
	CBW  ;CONVERT AL TO WORD
	SUB	DI,AX  ;GET EXPONENT CORRECT
	PUSH	DI  ;SAVE EXPONENT
	MOV	DX,AX  ;DX:=exponent for MDPTEN.
	CALL	@MATH1@_MDPTEN  ;Multiply or divide by power of ten.
	JMP	@MATH1@_FNV10  ;See if need to do it again.

@MATH1@_FNV20:	MOV	BX,@MATH1@_@SDP06+4  ;LOWER BOUND
	CALL	@MATH1@_@SMOVBS  ;MOVE OUT TO "DS" AREA
	CALL	@MATH1@_@SCOMPM  ;ONE MORE MULT. POSSIBLE
;$COMPM WILL SET CF=1 IF $DP06
;IS LARGER, CF=0 FOR EQ OR GT
	JNB	@MATH1@_FNV30  ;JUMP IF NOT NEEDED
	CALL	@MATH1@_@SMUL10  ;MULTIPLY BY TEN
	POP	DI  ;RECALL EXPONENT
	DEC	DI  ;ACCOUNT FOR MULTIPLY BY 10.
	PUSH	DI
@MATH1@_FNV30:	CALL	@@SGETYP  ;SET CONDITION CODES FOR TYPE

	JB	@MATH1@_FNV40  ;done if single precision

	MOV	BX,@MATH1@_@SDP09  ;MUST MULTIPLY BY 10^9
	CALL	@MATH1@_@SMOVAC  ;MOVE 10^9 TO $ARG
	CALL	@MATH1@_@SFMULD  ;PERFORM MULTIPLICATION
	POP	AX  ;RECALL EXPONENT
	SUB	AL,((9) and 0FFh)  ;SUBTRACT 9
	PUSH	AX  ;Resave the exponent.
	MOV	BX,@MATH1@_HIDBL  ;Is the number too big?  (Will it
	CALL	@MATH1@_@SMOVBF  ;overflow when $FOTCV adds .5 to it?)
	CALL	@MATH1@_@SDCMPM
	JNA	@MATH1@_FNV40  ;No.
@MATH1@_FNV44:	CALL	@MATH1@_@SDIV10  ;Yes, divide by ten and fix up the
;the decimal exponent.
	POP	AX  ;restore the exponent
	INC	AL  ;adjust for $DIV10
	PUSH	AX
@MATH1@_FNV40:	POP	AX  ;recall exponent
@MATH1@_FNV50:	POP	CX  ;restore registers
	POP	BX
	OR	AL,AL  ;SET CONDITION CODES ACCORDING TO EXP
	RET

; The largest double precision value that .5 can be added to without
; overflow occuring.

@MATH1@_HIDBL:	DB	253,255,3,191,201,27,14,182  ;9999999999999999.

; SUBTTL	 $FOUT	 CONTROL OUTPUT CONVERSION
;***************************************************************

;       $FOUT   THIS ROUTINE PROVIDES TOP-LEVEL CONTROL OF THE
;               FREE FORMAT OUTPUT FUNCTION.
;       CALLING SEQUENCE:       CALL    $FOUT

;****************************************************************

@MATH1@_S:	MOV	BX,@@SFBUFF+1  ;FETCH BUFFER POINTER
	MOV	byte [BX+0],((" ") and 0FFh)  ;MOVE IN SPACE FOR POSSIBLE SIGN
	PUSH	BX  ;SAVE BUFFER POINTER
	CALL	@@SSIGNS  ;DETERMINE SIGN OF NUMBER
	POP	BX  ;RECALL BUFFER POINTER
	PUSHF  ;SAVE FLAGS FOR LATER
	JNS	@MATH1@_FO20  ;JUMP IF POSITIVE
	MOV	byte [BX+0],(("-") and 0FFh)  ;PUT IN MINUS SGN
	PUSH	BX  ;SAVE TEXT POINTER
	CALL	@MATH1@_@SVNEG  ;NEGATE NO. SO WE WORK ONLY WITH
	POP	BX  ;RECALL TEXT POINTER
	OR	AL,((1) and 0FFh)  ;POS. NOS. AND SET ZF=0
@MATH1@_FO20:	INC	BX  ;POINT TO NEXT BUFFER POSITION
	MOV	byte [BX+0],(("0") and 0FFh)  ;PUT IN ZERO IN CASE NO IS ZERO
	POPF  ;RECALL FLAGS
	RET
@FOUT:
@MATH1@_@SFOUT:  ;FREE-FORMAT ENTRY POINT
	CALL	@MATH1@_S  ;DO SIGN FIX-UP
	JNZ	@@SFOUT2  ;IF NON-ZERO PROCEED
	INC	BX  ;POINT TO NEXT OUTPUT BUFFER POS.
	MOV	byte [BX+0],((0) and 0FFh)  ;INDICATE END OF NUMBER
	MOV	BX,@@SFBUFF+1  ;POINT (BX) TO START POSITION
	RET
@@SFOUT2: CALL	@@SGETYP  ;GET TYPE NO.
	JNS	@MATH1@_FO50  ;GO FORMAT SINGLE OR DOUBLE PREC.
	MOV	CX,7*256  ;default 7 digits prior to dp.
	XOR	AX,AX  ;CLEAR COMMA COUNT
	MOV	word [@@SFMTAX],AX
	MOV	word [@@SFMTCX],CX
	CALL	@@SFOTCI  ;CONVERT INTEGER TO ASCII
	JMP	@MATH1@_@SFOTZS  ;DO LEADING ZERO SUPPRESSION
@MATH1@_FO50:	JMP	@MATH1@_@SFOFMT  ;SINGLE OR DOUBLE PREC. OUTPUT

; SUBTTL	 $INT	 CONVERT PRESENT NO. TO INTEGER BY TRUNCATION
;***********************************************************

;       $INT    SINGLE PRECISION INT ROUTINE
;       $DINT   DOUBLE PRECISION INT ROUTINE
;       $QINT   CONVERT TO INT AND LEAVE IN (BLDX)
;       $FTDNT  FOUT ENTRY TO CONVERT TO INT AND LEAVE RT.ADJUSTED
;       $SHRD   SHIFT DOUBLE PRECISION MANTISSA RIGHT

;**********************************************************
;**********************************************************
;THE INT TECHNIQUE IS PRETTY STRAIGHT FORWARD EXCEPT
;FOR NEGATIVE NON-INTEGERS. THE RUB WITH THESE NOS. IS THAT
;IF THEY HAVE ANY FRACTIONAL BITS THE ANSWER IS TO
;BE THE NEXT LOWER VALUE INTEGER. FOR EXAMPLE : INT(-1.1) SHOULD
;RETURN -2 WHEREAS INT(1.1) SHOULD RETURN 1. THE TRICK USED TO
;EFFECT THIS IS TO SUBTRACT 1 FROM NEGATIVE NON-INTEGER MANTISSAS
;PRIOR TO SHIFTING OUT FRACTIONAL BITS THEN ADD 1 BACK TO THE
;MANTISSA ONCE FRACTIONAL BITS HAVE BEEN SHIFTED OUT. WITH THE
;FOLLOWING EXAMPLE (IN BINARY) WATCH HOW THIS TECHNIQUE WORKS:
;FIND INT(10011.011)
;       (1)     SINCE THIS IS A POSITIVE NO WE JUST SHIFT OUT
;               THE FRACTIONAL BITS AND NORMALIZE
;FIND INT(-10011.011)
;       (1)     SUBTRACT ONE FROM THE MANTISSA YIELDING -10011.010
;       (2)     SHIFT OUT THE FRACTIONAL BITS YIELDING -10011.
;       (3)     ADD 1 TO MANTISSA YIELDING -10100 THE CORRECT VALUE
;FIND INT(-10011.000)
;       (1)     SUBTRACT ONE FROM MANTISSA YIELDING -10010.111
;       (2)     SHIFT OUT THE FRACTIONAL BITS YIELDING -10010.
;       (3)     ADD 1 TO MANTISSA YIELDING -10011. THE CORRECT VALUE
;******************************************************************
@MATH1@_@SDINT:  ;DOUBLE PRECISION INT FUNCTION
	MOV	CL,byte [@@SFAC]  ;CL:=exponent.
	SUB	CL,((184) and 0FFh)  ;Is there a fractional part?
	JNB	@MATH1@_DNT20  ;RETURN IF NO FRACTIONAL BITS
	NEG	CL  ;CL NOW POSITIVE
@MATH1@_@SFTDNT: PUSHF  ;FOUT ENTRY POINT. THIS IS SEPARATE
;ENTRY POINT BECAUSE FOUT WISHES
;TO HAVE INTEGER RIGHT ADJUSTED
;IN THE MANTISSA BITS. WE WILL DO
;THE NECESSARY SHIFTS AND RETURN
;PRIOR TO NORMALIZATION IF CALLED
;BY FOUT (SIGNIFIED BY CF=0)
	TEST	byte [@@SFAC],((255) and 0FFh)  ;Is the exponent zero?
	JNE	@MATH1@_DINTNZ  ;No, proceed.
	POPF  ;Yes, if the exponent is zero the
	RET  ;number is zero.  Don't operate on
;the possible garbage in the mantissa.
@MATH1@_DINTNZ: MOV	BX,@@SFAC-2
	MOV	AL,byte [BX+1]  ;FETCH SIGN BYTE
	MOV	byte [BX+3],AL  ;AND PUT IN $FAC+1  FOR $NORMD
	OR	AL,AL  ;SEE IF NEGATIVE
	PUSHF
	OR	AL,((128) and 0FFh)  ;RESTORE HIDDEN 1
	MOV	byte [BX+1],AL  ;AND REPLACE
	MOV	byte [BX+2],((184) and 0FFh)  ;SET EXPONENT FOR POST SHIFT VALUE
	POPF  ;RECALL SF
	PUSHF
	JNS	@MATH1@_DNT10  ;IF POSITIVE PROCEED
;*****************************************************************
;NEGATIVE NO. MUST DO THE FANCY FOOTWORK DESCRIBED ABOVE
;*****************************************************************
	CALL	@MATH1@_DINTA  ;SUBTRACT 1 FROM MANTISSA BITS
@MATH1@_DNT10:	XOR	CH,CH  ;(CX)=SHIFT COUNT
	CALL	@MATH1@_@SSHRD  ;DOUBLE PRECISION SHIFT RIGHT
	POPF  ;RECALL SF
	JNS	@MATH1@_DNT15  ;IF POSITIVE PROCEED
	CALL	@MATH1@_ADD1D  ;ADD 1 TO MANTISSA BITS
@MATH1@_DNT15:	MOV	byte [@@SDFACL-1],((0) and 0FFh)  ;ZERO THE OVERFLOW BYTE
	POPF  ;SEE IF CALLED BY FOUT (CF=0)
	JNB	@MATH1@_DNT20  ;IF SO JUST RETURN
	JMP	@@SNORMD  ;OTHERWISE NORMALIZE
@MATH1@_DNT20:	RET

@MATH1@_@SSHRD:  ;SHIFT RIGHT DOUBLE PRECISION

@MATH1@_SHRD10: PUSH	CX  ;SAVE OUTER LOOP VARIABLE (BITS TO
;BE SHIFTED RIGHT)
	PUSH	BX  ;SAVE POINTER TO HIGH BYTE TO SHIFT
	CLC  ;CF=0
	CALL	@MATH1@_@SSHDR  ;SHIFT 1 BIT RIGHT
	POP	BX
	POP	CX  ;GET OUTER LOOP VARIABLE
	LOOP	@MATH1@_SHRD10
	RET

@MATH1@_DINTA:	PUSH	BX
	MOV	BX,@@SDFACL  ;BEGINNING ADDRESS FOR SUBTRACT
@MATH1@_DINA10: SUB	word [BX+0],1  ;NEED CF SO CAN'T USE DEC
	JNB	@MATH1@_DINA20
	INC	BX
	INC	BX  ;CAN DO WORD SUBTRACTS SINCE HIGH BIT
;OF MANTISSA IS SET (THUS PROTECTING
;THE EXPONENT FROM THE SUBTRACT)
	JMP	@MATH1@_DINA10
@MATH1@_DINA20: POP	BX
	RET

@MATH1@_ADD1D:  ;ADD 1 TO DOUBLE PRECISION MANTISSA BITS
	PUSH	BX
	MOV	BX,@@SDFACL
@MATH1@_ADD10:	INC	byte [BX+0]
	JNZ	@MATH1@_ADD20
	INC	BX  ;POINT TO NEXT BYTE THERE WAS A CARRY
	JMP	@MATH1@_ADD10
@MATH1@_ADD20:	POP	BX
	RET

@INT:
@MATH1@_@SINT:  ;SINGLE PRECISION INT FUNCTION
	MOV	CL,byte [@@SFAC]  ;FETCH EXPONENT
	SUB	CL,((152) and 0FFh)  ;CALCULATE SHIFT COUNT
	JNB	@MATH1@_INT20  ;ALREADY INTEGER PROCEED
	NEG	CL  ;GET POSITIVE SHIFT COUNT

; Note - At this point the carry is set.  This will be used
; to indicate that this is not a QINT call.  Also note that
; if the exponent is zero the above subtraction did set the
; carry so the check for the zero exponent case below is
; guaranteed to be executed.

@MATH1@_QINTX:  ; $QINTX'S ENTRY POINT
	MOV	DX,word [@@SFACLO]  ;FETCH LOW MANTISSA BITS
	MOV	BX,word [@@SFAC-1]  ;FETCH EXP,SIGN,HIGH MANTISSA BITS
	INC	BH  ;Is the exponent zero?  (Test for zero
	DEC	BH  ;without affecting the carry.)
	JNE	@MATH1@_QINTNZ  ;No, proceed.
	XOR	BL,BL  ;Yes, put zero into BL,DX for QINT
	XOR	DX,DX  ;rather than work with the possible
	RET  ;garbage in the mantissa (an exponent
;of zero means the number is zero).
@MATH1@_QINTNZ: PUSHF  ;Save carry which if clear indicates
;this is a QINT call.
	OR	BL,BL  ;SEE IF NEGATIVE
	PUSHF  ;SAVE
	MOV	byte [@@SFAC+1],BL  ;SAVE SIGN FOR NORMS
	MOV	byte [@@SFAC],((152) and 0FFh)  ;SET EXP FOR POST SHIFT
	OR	BL,((128) and 0FFh)  ;RESTORE HIDDEN 1
	POPF
	PUSHF  ;SAVE SIGN
	JNS	@MATH1@_INT10
	SUB	DX,1  ;CAN'T DO A 'DEC' BECAUSE NEED CF
	SBB	BL,((0) and 0FFh)  ;DO APPROPRIATE SUBTRACT TO HIGH BYTE
@MATH1@_INT10:	XOR	CH,CH  ;CX HAS LOOP COUNT
	OR	CL,CL  ;IF SHIFT COUNT ZERO MUST JUMP OVER
	JZ	@MATH1@_INT12  ;RIGHT SHIFTS
@MATH1@_INT11:	SHR	BL,1  ;SHIFT RIGHT INTO CF
	RCR	DX,1  ;ROTATE RIGHT
	LOOP	@MATH1@_INT11  ;WILL DO (CX) RIGHT SHIFTS
@MATH1@_INT12:	POPF  ;RECALL SIGN OF NO.
	LAHF  ;STORE FLAGS TEMPORARILY
	JNS	@MATH1@_INT15  ;PROCEED IF POSITIVE
	INC	DX
	JNZ	@MATH1@_INT15
	INC	BL
@MATH1@_INT15:
	POPF  ;CF=0 IF CALLED BY QINT
	JNB	@MATH1@_INT20  ;JUST RETURN IF QINT CALL
	XOR	AH,AH  ;CLEAR OVERFLOW BYTE
	JMP	@@SNORMS  ;NORMALIZE AND RETURN
@MATH1@_INT20:	SAHF  ;MUST SEE IF NEGATIVE
@MATH1@_NGBLDX: JNS	@MATH1@_INT30  ;IF NOT PROCEED AS NORMAL
	NOT	DX  ;COMPLEMENT DX
	NOT	BL  ;AND BL
	ADD	DX,1  ;NEED CF SET IF DX OVERFLOWS
	ADC	BL,((0) and 0FFh)  ;2's COMPLEMENT NOW FORMED
@MATH1@_INT30:	RET
@MATH1@_QINT:
@MATH1@_@SQINT:  ;DO INT(FAC) AND LEAVE IN (BLDX)
	MOV	CL,((152) and 0FFh)
	SUB	CL,byte [@@SFAC]  ;GET SHIFT COUNT TO CL
	CLC  ;CF=0
	JMP	@MATH1@_QINTX  ;LEAVE RIGHT ADJUSTED

; SUBTTL	 $LOG	 SINGLE PRECISION NATURAL LOG FUNCTION
;**********************************************************

;       $LOG    COMPUTE THE NATURAL LOG OF THE VALUE IN THE FAC
;       CALLING SEQUENCE:       CALL    $LOG
;               WITH INPUT ARGUMENT IN THE FAC
;       MLLN2   IF THIS ENTRY POINT IS USED THE FAC WILL BE
;               MULTIPLIED BY LN(2)

;************************************************************

@LOG:
@MATH1@_@SLOG:	CALL	@@SSIGNS  ;ERROR IF ($FAC).LE..0
	JLE	@MATH1@_LG100
;****************************************************************
;       WILL NOW PERFORM SPECIAL TEST FOR ARGUMENT OF 1.0 AND IF
;       FOUND EQUAL ANSWER IS 0
;*****************************************************************
	MOV	DX,0  ;FETCH 1.0 TO (BXDX)
	MOV	BX,33024
	CALL	@@SFCOMP
	JNZ	@MATH1@_LOG10  ;PROCEED IF NOT 1.0
	MOV	word [@@SFACLO],DX  ;WILL ZERO $FAC AND RETURN
	MOV	word [@@SFACM1],DX
	RET
@MATH1@_LOG10:
	MOV	AL,byte [@@SFAC]  ;FETCH EXPONENT
	SUB	AL,((128) and 0FFh)  ;TAKE OUT BIAS
	CBW  ;CONVERT BYTE TO WORD
	PUSH	AX  ;AND SAVE
	MOV	byte [@@SFAC],((128) and 0FFh)  ;ZERO THE EXPONENT
	CALL	@MATH1@_@SPUSHF  ;SAVE ARG FOR Q(X) CALCULATION
	MOV	BX,@@SLOGP  ;NOW TO USE HART APPROX FOR P(X)
	CALL	@MATH1@_@SPOLY
	POP	DX  ;GET X OFF THE STACK
	POP	BX
	CALL	@MATH1@_@SPUSHF  ;SAVE P(X)
	CALL	@@SMOVFR  ;MOVE X TO FAC
	MOV	BX,@MATH1@_@SLOGQ
	CALL	@MATH1@_@SPOLY  ;CALCULATE Q(X)
	POP	DX  ;RECALL P(X)
	POP	BX
	CALL	@@SFDIVS  ;CALCULATE P(X)/Q(X)
	POP	DX  ;FETCH RAW EXPONENT
	CALL	@MATH1@_@SPUSHF  ;SAVE FAC ON THE STACK
	CALL	@@SFLT  ;FLOAT THE VALUE INTO THE $FAC
	POP	DX  ;RECALL LOG2 VALUE
	POP	BX
	CALL	@@SFADDS  ;ADD
@MATH1@_MLLN2:	MOV	BX,32817  ;FETCH LN(2) TO (BXDX)
	MOV	DX,29208
	JMP	@@SFMULS  ;MULTIPLY TO COMPLETE
@MATH1@_LG100:	JMP	@@SFCERR

; SUBTTL	 $NORMD  DOUBLE PRECISION NORMALIZATION ROUTINE
;******************************************************************

;       $NORMD  NORMALIZES THE NUMBER IN $FAC+1 THRU $DFACL-1
;               AND JUMPS TO $ROUND
;       CALLING SEQUENCE:       CALL    $NORMD
;               OR              JMP     $NORMD
;               WILL RESULT IN NORMALIZATION FOLLOWED BY ROUNDING
;               AND PACKING THE $FAC.

;*******************************************************************

@@SNORMD: MOV	DL,((57) and 0FFh)  ;MAX BITS TO SHIFT LEFT
	MOV	BX,@@SDFACL-1
@MATH1@_NORD5:	MOV	DI,@@SFAC-1
	MOV	SI,@@SFAC
	JMP	@MATH1@_NORD30
@MATH1@_NORD10:
	MOV	CX,4
	CLC  ;CF=0
@MATH1@_NORD20: RCL	word [BX+0],1
	INC	BX
	INC	BX  ;POINT TO NEXT WORD
	LOOP	@MATH1@_NORD20
	MOV	BX,@@SDFACL-1  ;POINT BACK TO END OF NUMBER
@MATH1@_NORD25:
	DEC	byte [SI+0]  ;DECREMENT EXPONENT
	JZ	@MATH1@_NORD40  ;DO CLEAN-UP IF UNDERFLOW
	DEC	DL  ;SEE IF MAX BITS SHIFTED
	JZ	@MATH1@_NORD40  ;IF SO TERMINATE SHIFTS
@MATH1@_NORD30: TEST	byte [DI+0],((255) and 0FFh)  ;SF=1 IF NOW NORMALIZED
	JS	@MATH1@_NORD40  ;NORMALIZED

	JNZ	@MATH1@_NORD10  ;MUST SHIFT BIT AT A TIME
;***************************************************************
;CAN DO AT 1 BYTE MOVE LEFT
;***************************************************************
	SUB	byte [SI+0],((8) and 0FFh)  ;SUBTRACT 8
	JBE	@MATH1@_NORD40  ;UNDERFLOW
	SUB	DL,((8) and 0FFh)  ;SEE IF MAX BITS SHIFTED
	JBE	@MATH1@_NORD40  ;AND IF SO QUIT
	MOV	SI,@@SFAC-2
	MOV	CX,7  ;7 BYTES TO MOVE
	STD  ;SO FOLLOWING MOVB WILL DECREMENT
;REPEAT CX TIMES (THE MOVB)
 REP	MOVSB  ;MOVE
	MOV	byte [@@SDFACL-1],((0) and 0FFh)  ;ZERO OVERFLOW
	JMP	@MATH1@_NORD5  ;SEE IF MORE CASES
@MATH1@_NORD40: JBE	@MATH1@_NORD50  ;UNDERFLOW JUMP
	JMP	@MATH1@_@SROUND
@MATH1@_NORD50:
	JMP	@@SDZERO

; SUBTTL	 $NORMS  SINGLE PRECISION NORMALIZATION ROUTINE
;************************************************************

;       $NORMS  SINGLE PRECISION NORMALIZATION ROUTINE
;               $NORMS SHIFTS (BLDXAH) LEFT UNTIL THE SIGN
;               BIT OF (BL)IS 1. FOR EACH LEFT SHIFT
;               $NORMS WILL DECREMENT THE FAC
;               ONCE THIS PROCESS IS COMPLETE, $NORMS WILL
;               JUMP TO $ROUNS TO ROUND THE NUMBER AND
;               PACK IT INTO THE FAC BYTES.

;*************************************************************

@@SNORMS:
	MOV	BH,byte [@@SFAC]  ;EXPONENT TO BH
	MOV	CX,4
@MATH1@_NOR10:	OR	BL,BL  ;SEE IF SIGN BIT SET
	JS	@MATH1@_NOR20  ;IF SO NORMALIZATION COMPLETE
	JNZ	@MATH1@_NOR15  ;UPPER BYTE NON-ZERO
	SUB	BH,((8) and 0FFh)  ;CAN WE SUBTRACT 8 W/O UNDERFLOW?
	JBE	@MATH1@_NOR17
	MOV	BL,DH
	MOV	DH,DL
	MOV	DL,AH
	XOR	AH,AH  ;CLEAR OVERFLOW BYTE
	LOOP	@MATH1@_NOR10
	JZ	@MATH1@_NOR17  ;UNDERFLOW!
@MATH1@_NOR15:
	CLC  ;CLEAR CARRY FLAG [CF]
	RCL	AH,1  ;SHIFT OVERFLOW BYTE LEFT.
	RCL	DX,1  ;SHIFT LOWER MANTISSA WORD LEFT
	RCL	BL,1  ;SHIFT HIGH MANTISSA BYTE LEFT
@MATH1@_NOR16:	DEC	BH  ;DECREMENT EXPONENT
	JNZ	@MATH1@_NOR10  ;CONTINUE UNLESS UNDERFLOW
@MATH1@_NOR17:	JMP	@MATH1@_@SZERO  ;ZERO THE FAC AND RETURN
@MATH1@_NOR20:	MOV	byte [@@SFAC],BH  ;UPDATE EXPONENT
	JMP	@MATH1@_@SROUNS

; SUBTTL $POLY	 SINGLE PRECISION POLYNOMIAL EVALUATOR
;*********************************************************

;       $POLY   EVALUATES THE POLYNOMIAL:
;                       P(X)=C0+C1X+C2X2+...+CNXN
;               THE EVALUATION IS ACCOMPLISHED VIA HORNER'S
;               RULE (SEE "THE ART OF COMPUTER PROGRAMMING"
;               VOL.2 PP423, BY KNUTH)
;       $POLYX  PERFORMS THE EVALUATION X(P(X**2)) ON THE
;               POLYNOMIAL MENTIONED ABOVE
;       CALLING SEQUENCE:       CALL $POLY
;               OR              CALL    $POLYX
;               WITH X STORED IN THE $FAC AND (BX)
;               POINTING TO THE FOLLOWING:
;                                       N+1
;                                       CN
;                                       CN-1
;                                       .
;                                       .
;                                       .
;                                       C0

;***********************************************************

@MATH1@_@SPOLYX:
	MOV	DX,word [@@SFACLO]  ;FETCH LOW BYTES
	MOV	BP,word [@@SFACM1]  ;AND HIGH BYTES
	PUSH	DX  ;SAVE X ON THE STACK
	PUSH	BP
	PUSH	BX  ;SAVE COEFFICIENT POINTER
	MOV	BX,BP  ;(BXDX)=X
	CALL	@@SFMULS  ;FORM X**2
	POP	BX  ;RECALL COEFFICIENT POINTER
	CALL	@MATH1@_@SPOLY  ;FORM P(X**2)
	POP	BX  ;FETCH X TO REGISTERS
	POP	DX
	JMP	@@SFMULS

@MATH1@_@SPOLY:	CLD  ;9-Aug-82/MLC - Good for LODC, MOVW,
;and MOVW down to POL10.
	MOV	SI,BX  ;SO WE CAN USE STRING MOVES
;MUST FETCH FROM THE CODE SEG
	lods byte [cs:si]  ;FETCH NUMBER OF COEFFICIENTS
	CBW  ;(AH)=0
	PUSH	AX  ;PUSH NUMBER ELEMENTS ON STACK
	PUSH	word [@@SFACM1]  ;SAVE THE FAC ON THE STACK
	PUSH	word [@@SFACLO]
	MOV	DI,@@SFACLO
;WANT TO FETCH COEFF FROM
	movs word [es:di],word [cs:si]
;FETCH FROM CODE SEGMENT
	movs word [es:di],word [cs:si]
@MATH1@_POL10:
	POP	DX  ;FETCH LOW X
	POP	BX  ;FETCH HIGH X
	POP	AX  ;RECALL COEFFICIENT COUNTER
	DEC	AX  ;DECREMENT
	JZ	@MATH1@_POL30  ;JUMP WHEN COMPLETE
	PUSH	AX  ;SAVE COUNTER
	PUSH	BX  ;SAVE X ON THE STACK
	PUSH	DX
	PUSH	SI  ;SAVE POINTER TO COEFFICIENTS
	CALL	@@SFMULS  ;MULTIPLY BY X
	POP	SI  ;FETCH COEFFICIENT POINTER
	CLD  ;9-Aug-82/MLC - Good for next two
;LODWs.
;MUST FETCH FROM CODE SEGMENT
	lods word [cs:si]  ;FETCH LOW WORD
	XCHG	AX,DX
;MUST FETCH FROM CODE SEGMENT
	lods word [cs:si]  ;FETCH HIGH WORD
	XCHG	AX,BX
	PUSH	SI  ;SAVE COEFFICIENT POINTER
	CALL	@@SFADDS  ;ADD IT IN
	POP	SI  ;GET POINTER BACK
	JMP	@MATH1@_POL10
@MATH1@_POL30:  ;CLEAR THE STACK
	RET

; SUBTTL	 $PUF	 PRINT-USING FOR FLOATING POINT NUMBERS
;**************************************************************

;       $PUF    THIS ROUTINE ACCEPTS EITHER SINGLE OR DOUBLE
;               PRECISION FLOATING VALUES AND FORMATS THEM
;               ACCORDING TO INPUT FORMATS. BOTH FIXED AND
;               "E" TYPE FORMATS ARE PRODUCED BY THIS CODE
;       CALLING SEQUENCE:       CALL    $PUF
;               WITH FLOATING POINT VALUE IN THE FAC, (BX) POINTING
;               TO THE NEXT PRINT POSITION IN THE OUTPUT BUFFER
;               AND FORMAT SPECIFICATIONS IN AX, AND CX.
;               $FMTAX LOADED INTO (AX) WILL CONTAIN COMMA COUNT
;               IN (AH) AND THE FOLLOWING FORMAT IN (AL):
;               BIT     7       =0 FREE FORMAT OUTPUT, NUMBER DICTATES
;                               OUTPUT FORMAT
;                               =1 PRINT USING OUTPUT. THE REMAINDER OF
;                               (AL) AND (CX) DICTATE HOW THE NUMBER IS
;                               TO BE PRINTED
;                       6       IF =1 GROUP THE DIGITS IN THE INTEGER
;                               PART IN GROUPS OF THREE AND SEPARATE
;                               WITH COMMAS.
;                       5       IF =1 FILL THE LEADING SPACES IN THE
;                               FIELD WITH ASTERISKS "*"
;                       4       IF =1 OUTPUT THE NUMBER WITH A FLOATING
;                               DOLLAR SIGN "$"
;                       3       IF =1 PRINT THE SIGN OF THE NUMBER WITH
;                               A PLUS "+" IF POSITIVE INSTEAD OF A SPC
;                       2       IF =1 PRINT THE SIGN AFTER THE NUMBER
;                       1       UNUSED
;                       0       IF =1 PRINT THE NUMBER IN SCIENTIFIC
;                               NOTATION AND IGNORE BIT 6.
;                               IF =0 USE FIXED POINT NOTATION.
;               $FMTCX WILL HAVE THE FOLLOWING FORMAT LOADED IN (CX)
;               (CH)    NUMBER PLACES IN FIELD TO LEFT OF DECIMAL POINT
;                       (DOES NOT INCLUDE THE DECIMAL POINT)
;               (CL)    NUMBER PLACES IN THE FIELD TO THE RIGHT OF THE
;                       DECIMAL POINT (INCLUDES DECIMAL POINT)

;****************************************************************

@MATH1@_@SPUF:
	PUSH	BX  ;SAVE OUTPUT BUFFER POINTER
	SHR	AL,1  ;CF=1 IF "E" FORMAT DESIRED
	JNB	@MATH1@_PUF10  ;IF FIXED PROCEED
	JMP	@MATH1@_@SPUFE  ;GO DO IT
@MATH1@_PUF10:
;******************************************************************
;KNOW THAT A FIXED FORMAT IS DESIRED. THE FOLLOWING ANALYSIS WILL
;BE PERFORMED:  (1) SEE IF NO. IS .GE. 10^16 , AND IF SO
;GO PRINT WITH $FOUT AND INSERT A LEADING "%". (2) BRACKET THE
;PRINTABLE DIGITS IN THE INTEGER PART OF THE NUMBER WITH $FOTNV
;(3) SEE IF LEADING ZEROS ARE REQUIRED(THE POSITIONS SPECIFIED
;TO THE LEFT OF THE DECIMAL POINT ARE MORE THAN THE AVAILABLE
;DIGITS TO LEFT OF DECIMAL POINT). (4) SEE IF THE SUM OF THE DIGITS
;ON THE LEFT PLUS THOSE ON THE RIGHT ARE LESS THAN THE AVAILABLE
;DIGITS,I.E. WE HAVE MORE PRINTABLE DIGITS THAN REQUIRED. IF THIS
;IS THE CASE WE MUST SHIFT THE NUMBER RIGHT SO THAT WE CAN ROUND IT
;AT THE CORRECT POSITION. (5) PUT IN THE PRINTABLE DIGITS. (6) SEE
;IF TRAILING ZEROS ARE REQUIRED(SPECIFIED DIGITS TO THE RIGHT
;WERE IN EXCESS OF DIGITS AVAILABLE)
;********************************************************************
	MOV	BX,@MATH1@_@SDP16  ;WILL FIRST SEE IF NO. TOO LARGE
	CALL	@MATH1@_@SMOVBF  ;NO. MOVED TO DBUFF FOR COMPARISON
;(IT WAS PREVIOUSLY IN CODE SEGMENT)
	CALL	@MATH1@_@SVCOMP  ;(FAC)-10^16(CF=1 IF OK)
	JB	@MATH1@_PUF30  ;JUMP IF SMALL ENOUGH TO PROCESS
;******************************************************************
;NO. WAS TOO LARGE TO PRINT WITH FIXED FORMAT. MUST PRINT IN FREE-
;FORMAT WITH $FOUT AND INSERT A LEADING "%" TO INDICATE IT OVERFLOWED
;THE SPECIFIED PRINT FIELD
;*******************************************************************
	POP	BX  ;RECALL PRINT BUFFER POINTER
	CALL	@MATH1@_@SFOUT  ;PRINT IN FREE-FORMAT
	DEC	BX  ;POINT TO POSITION 1
	MOV	byte [BX+0],(("%") and 0FFh)  ;PUT IN OVERFLOW INDICATOR
	RET  ;DONE
@MATH1@_PUF30:
;********************************************************************
;ALL WE KNOW AT THIS POINT IS THAT IT IS POSSIBLE TO PRINT THE
;NUMBER WITH A FIXED FORMAT, DO NOT KNOW THE SPECIFIED FIXED FORMAT
;IS SUFFICIENT. WHAT WE WILL DO IS FORMAT THE NUMBER IN FIXED FORMAT
;AND THEN JUMP TO $PUFXE AND LET HIM DETERMINE IF THE NUMBER WAS
;WITHIN THE SPECIFIED FORMAT.
;********************************************************************
	CALL	@@SGETYP  ;DETERMINE TYPE
	MOV	CH,((16) and 0FFh)  ;ASSUME DOUBLE PREC. (16 PRINTABLE POS)
	JNB	@MATH1@_PUF40

	MOV	CH,((7) and 0FFh)  ;7 print positions if single precision

@MATH1@_PUF40:	CALL	@@SSIGNS  ;SEE IF NO. IS ZERO
	JZ	@MATH1@_PUF50  ;IF SO DON'T CALL $FOTNV
	CALL	@MATH1@_@SFOTNV  ;BRACKET NO. SO ALL PRINTABLE DIGITS
;IN THE INTEGER PART OF THE NUMBER AND
;RETURN COMPLEMENTING EXPONENT IN (AL)
;AND SF=1 IF THIS EXPONENT IS NEG.
;(THERE ARE DIGITS TO RIGHT OF D.P)
@MATH1@_PUF50:	POP	BX  ;GET OUTPUT BUFFER POINTER BACK
	JS	@MATH1@_PUF80  ;GO PRINT NO. WITH DIGITS TO RIGHT
;OF DECIMAL POINT
;*********************************************************************
;KNOW AT THIS POINT WE HAVE A NUMBER LESS THAN 10^16 THAT HAS NO
;PRINTABLE DIGITS TO RIGHT OF THE DECIMAL POINT. THEREFORE WE HAVE
;TO PUT IN LEADING ZEROS IF THE SPECIFIED PRINT POSITIONS TO THE LEFT
;OF THE DECIMAL POINT ARE MORE THAN THE PRINTABLE POSITIONS (CH)
;AND THE POSITIVE EXPONENT IN (AL)
;********************************************************************
	MOV	DL,AL  ;SAVE THIS POSITIVE EXP. FOR LATER
	ADD	AL,CH  ;THIS IS NECESSARY PRINT POSITIONS
;TO ACCOMODATE THIS NUMBER.
	SUB	AL,byte [@@SFMTCX+1]  ;SUBTRACT DIGITS TO LEFT
	JNS	@MATH1@_PUF60  ;NO LEADING ZEROS REQUIRED
	NEG	AL  ;MUST MAKE (AL) POSITIVE FOR $FOTZ
	CALL	@MATH1@_@SFOTZ  ;PUT IN (AL) LEADING ZEROS
@MATH1@_PUF60:	XOR	CL,CL  ;ZERO CREATED ZEROS
	CALL	@MATH1@_DPCOM  ;SET-UP DECIMAL POINT AND COMMA CT.
	PUSH	word [@@SFMTCX]  ;SAVE DECIMAL POINT INFO.
	PUSH	DX  ;SAVE EXPONENT
	CALL	@MATH1@_@SFOTCV  ;CONVERT THE BINARY NO. TO ASCII DIGITS
;NOTE THAT $FOTCV WILL ONLY CONVERT
;THE PRINTABLE DIGITS. IF THERE WAS A
;NON-ZERO EXPONENT AS WELL WE MUST
;INSERT SOME ZEROS PRIOR TO THE DECIMAL
;POINT. FURTHER WE MUST PAY ATTENTION
;TO OUR COMMA COUNT WHILE INSERTING
;THESE ZEROS.
	POP	DX  ;RECALL EXPONENT
	POP	word [@@SFMTCX]  ;RECALL DECIMAL POINT INFO.
	PUSH	word [@@SFMTCX]  ;SAVE DESIRED POSITIONS LEFT/RT.
	XOR	AL,AL  ;WANT DL IN AL WITH APPROPRIATE SIGNS
	OR	AL,DL  ;DL=EXPONENT
	JZ	@MATH1@_PUF70  ;IF NO ZEROS PRIOR TO D.P. JUMP
	CALL	@MATH1@_@SFOTZC  ;PUT IN ZEROS AND PAY ATTENTION TO
;COMMA COUNT.
	CALL	@MATH1@_@SFOTED  ;PUT IN DECIMAL POINT
@MATH1@_PUF70:	POP	word [@@SFMTCX]  ;RECALL DESIRED POSITIONS LEFT/RT.
	PUSH	word [@@SFMTCX]  ;AND SAVE AGAIN
	MOV	AL,byte [@@SFMTCX]  ;FETCH NO. POSITIONS TO RT. OF D.P.
	JMP	@MATH1@_@SPUIZ  ;GO PUT IN ANY REQUIRED TRAILING ZEROS
;AND CHECK TO ASSURE FIELD SPECS. MET
@MATH1@_PUF80:
;********************************************************************
;AT THIS POINT WE KNOW WE HAVE PRINTABLE DIGITS TO THE RIGHT OF THE
;DECIMAL POINT . WE KNOW THIS BECAUSE $FOTNV WAS CALLED TO BRACKET
;THE NO. SUCH THAT THE PRINTABLE DIGITS WERE IN THE INTEGER PART
;OF THE NUMBER AND THE COMPLEMENTING EXPONENT WAS IN (AL). FURTHER
;SF=1 WAS SET TO INDICATE (AL) WAS NEGATIVE.
;WE FURTHER NEED TO DETERMINE IF WE NEED TO ROUND SOMEWHERE
;WITHIN THE PRINTABLE DIGITS. THIS WILL BE THE CASE IF THE
;DIGITS TO BE PRINTED TO THE RIGHT IS LESS THAN THOSE AVAILABLE
;TO THE RIGHT. (AL) HAS THOSE AVAILABLE TO THE RIGHT, $FMTCX HAS
;THOSE DESIRED.
;***************************************************************
	MOV	DL,AL  ;SAVE THE COMPLEMENTING EXPONENT
	MOV	AL,byte [@@SFMTCX]  ;FETCH DIGITS DESIRED TO RIGHT
	OR	AL,AL  ;IF NON-ZERO MUST SUBTRACT 1
;BECAUSE DECIMAL POINT INCLUDED
	JZ	@MATH1@_PUF90  ;PROCEED IF NO DIG. TO RT. DESIRED
	DEC	AL  ;TAKE OUT FOR DECIMAL POINT COUNT
@MATH1@_PUF90:	MOV	DH,AL  ;SAVE DESIRED DIGITS TO RIGHT COUNT
	ADD	AL,DL  ;SUBTRACT DIGITS AVAILABLE TO RT.
;(THIS IS A SUBTRACT BECAUSE (DL) IS
;THE NEGATIVE TO DIGITS TO RT.)
	MOV	CL,AL  ;WILL NEED THIS FOR LATER. IT
;IS THE NEGATIVE OF THE NUMBER
;OF DIGITS WE ARE ABOUT TO SHIFT
;OFF TO THE RIGHT
	JS	@MATH1@_PUF100  ;JUMP IF INTERNAL ROUNDING NECESSARY
	XOR	AL,AL  ;WILL NEED ALL PRINTABLE DIGITS
	MOV	CL,AL  ;NO DIGITS SHIFTED OFF
	JMP	@MATH1@_PUF110  ;DO NOT NEED TO DIVIDE IF POSITIVE
@MATH1@_PUF100: PUSH	AX
	PUSH	CX  ;SAVE GENERATED LEADING ZEROS
	PUSH	DX
	PUSH	BX
	CALL	@MATH1@_@SDIV10  ;NEED TO ELIMINATE EXCESS PRINTABLE
	POP	BX
	POP	DX
	POP	CX  ;RECALL GENERATED LEADING ZEROS
	POP	AX  ;RECALL EXCESS DIGITS
	INC	AL  ;BECAUSE AL WAS ORIGINALLY NEGATIVE
	JS	@MATH1@_PUF100  ;CONTINUE FOR INTERNAL ROUNDING
	MOV	AH,CL  ;WILL NEED CREATED LEADING ZEROS
;LATER
@MATH1@_PUF110:
	MOV	AL,DL  ;GET NEGATIVE EXPONENT
	SUB	AL,CL  ;ADD CREATED ZEROS
	ADD	AL,CH  ;IF SF=1 THEN NO DIGITS TO LEFT
	JNS	@MATH1@_PUF120  ;JUMP IF DIGITS TO LEFT OF DECIMAL PT
;******************************************************************
;WE KNOW HERE THAT THE ENTIRE PRINTABLE DIGITS GO TO THE RIGHT OF
;THE DECIMAL POINT. IF DIGITS WERE REQUESTED TO THE LEFT THEN WE
;NEED TO INSERT LEADING ZEROS
;********************************************************************
	MOV	AL,byte [@@SFMTCX+1]  ;DESIRED LEADING DIGITS
	CALL	@MATH1@_@SFOTZ  ;INSERT (AL) LEADING ZEROS
	MOV	byte [BX+0],((".") and 0FFh)  ;PUT IN DECIMAL POINT
	MOV	word [@@SDPADR],BX  ;*** Save DP position for $FOTED, etc. ***
	INC	BX  ;NEXT BUFFER POSITION
	XOR	CL,CL  ;COMMA COUNT TO ZERO
;**********************************************************
;OK WE'VE PUT IN THE REQUIRED LEADING ZEROS PRIOR
;TO THE DECIMAL POINT. WE MAY FURTHER NEED TO PUT IN A FEW
;AFTER THE DECIMAL POINT. WE KNOW THAT THE EXPONENT IS
;GREATER IN ABSOLUTE VALUE THAN THE NO. OF PRINTABLE DIGITS.
;THE NUMBER OF LEADING ZEROS REQUIRE HERE THEN IS ABS.
;VALUE OF THE EXPONENT LESS PRINTABLE DIGITS
;**********************************************************
	MOV	AL,DH  ;Get number of digits after decimal point
	SUB	AL,CH  ;Subtract number that will be printed by $FOTCV
	CALL	@MATH1@_@SFOTZ  ;PUT IN (AL) LEADING ZEROS
	XOR	CX,CX  ;*** No longer need comma & decimal info ***
	PUSH	DX  ;*** 8-Mar-82/ngt Fix                    ***
	PUSH	word [@@SFMTCX]  ;*** Balance number of PUSHes and POPs   ***
	JMP	@MATH1@_PUF140  ;GO PUT IN THE DIGITS
@MATH1@_PUF120:
;*******************************************************************
;WE KNOW HERE THAT THERE ARE DIGITS TO THE LEFT OF THE DEC.PT.
;WE NEED TO DETERMINE IF LEADING ZEROS ARE REQUIRED. THEY WILL BE
;REQUIRED IF THE SPECIFIED DIGITS TO THE LEFT IS GREATER THAN
;THE NUMBER OF PRINTABLE DIGITS LESS THOSE TO THE RIGHT. RECALL THAT
;EARLIER WE PUT THE NUMBER OF PRINTABLE DIGITS IN (CH). DUE TO THE
;ABOVE CODE WE MAY HAVE INCREASED THE NUMBER OF DIGITS AVAILABLE TO
;THE LEFT BECAUSE WE SHIFTED THE NUMBER RIGHT BRINGING IN LEADING
;ZEROS. FOR EXAMPLE: IF WE GOT HERE WITH THE NUMBER 12.78575 $FOTNV
;WOULD HAVE 1278575. IN THE FAC AND -5 IN (AL), IF FURTHER THE INPUT
;FORMAT HAD BEEN ########.## WE WOULD HAVE SHIFTED THE NUMBER 3 DIGITS
;RIGHT FOR ROUNDING PURPOSES LEAVING 1278.575 IN THE FAC AND -3 IN
;(CL). ONCE WE GO TO $FOTCV , HE SHALL PRODUCE THE DIGITS
;00012.79 SO THE FORMULA FOR LEADING ZEROS IS:
;LEADING ZEROS=DESIRED DIGITS-[(CH)+(DL)-(CL)]
;               =DESIRED DIGITS-(CH)-(DL)+(CL)
;OR AS IN THIS EXAMPLE,LEADING ZEROS=8-[7+(-5)-(-3)]=3
;*********************************************************************
	MOV	AL,byte [@@SFMTCX+1]  ;FETCH DESIRED DIGITS
	PUSH	DX  ;SAVE DIGITS TO RIGHT
	PUSH	word [@@SFMTCX]  ;SAVE DIGITS TO LEFT/RIGHT
	SUB	AL,CH  ;SUBTRACT PRINTABLE DIGITS
	SUB	AL,DL  ;ADD DIGITS TO RIGHT
	ADD	AL,CL  ;SUBTRACT CREATED LEADING ZEROS
	JS	@MATH1@_PUF130  ;IF NO LEADING ZEROS REQUIRED JUMP
	CALL	@MATH1@_@SFOTZ  ;PUT IN REQUIRED LEADING ZEROS
@MATH1@_PUF130: CALL	@MATH1@_DPCOM  ;SET UP DECIMAL POINT AND COMMA CTS.
@MATH1@_PUF140: PUSH	word [@@SFMTCX]  ;SAVE DECIMAL POINT INFO.
	CALL	@MATH1@_@SFOTCV  ;CONVERT FAC TO ASCII DIGITS AND
;INSERT INTO OUTPUT BUFFER. DECIMAL
;POINT AND COMMA COUNTS ARE IN
;(CH)&(CL) RESPECTIVELY
	POP	word [@@SFMTCX]  ;Retrieve the right and left counts.
;($FMTCX:=digits to right of decimal
;point plus one for the decimal point,
;$FMTCX+1:=digits to left of decimal
;point.)
	POP	AX  ;RECALL DIGITS TO LEFT
	POP	DX  ;RECALL DIGITS TO RIGHT
	TEST	byte [@@SFMTCX],((255) and 0FFh)  ;Is the right side count zero?
;(This count includes the point
;point itself.)
	JNZ	@MATH1@_PUF150  ;No, retain the decimal point.
;Go see if trailing zeroes are needed.
	MOV	BX,word [@@SDPADR]  ;Yes, get rid of the decimal point
;by backing up the pointer so the
	JMP	@MATH1@_@SPUFXE  ;GO DO FIX-UP
@MATH1@_PUF150:
;*****************************************************************
;WE NEED TO NOW DETERMINE IF TRAILING ZEROS ARE TO BE PRINTED
;THIS WILL BE THE CASE IF NO. DIGITS TO THE RIGHT (DL) IS LESS
;THAN THOSE REQUESTED (AL).
;****************************************************************
	ADD	AL,DL  ;SUBTRACT DIGITS TO THE RIGHT
	DEC	AL  ;BECAUSE DECIMAL POINT WAS INCLUDED
	JS	@MATH1@_PUF160  ;GO DO FIX-UP
	CALL	@MATH1@_@SFOTZ  ;PUT IN TRAILING ZEROS
@MATH1@_PUF160: JMP	@MATH1@_@SPUFXE  ;GO DO FIX-UP

@MATH1@_DPCOM:  ;ROUTINE TO SET UP DECIMAL POINT AND COMMA COUNTS
	MOV	AL,CH  ;FETCH PRINTABLE DIGITS
	ADD	AL,DL  ;SUBTRACT DIGITS TO RIGHT
	SUB	AL,CL  ;ADD CREATED ZEROS
	INC	AL  ;FOR SIGN
	MOV	CH,AL
@MATH1@_DPC10:	SUB	AL,((3) and 0FFh)  ;SUBTRACT OUT AL MULTIPLES OF 3
	JG	@MATH1@_DPC10
	ADD	AL,((3) and 0FFh)
	MOV	CL,AL  ;COMMA COUNT NOW SET
	MOV	AL,byte [@@SFMTAX]  ;FETCH FORMAT FLAGS
	AND	AL,((64) and 0FFh)  ;SEE IF COMMAS DESIRED
	JNZ	@MATH1@_DPC20
	MOV	CL,AL  ;ZERO COMMA COUNT
@MATH1@_DPC20:	RET

; SUBTTL	 $PUFOT  PRINT USING OUTPUT ROUTINE
;***************************************************************

;       $PUFOT  THIS ROUTINE PROVIDES TOP-LEVEL CONTROL OF THE
;               PRINT USING OUTPUT FUNCTION.
;       CALLING SEQUENCE:       CALL    $PUFOT
;               WITH NUMBER TO BE OUTPUT IN THE FAC AND FORMAT
;               SPECIFICATIONS IN (AL), AND (CX).(AL) IS SET AS
;               FOLLOWS:
;               BIT     7       =0 FREE FORMAT OUTPUT, NUMBER DICTATES
;                               OUTPUT FORMAT
;                               =1 PRINT USING OUTPUT. THE REMAINDER OF
;                               (AL) AND (CX) DICTATE HOW THE NUMBER IS
;                               TO BE PRINTED
;                       6       IF =1 GROUP THE DIGITS IN THE INTEGER
;                               PART IN GROUPS OF THREE AND SEPARATE
;                               WITH COMMAS.
;                       5       IF =1 FILL THE LEADING SPACES IN THE
;                               FIELD WITH ASTERISKS "*"
;                       4       IF =1 OUTPUT THE NUMBER WITH A FLOATING
;                               DOLLAR SIGN "$"
;                       3       IF =1 PRINT THE SIGN OF THE NUMBER WITH
;                               A PLUS "+" IF POSITIVE INSTEAD OF A SPC
;                       2       IF =1 PRINT THE SIGN AFTER THE NUMBER
;                       1       UNUSED
;                       0       IF =1 PRINT THE NUMBER IN SCIENTIFIC
;                               NOTATION AND IGNORE BIT 6.
;                               IF =0 USE FIXED POINT NOTATION.
;               (CH)    NUMBER PLACES IN FIELD TO LEFT OF DECIMAL POINT
;                       (DOES NOT INCLUDE THE DECIMAL POINT)
;               (CL)    NUMBER PLACES IN THE FIELD TO THE RIGHT OF THE
;                       DECIMAL POINT (INCLUDES DECIMAL POINT)

;****************************************************************

@PUFOUT:
@MATH1@_@SPUFOT:
	MOV	AH,AL  ;FETCH FORMAT SPECS.
	TEST	AH,((64) and 0FFh)  ;ZF=0 IF COMMAS DESIRED
	MOV	AH,((3) and 0FFh)  ;IF COMMAS DESIRED
	JNZ	@MATH1@_PFO05  ;JUMP IF COMMAS DESIRED
	XOR	AH,AH  ;COMMAS NOT DESIRED
@MATH1@_PFO05:	MOV	word [@@SFMTAX],AX  ;SAVE COMMA COUNT AND PFORMAT SPECS
	MOV	word [@@SFMTCX],CX  ;SAVE POSITIONS TO RT./LEFT
;OF DECIMAL POINT
	MOV	AH,AL  ;FOR TESTING
	MOV	BX,@@SFBUFF+1  ;FETCH BUFFER POINTER
	MOV	byte [BX+0],((" ") and 0FFh)  ;MOVE IN SPACE FOR POSSIBLE SIGN
	TEST	AH,((8) and 0FFh)  ;SEE IF "+" DESIRED
	JZ	@MATH1@_PFO10  ;JUMP IF NOT
	MOV	byte [BX+0],(("+") and 0FFh)  ;MOVE IN PLUS
@MATH1@_PFO10:	PUSH	BX  ;SAVE BUFFER POINTER
	CALL	@@SSIGNS  ;DETERMINE SIGN OF NUMBER
	POP	BX  ;RECALL BUFFER POINTER
	JNS	@MATH1@_PFO20  ;JUMP IF POSITIVE
	MOV	byte [BX+0],(("-") and 0FFh)  ;PUT IN MINUS SGN
	PUSH	BX  ;SAVE BUFFER PTR.
	CALL	@MATH1@_@SVNEG  ;NEGATE NO. SO WE WORK ONLY WITH
	POP	BX  ;RECALL BUFFER PTR.
@MATH1@_PFO20:	INC	BX  ;POINT TO NEXT BUFFER POSITION
	MOV	byte [BX+0],(("0") and 0FFh)  ;PUT IN ZERO IN CASE NO IS ZERO
	CALL	@@SGETYP  ;SET COND CODES ACCORDING TO TYPE
	MOV	AX,word [@@SFMTAX]  ;FETCH FORMAT SPECS
	MOV	CX,word [@@SFMTCX]
	JS	@MATH1@_PFO40  ;IF INTEGER JUMP
	JMP	@MATH1@_@SPUF  ;DO FLOATING POINT FORMATTING
@MATH1@_PFO40:	JMP	@MATH1@_@SPUI  ;PROCESS INTEGER

; SUBTTL	 $PUI	 PRINT USING FOR INTEGERS
;************************************************************

;       $PUI    PRINT THE INTEGER ACCORDING TO THE FORMATS IN
;               $FMTCX (NO PLACES TO LEFT/RIGHT OF DECIMAL POINT)
;               $FMTAX (AH)=0 OR 3 FOR COMMA INSERTION AND (AL)
;               HAS THE FOLLOWING MEANING:
;               BIT     7       =0 FREE FORMAT OUTPUT, NUMBER DICTATES
;                               OUTPUT FORMAT
;                               =1 PRINT USING OUTPUT. THE REMAINDER OF
;                               (AL) AND (CX) DICTATE HOW THE NUMBER IS
;                               TO BE PRINTED
;                       6       IF =1 GROUP THE DIGITS IN THE INTEGER
;                               PART IN GROUPS OF THREE AND SEPARATE
;                               WITH COMMAS.
;                       5       IF =1 FILL THE LEADING SPACES IN THE
;                               FIELD WITH ASTERISKS "*"
;                       4       IF =1 OUTPUT THE NUMBER WITH A FLOATING
;                               DOLLAR SIGN "$"
;                       3       IF =1 PRINT THE SIGN OF THE NUMBER WITH
;                               A PLUS "+" IF POSITIVE INSTEAD OF A SPC
;                       2       IF =1 PRINT THE SIGN AFTER THE NUMBER
;                       1       UNUSED
;                       0       IF =1 PRINT THE NUMBER IN SCIENTIFIC
;                               NOTATION AND IGNORE BIT 6.
;                               IF =0 USE FIXED POINT NOTATION.
;       CALLING SEQUENCE:       CALL    $PUI
;               WITH THE AFOREMENTIONED INFORMATION AVAILABLE

;******************************************************************

@MATH1@_@SPUI:	MOV	AX,word [@@SFMTAX]  ;FETCH PRINT DESCRIPTION DATA
	MOV	CL,AH  ;$FOTCI WILL NEED COMMA INFO
;IN (CL)
	MOV	CH,((6) and 0FFh)  ;AT MOST 6 PLACES PRIOR TO DECIMAL PT
	SHR	AL,1  ;SETS CF=1 IF "E" TYPE PRINT DESIRED
	MOV	DX,word [@@SFMTCX]  ;FETCH PLACES TO LEFT/RIGHT OF DEC. PT
	JNB	@MATH1@_PI10  ;IF NOT "E" FORMAT JUMP
	PUSH	BX  ;SAVE BUFFER POINTER
	PUSH	DX  ;SAVE PLACES TO LEFT/RIGHT OF DEC. PT
	CALL	@@SCSI  ;CONVERT THE INTEGER TO S.P.
	XOR	AL,AL  ;MUST SET ZF=1 FOR $PUFE
	POP	DX  ;FETCH PLACES TO LEFT /RIGHT OF D.P.
	JMP	@MATH1@_@SPUFE  ;GO FORMAT THE SINGLE PRECISION NO.
@MATH1@_PI10:	MOV	AL,DH  ;FETCH PLACES TO LEFT OF D.P.
	SUB	AL,((5) and 0FFh)  ;LET'S SEE IF LEADING ZEROS NEEDED
;*******************************************************************
;AT MOST 5 PRINT POSITIONS NEEDED FOR INTEGER (-32768,32767) SO IF
;DESIRED NO. PLACES ON LEFT IS MORE THAN 5 WE NEED TO FILL THESE
;POSITIONS WITH ASCII SPACES.
;******************************************************************
	JS	@MATH1@_PI20  ;JUMP IF LESS THAN 5
	CALL	@MATH1@_@SFOTZ  ;ZERO FILL (AL) POSITIONS
@MATH1@_PI20:	PUSH	DX  ;SAVE POSITIONS TO LEFT/RIGHT OF D.P.
	CALL	@@SFOTCI  ;CONVERT THE INTEGER TO ASCII DIGITS
;AND INSERT DECIMAL POINT AND COMMAS
;AS DESIRED
	POP	AX  ;RECALL NO. PLACESTO LEFT/RIGHT OF D.P.
	PUSH	AX  ;AND SAVE AGAIN
@MATH1@_@SPUIZ:	OR	AL,AL  ;IF 0 THEN NO DECIMAL POINT DESIRED
	JNZ	@MATH1@_PI30  ;IF DESIRED PROCEED
	DEC	BX  ;THIS WILL ELIMINATE DECIMAL POINT
@MATH1@_PI30:	DEC	AL  ;MAY NEED TO INSERT ZEROS TO RIGHT
;OF DECIMAL POINT.
	JS	@MATH1@_PI40  ;JUMP IF NOT DESIRED
	CALL	@MATH1@_@SFOTZ  ;PUT (AL) ASCII ZEROS IN BUFFER
	MOV	byte [BX+0],((0) and 0FFh)  ;RE-ESTABLISH END-OF-PRINT
@MATH1@_PI40:	POP	word [@@SFMTCX]  ;MAINTAIN DIGITS LEFT/RT. OF DP.
	JMP	@MATH1@_@SPUFXE  ;BE SURE FORMAT SPECS MET

; SUBTTL	 $RND	 PSEUDO-RANDOM NUMBER GENERATOR
;******************************************************************

;       $RND    GENERATE THE NEXT RANDOM NUMBER IN THE
;               SEQUENCE.

;       CALLING SEQUENCE:       CALL    $RND
;               WITH THE PREVIOUS RANDOM NUMBER IN $RNDX
;               AND DATA ITEMS $RNDA AND $RNDC SET PROPERLY
;       METHOD: LINEAR CONGRUENTIAL FROM VOL. 2 CHAPTER 3 OF
;               KNUTH - THE ART OF COMPUTER PROGRAMMING.
;               M=16,777,216 OR 2^24; [ A MOD 8 ]=5 AND
;               [ C MOD 8 ]=3
;               RND(N+1)=(RND(N)*A+C)MOD M

;               THE DATA ITEMS A AND C CORRESPOND TO $RNDA
;               AND $RNDC RESPECTIVELY AND WERE CAREFULLY
;               CHOSEN TO MEET THE RECIPE IN KNUTH.

;**************************************************************

@RND:
@MATH1@_@SRND:	CALL	@@SSIGNS  ;FIND WHICH MODE REQUESTED
	JZ	@MATH1@_OLDRN  ;RETURN PREVIOUS NO.?
	JNS	@MATH1@_RND10  ;GO DO NEW SEED
	MOV	AX,word [@@SFACLO]  ;FETCH NUMBER
	MOV	word [@@SRNDX],AX  ;AND INITIALIZE LAST RANDOM #
	MOV	AL,byte [@@SFAC-1]
	MOV	byte [@@SRNDX+2],AL  ;SO SEQUENCE STARTS AGAIN
@MATH1@_RND10:	MOV	AX,word [@@SRNDX]  ;FETCH LOW 16 BITS OF RNDX
	MUL	word [cs:@MATH1@_@SRNDA]  ;MULTIPLY BY LOW BITS OF A
	MOV	DI,AX  ;SAVE LOW 16 BITS
	MOV	CL,DL  ;SAVE UPPER 8 BITS
	MOV	AL,byte [cs:@MATH1@_@SRNDA+2]  ;FETCH UPPER 8 BITS OF A
	XOR	AH,AH  ;CLEAR UPPER AX
	MUL	word [@@SRNDX]  ;MULTIPLY BY LOW RNDX
	ADD	CL,AL  ;ADD TO UPPER 8 BITS
	XOR	AH,AH  ;CLEAR UPPER AX
	MOV	AL,byte [@@SRNDX+2]  ;FETCH HIGH 8 BITS OF RNDX
	MUL	word [cs:@MATH1@_@SRNDA]  ;MULTIPLY BY LOW 16 OF A
	ADD	CL,AL  ;ADD IN TO UPPER 8
	XOR	AH,AH  ;CLEAR OVERFLOW BYTE FOR NORM
	MOV	DX,word [cs:@MATH1@_@SRNDC]  ;FETCH LOW 16 OF C
	ADD	DX,DI  ;ADD IN LOW OF RND(N)*A
	MOV	BL,byte [cs:@MATH1@_@SRNDC+2]  ;FETCH HIGH OF C
	ADC	BL,CL  ;ADD WITH CARRY HIGH RND(N)*A
	MOV	byte [@@SFAC+1],AH  ;SIGN IS POSITIVE
	MOV	AL,((128) and 0FFh)  ;SO NORM WILL PRODUCE NO.
;LESS THAN 1
	MOV	byte [@@SFAC],AL
	MOV	word [@@SRNDX],DX  ;SAVE NEW RND(N+1)
	MOV	byte [@@SRNDX+2],BL
	MOV	AL,((4) and 0FFh)  ;MUST SET VALTP TO SINGLE PREC.
	MOV	byte [@@SVALTP],AL
	JMP	@@SNORMS
@MATH1@_NEWSD:  ;DETERMINE NEW RANDOM NO. SEED
	MOV	BX,@@SFBUFF  ;WILL SUM THE FIRST 32 WDS OF
	MOV	CX,32  ;RAM
@MATH1@_NEW10:	ADD	AX,word [BX+0]
	INC	BX
	INC	BX
	LOOP	@MATH1@_NEW10
	AND	AL,((254) and 0FFh)  ;BE SURE BIT 0=0 SO AS TO NOT
;MATCH RND0
	MOV	word [@@SRNDX],AX
	JMP	@MATH1@_RND10  ;GO PROCEED AS USUAL
@MATH1@_OLDRN:  ;RETURN THE PREVIOUS RANDOM NO.
	MOV	DX,word [@@SRNDX]  ;FETCH LOW 16 BITS
	MOV	BL,byte [@@SRNDX+2]  ;FETCH HIGH 8 BITS
	XOR	AX,AX  ;CLEAR OVERFLOW BYTE (AH)
	MOV	AL,((128) and 0FFh)  ;EXPONENT OF 0
	MOV	byte [@@SFAC],AL
	MOV	byte [@@SFAC+1],AH  ;POSITIVE SIGN
	JMP	@@SNORMS  ;GO NORMALIZE

; SUBTTL	 $ROUND  DOUBLE PRECISION ROUND ROUTINE
;*****************************************************************

;       $ROUND  ROUND THE DOUBLE PRECISION FLOATING POINT NUMBER IN
;               $FAC+1 THRU $DFACL-1.
;       CALLING SEQUENCE:       CALL    $ROUND
;               WITH NUMBER IN $FAC TO BE ROUNDED

;******************************************************************

@MATH1@_@SROUND:  ;DOUBLE PRECISION ROUND AND PACK
	MOV	BX,@@SDFACL-1
	ADD	word [BX+0],128  ;ADD TO HIGH BIT OV OVERFLOW BYTE
	MOV	CX,3  ;3 MORE BYTES TO LOOK AT POTENTIALLY
	JNB	@MATH1@_RDD20  ;IF CF=0 WE ARE DONE
@MATH1@_RDD10:	INC	BX
	INC	BX
	INC	word [BX+0]  ;IF THIS GETS ZF=1 THEN CARRY
	JNZ	@MATH1@_RDD20  ;FINISHED WHEN ZF=0
	LOOP	@MATH1@_RDD10
	INC	byte [@@SFAC]  ;MUST INCREMENT EXPONENT
	RCR	word [BX+0],1  ;SET HIGH BYTE TO 200
@MATH1@_RDD20:
	JZ	@MATH1@_RDD30  ;OVERFLOW HOOK
	TEST	byte [@@SDFACL-1],((255) and 0FFh)  ;SEE IF OVERFLOW BYTE ZERO
	JNZ	@MATH1@_@SROUNX
	AND	byte [@@SDFACL],((254) and 0FFh)  ;MAKE ANSWER EVEN
@MATH1@_@SROUNX:
	AND	byte [@@SFAC-1],((127) and 0FFh)  ;CLEAR SIGN BIT
	MOV	AL,byte [@@SFAC+1]  ;FETCH SIGN BYTE
	AND	AL,((128) and 0FFh)  ;CLEAR ALL BUT SIGN
	OR	byte [@@SFAC-1],AL  ;AND SET SIGN APPROPRIATELY
	RET
@MATH1@_RDD30:	JMP	@MATH1@_@SOVFLS

; SUBTTL	 $ROUNS  INTEL 8086 ROUNDING SUBROUTINE
;***********************************************************

;       $ROUNS  SINGLE PRECISION ROUNDING SUBROUTINE
;       CALLING SEQUENCE:       CALL    $ROUNS
;       ASSUMPTIONS:    (BLDXAH)WILL BE ROUNDED BY ADDING
;                       128 TO (AH) . IF CF (CARRY) IS SET
;                       AND (AH) IS NON-ZERO AFTER THIS
;                       ADDITION (BLDX) WILL BE INCREMENTED
;                       ONCE ROUNDING IS COMPLETE, LOGIC WILL
;                       CONTINUE INTO PAKSP FOR PACKING THE MANTISSA
;                       AND SIGN INTO THE FAC.

;**************************************************************

@MATH1@_@SROUNS: AND	AH,((224) and 0FFh)  ;CLEAR SUPERFLUOUS BITS
@MATH1@_@SROUNM: ADD	AH,((128) and 0FFh)  ;ADD TO MOST SIG. BIT OF AH
	JNB	@MATH1@_PAKSP  ;IF NO CARRY RETURN
	PUSHF  ;IF ZF=1 WANT TO ROUND TO EVEN
	INC	DX  ;IF ZF=1 MUST INCREMENT BL
	JNZ	@MATH1@_TSTEVN
	POPF  ;KNOW RESULT WILL BE EVEN
	INC	BL  ;IF ZF=1 MUST INCREMENT EXPONENT
	JNZ	@MATH1@_PAKSP
	STC  ;CF=1
	RCR	BL,1  ;THIS WILL SET HIGH BIT OF BL
	INC	byte [@@SFAC]  ;IF THIS CAUSES ($FAC)=0 WE HAVE
;OVERFLOW IN ROUNDING
	JNZ	@MATH1@_PAKSP
	JMP	@MATH1@_@SOVFLS
@MATH1@_TSTEVN: POPF  ;IF ZF=1 MUST CLEAR LOW BIT OF DL
	JNZ	@MATH1@_PAKSP  ;GO PACK THE FAC
	AND	DL,((254) and 0FFh)  ;CLEAR LOW BIT
@MATH1@_PAKSP:  ;PAK SINGLE PRECISION FAC. EXPONENT IS IN FAC,SIGN IN FAC+1
;THE MANTISSA IS IN (BLDX)
	MOV	SI,@@SFAC-3  ;LOAD ADDRESS OF $FAC IN SI
	MOV	word [SI+0],DX  ;MOVE LOWER MANTISSA WORD IN
	INC	SI  ;INCREMENT TO HIGH MANTISSA BYTE
	INC	SI
	MOV	BH,byte [@@SFAC+1]  ;FETCH SIGN
	AND	BX,32895  ;CLEAR ALL BUT SIGN IN BH SIGN IN BL
	OR	BL,BH  ;(BL) NOW IN CORRECT FORMAT
	MOV	byte [SI+0],BL  ;PUT INTO FAC-1
	RET

; SUBTTL	 $SIGD	 CALCULATE SIGNIFICANT DIGITS FOR $FOUT
;**************************************************************

;       $SIGD   WHEN $FOUT IS DETERMINING WHETHER TO PRINT
;               A NUMBER IN SCIENTIFIC NOTATION OR FIXED POINT
;               IT NEEDS TO KNOW THE NUMBER OF SIGNIFICANT DIGITS
;               IF THE NUMBER IS LESS THAN .01 .
;               PRIOR TO CALLING $SIGD, $FOUT HAS BRACKETED THE
;               SIGNIFICANT DIGITS VIA $FOUNV. THE NUMBER IN THE
;               FAC WILL BE AXXXXXX OR AXXXXXXXXXXXXXXX WHERE A IS
;               NON-ZERO. $SIGD'S JOB IS TO DETERMINE HOW MANY OF
;               THESE X'S STARTING FROM THE RIGHT ARE ZERO
;               PRIOR TO A NON-ZERO X. FOR EACH ZERO X, $SIGD WILL
;               INCREMENT (CL).
;       CALLING SEQUENCE:       CALL    $SIGD

;*******************************************************************

@MATH1@_@SSIGD:  ;(CL)=(CL)+1 FOR EACH ZERO DIGIT STARTING FROM
;THE RIGHT . ASSUMES $FOUNV HAS PREVIOUSLY OPERATED.
	MOV	SI,CX  ;SAVE CX
	CALL	@@SVPSHF  ;PUSH EITHER 4 OR 8 BYTES OF $FAC
;ON THE STACK ACCORDING TO $VALTP
	MOV	CX,SI  ;MUSU MAINTAIN (CL)
	PUSH	CX
;**************************************************************
;FIRST THING WE'LL DO IS ROUND THE FAC AND MAKE SURE WE
;STILL HAVE AN INTEGER.
;***************************************************************
;*****************************************************************
;IF WE ALREADY HAVE AN EXACT INTEGER DON'T WANT TO ADD .5 HERE
;*****************************************************************
	CALL	@@SGETYP
	JB	@MATH1@_SI31  ;JUMP IF SINGLE PREC
	CMP	byte [@@SFAC],((184) and 0FFh)  ;IF EQUAL OR SF=0 THEN INTEGER ALREADY
	JNS	@MATH1@_SI20  ;DON'T ADD .5
	JMP	@MATH1@_SI32  ;PROCESS FAC NORMALLY
@MATH1@_SI31:	CMP	byte [@@SFAC],((152) and 0FFh)  ;IF SF=0 THEN INTEGER ALREADY
	JNS	@MATH1@_SI20
@MATH1@_SI32:	CALL	@MATH1@_@SVADDH  ;ADD .5 TO FAC
	CALL	@@SVINT  ;MAKE SURE WE STILL HAVE AN INTEGER
@MATH1@_SI20:
	MOV	BX,@@SZLO  ;FETCH ADDRESS OF Z INTO (BX)
	CALL	@MATH1@_@SVMVMF  ;MOVE FAC TO Z , Z=INT(FAC+.5)
	POP	CX  ;GET (CL) BACK
@MATH1@_SI30:	PUSH	CX  ;SAVE CX FOR LATER
	MOV	DI,@@SZ1LO  ;GET ADDRESS OF Z1
	MOV	BX,@@SZLO  ;GET ADDRESS OF Z
	CALL	@MATH1@_@SVMOVM  ;Z1=Z
	MOV	BX,@@SZLO  ;FETCH ADDRESS OF Z
	CALL	@MATH1@_@SVMVFM  ;MOVE Z TO FAC
	CALL	@MATH1@_@SDIV10  ;FAC=Z/10
	CALL	@@SVINT  ;FAC=INT(Z/10)
	MOV	BX,@@SZLO
	CALL	@MATH1@_@SVMVMF  ;Z=INT(Z/10)
	CALL	@MATH1@_@SMUL10  ;FAC=INT(Z/10)*10
	MOV	BX,@@SZ1-1  ;ADDRESS OF Z1-1
	CALL	@@SGETYP  ;NEED TO DECREMENT BX IF S.P.
	JNB	@MATH1@_SI35
	SUB	BX,4  ;NOW (BX) POINTS TO S.P.
@MATH1@_SI35:
	CALL	@MATH1@_@SVCMPM  ;COMPARE TO FAC
	POP	CX  ;GET SIGNIFICANT DIGIT COUNT BACK
	JNZ	@MATH1@_SI40  ;THROUGH WHEN NON-ZERO
